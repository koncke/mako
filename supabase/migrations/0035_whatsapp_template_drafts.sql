-- =============================================================================
-- 0035_whatsapp_template_drafts — Borradores de plantillas de WhatsApp
-- =============================================================================
-- Las plantillas APROBADAS viven en Meta (source of truth del status). Acá
-- guardamos los BORRADORES que se redactan/validan en la app antes de mandarlos
-- a aprobar, más metadata local: el resultado del validador de MaKo, la etapa
-- del funnel para filtrar, y el vínculo con la plantilla en Meta una vez enviada.
-- Estados: borrador → (enviar a Meta) → pending → approved | rejected.
-- RLS on sin políticas = solo server-side (service_role), igual que el resto.

begin;

create table if not exists whatsapp_template_drafts (
  id               bigint generated by default as identity primary key,
  name             text not null,                 -- minúsculas + guiones bajos (meta-safe)
  language         text not null default 'es_MX',
  category         text not null default 'marketing'
                     check (category in ('marketing','utility','authentication')),
  body             text not null default '',      -- cuerpo con {{var}}
  header           text,                          -- header TEXT opcional (<=60)
  footer           text,                          -- footer estático opcional (<=60)
  buttons          jsonb not null default '[]'::jsonb,  -- [{type,text,url?,phone_number?}]
  params           jsonb not null default '[]'::jsonb,  -- [{name, example}] (samples obligatorios para Meta)
  status           text not null default 'borrador'
                     check (status in ('borrador','pending','approved','rejected','paused','disabled')),
  meta_template_id text,                          -- id que devuelve Graph API al crear
  rejection_reason text,                          -- motivo de Meta si REJECTED
  validacion       jsonb,                         -- último output del validador MaKo {riesgo,razones,...}
  etapa            text,                          -- etapa del funnel para filtrar (espeja nutricion_secuencias.etapa)
  created_at       timestamptz not null default now(),
  updated_at       timestamptz not null default now(),
  unique (name, language)
);

create index if not exists idx_wa_tpl_drafts_status on whatsapp_template_drafts (status);
create index if not exists idx_wa_tpl_drafts_etapa  on whatsapp_template_drafts (etapa);

comment on table whatsapp_template_drafts is
  'Borradores de plantillas de WhatsApp: se redactan/validan en la app y se envían a aprobar a Meta. El status definitivo lo manda Meta (Graph API).';

alter table whatsapp_template_drafts enable row level security;

commit;
