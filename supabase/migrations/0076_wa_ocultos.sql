-- =============================================================================
-- 0076_wa_ocultos — ocultar conversaciones del WhatsApp no oficial
-- =============================================================================
-- Distinto de wa_bloqueados: "oculto" NO corta el envío ni la nutrición; solo
-- SACA la conversación del inbox (y por lo tanto de MaKo), para mensajes/chats
-- personales que no se quieren previsualizar. Se puede desocultar. A nivel app,
-- por teléfono, scopeado por workspace.

begin;

create table if not exists wa_ocultos (
  id           bigint generated by default as identity primary key,
  workspace_id bigint not null default 1 references workspaces(id) on delete cascade,
  telefono     text not null,                     -- normalizado (dígitos)
  lead_id      bigint references leads(id) on delete set null,
  created_at   timestamptz not null default now(),
  created_by   text                               -- email del que ocultó
);

-- Un teléfono se oculta UNA vez por workspace (target del ON CONFLICT del upsert).
create unique index if not exists uq_wa_ocultos_tel
  on wa_ocultos (workspace_id, telefono);

comment on table wa_ocultos is
  'Conversaciones ocultadas del inbox no oficial (no se muestran ni entran a MaKo). No corta el envío; es solo de visualización.';

alter table wa_ocultos enable row level security;

commit;
