-- =============================================================================
-- 0047_experimentos — Experimentos (la única verdad, con datos)
-- =============================================================================
-- Un experimento convierte una HIPÓTESIS (lenguaje natural) en una prueba
-- MEDIBLE: una métrica del funnel, una ventana de medición, un baseline y un
-- criterio de éxito. Mientras corre, su valor se mide EN VIVO contra los datos
-- reales (lib/experimentos.ts lee getMarketingWindow); no se cachea la serie.
-- Al cerrar, MaKo lee los datos del experimento y deja un APRENDIZAJE: la única
-- conclusión que el sistema declara como verdad, porque está respaldada por el
-- dato medido. En el resto del dashboard MaKo nunca concluye — sugiere abrir un
-- experimento.
--
-- estado:    propuesto | activo | cerrado | descartado
--   - propuesto  → idea de MaKo todavía sin arrancar (sin fecha_inicio)
--   - activo     → corriendo, midiéndose a diario contra el dato real
--   - cerrado    → tiene veredicto + aprendizaje (verdad con datos)
--   - descartado → se abandonó sin concluir
-- veredicto: validada | refutada | no_concluyente   (solo cuando estado=cerrado)
-- origen:    mako | manual
--
-- RLS on sin políticas = solo server-side (service_role), igual que el resto.
-- =============================================================================

begin;

create table if not exists experimentos (
  id              bigint generated by default as identity primary key,

  -- Hipótesis y qué cambia (en lenguaje natural)
  titulo          text not null default '',
  hipotesis       text not null default '',          -- la pregunta/apuesta original
  cambio          text,                              -- la intervención concreta a probar

  estado          text not null default 'activo',    -- propuesto|activo|cerrado|descartado
  origen          text not null default 'mako',      -- mako|manual

  -- Métrica medible (clave del catálogo en lib/experimentos.ts)
  metrica         text not null default 'cpl',       -- cpl|cpc|ctr|cac|agendamientos|...
  metrica_label   text,                              -- etiqueta humana (snapshot)
  direccion       text not null default 'subir',     -- subir|bajar  (qué cuenta como éxito)
  objetivo_valor  numeric,                           -- valor objetivo (si lo hay)
  criterio_exito  text,                              -- criterio en lenguaje natural

  -- Baseline medido al iniciar (ventana de igual largo previa a fecha_inicio)
  baseline_valor  numeric,
  baseline_desde  date,
  baseline_hasta  date,

  -- Ventana de medición
  ventana_dias    integer not null default 14,
  presupuesto_usd numeric,
  fecha_inicio    date,                              -- cuándo arrancó (null si propuesto)
  fecha_fin       date,                              -- objetivo de cierre = inicio + ventana

  -- Cierre (verdad con datos)
  veredicto       text,                              -- validada|refutada|no_concluyente
  resultado_valor numeric,                           -- valor medido al cerrar
  aprendizaje     text,                              -- la conclusión respaldada por el dato
  cerrado_at      timestamptz,

  -- IA / meta
  config          jsonb,                             -- propuesta estructurada completa de MaKo
  racional        text,                              -- por qué MaKo eligió esta métrica/ventana
  model           text,                              -- modelo usado al sugerir/cerrar

  created_at      timestamptz not null default now(),
  updated_at      timestamptz not null default now()
);

create index if not exists idx_experimentos_estado
  on experimentos (estado, created_at desc);

comment on table experimentos is
  'Experimentos del negocio: hipótesis → prueba medible → aprendizaje con datos. '
  'Llenada y mostrada en /experimentos. Es la única vista donde el sistema declara verdades; '
  'en el resto MaKo sugiere abrir un experimento en vez de concluir.';

alter table experimentos enable row level security;

commit;
