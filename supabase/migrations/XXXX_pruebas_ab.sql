begin;

-- Una fila por cosa que se prueba (una landing, una tarjeta «A/B TEST» de una automatización).
create table if not exists pruebas (
  id                 bigint generated by default as identity primary key,
  workspace_id       bigint not null references workspaces(id) on delete cascade,
  superficie         text not null check (superficie in ('landing', 'automatizacion', 'portada_mako', 'anuncios', 'vsl')),
  -- landing: {doc_id, version_base, seccion_id?} · automatización: {secuencia_id, nodo_id}
  lugar              jsonb not null default '{}'::jsonb,
  -- landing:<doc> / auto:<secuencia>: una prueba VIVA por lugar (el índice de abajo).
  clave_lugar        text not null check (char_length(clave_lugar) between 3 and 200),
  titulo             text not null default '',
  hipotesis          text not null default '',
  cambio             text,
  origen             text not null default 'dueno' check (origen in ('dueno', 'mako')),
  unidad             text not null check (unidad in ('lead', 'visitante')),
  -- La métrica que decide (lib/pruebas/metricas.ts), CONGELADA al crear: la lista exacta de destinos, si la pide.
  metrica            text not null,
  metrica_def        jsonb not null default '{}'::jsonb,
  -- [{metrica, tolerancia_rel}]: la final (agendó, compró) cuida que la cercana no gane a costa de ella.
  guardrails         jsonb not null default '[]'::jsonb,
  -- El plan, calculado ANTES de arrancar (lib/pruebas/volumen.ts): es el horizonte del juez.
  ventana_dias       integer not null check (ventana_dias between 0 and 60),
  tasa_base          numeric check (tasa_base is null or (tasa_base > 0 and tasa_base < 1)),
  mde_rel            numeric not null check (mde_rel > 0),
  n_por_rama         integer not null check (n_por_rama >= 1),
  min_dias           integer not null default 7 check (min_dias >= 0),
  max_dias           integer not null check (max_dias >= 1),
  -- Editar una rama o cambiar los pesos abre una época nueva: sólo cuentan los que entran después.
  epoca              integer not null default 1 check (epoca >= 1),
  epoca_at           timestamptz,
  -- «Que MaKo elija solo» (la tarjeta) o el piloto del Landing AI.
  auto_aplicar       boolean not null default false,
  estado             text not null default 'propuesta' check (estado in ('propuesta', 'corriendo', 'detenida', 'concluida', 'descartada', 'vencida', 'deshecha')),
  veredicto          text check (veredicto is null or veredicto in ('gana_variante', 'gana_control', 'da_lo_mismo', 'no_concluyente')),
  -- La rama (su clave) que recibe el 100 % al terminar.
  sirviendo          text check (sirviendo is null or sirviendo in ('A', 'B', 'C', 'D')),
  experimento_id     bigint references experimentos(id) on delete set null,
  -- La última lectura del cron, y por qué falló si falló (una lectura que falla NO decide).
  ultima_lectura_at  timestamptz,
  ultima_lectura_error text,
  propuesta_vence_at timestamptz,
  iniciada_at        timestamptz,
  concluida_at       timestamptz,
  created_at         timestamptz not null default now(),
  updated_at         timestamptz not null default now()
);
create unique index if not exists pruebas_una_viva_por_lugar on pruebas (workspace_id, clave_lugar) where estado in ('propuesta', 'corriendo');
create index if not exists pruebas_corriendo_idx on pruebas (estado) where estado in ('propuesta', 'corriendo');

-- Las ramas. A es el control («Sin cambio»): no se borra ni se edita.
create table if not exists prueba_variantes (
  id             bigint generated by default as identity primary key,
  prueba_id      bigint not null references pruebas(id) on delete cascade,
  workspace_id   bigint not null references workspaces(id) on delete cascade,
  clave          text not null check (clave in ('A', 'B', 'C', 'D')),
  es_control     boolean not null default false,
  nombre         text not null default '',
  peso           integer not null check (peso between 0 and 100),
  -- landing: la foto armada (`armarFoto`) · automatización: {nodo_destino}. La B es una foto inmutable.
  contenido      jsonb not null default '{}'::jsonb,
  firma          text,
  porque         text,
  autor          text not null default 'dueno' check (autor in ('dueno', 'ia')),
  activa         boolean not null default true,
  cortada_motivo text,
  cortada_at     timestamptz,
  unique (prueba_id, clave)
);

-- Quién vio qué. Una fila por unidad y por prueba: la que ya tiene rama la conserva siempre.
create table if not exists prueba_asignaciones (
  prueba_id     bigint not null references pruebas(id) on delete cascade,
  unidad        text not null check (char_length(unidad) between 1 and 200 and lower(unidad) <> 'desconocido'),
  variante      text not null check (variante in ('A', 'B', 'C', 'D')),
  workspace_id  bigint not null references workspaces(id) on delete cascade,
  epoca         integer not null,
  -- La hora del PEDIDO (no la del insert): el pageview puede llegar antes que la fila (crítica, punto 9).
  asignada_at   timestamptz not null,
  -- El estado de cada métrica de ESTADO al asignar, {"agendo": true, "pago": false}: sólo cuenta pasar de no a sí
  -- (crítica, punto 5). Por métrica, porque la que decide y un guardrail pueden ser las dos de estado.
  previo        jsonb,
  -- El PRIMER «sí» de cada métrica y su hora, congelados cuando se conocen: {"respondio": {"at": "…"}}. Por métrica, porque la
  -- que decide y un guardrail se miden a la vez («respondió» se reescribe al volver a entrar; «agendó» no tiene hora propia).
  resultados    jsonb not null default '{}'::jsonb,
  primary key (prueba_id, unidad)
);
create index if not exists prueba_asignaciones_epoca_idx on prueba_asignaciones (prueba_id, epoca);

-- Los números de cada día: quedan para auditar y nunca se recalculan hacia atrás.
create table if not exists prueba_lecturas (
  prueba_id    bigint not null references pruebas(id) on delete cascade,
  fecha        date not null,
  variante     text not null check (variante in ('A', 'B', 'C', 'D')),
  workspace_id bigint not null references workspaces(id) on delete cascade,
  epoca        integer not null,
  dia          integer not null,
  n            integer not null default 0,
  n_maduros    integer not null default 0,
  x            integer not null default 0,
  guardrails   jsonb,
  p_mejor      numeric,
  p_peor       numeric,
  perdida      numeric,
  lift_p5      numeric,
  lift_p95     numeric,
  primary key (prueba_id, fecha, variante)
);

-- El porqué de cada decisión, con el molde del Media Buyer: numeros = [{condicion, valor, porQue}].
create table if not exists prueba_historial (
  id           bigint generated by default as identity primary key,
  prueba_id    bigint not null references pruebas(id) on delete cascade,
  workspace_id bigint not null references workspaces(id) on delete cascade,
  at           timestamptz not null default now(),
  accion       text not null check (accion in ('propuesta', 'aprobada', 'arrancada', 'reiniciada', 'cortada', 'retractada', 'concluida', 'aplicada', 'detenida', 'deshecha', 'vencida', 'fallida')),
  quien        text not null default 'mako',
  porque       text,
  numeros      jsonb not null default '[]'::jsonb
);
create index if not exists prueba_historial_idx on prueba_historial (prueba_id, at desc);

alter table pruebas enable row level security;
alter table prueba_variantes enable row level security;
alter table prueba_asignaciones enable row level security;
alter table prueba_lecturas enable row level security;
alter table prueba_historial enable row level security;
revoke all on pruebas from anon, authenticated;
revoke all on prueba_variantes from anon, authenticated;
revoke all on prueba_asignaciones from anon, authenticated;
revoke all on prueba_lecturas from anon, authenticated;
revoke all on prueba_historial from anon, authenticated;

commit;
