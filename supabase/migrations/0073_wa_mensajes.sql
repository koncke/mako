-- =============================================================================
-- 0073_wa_mensajes — Espejo total de mensajes del WhatsApp NO oficial (Evolution)
-- =============================================================================
-- "Respaldo total" del PDF: nuestra DB es la fuente de verdad, no WhatsApp. Cada
-- mensaje (entrante del lead Y saliente que el dueño escribe desde el teléfono)
-- llega por el webhook messages.upsert y se guarda acá; la multimedia se baja a
-- un bucket propio. Si banean el número, el historial queda intacto y se puede
-- reenganchar mencionando los últimos acuerdos (plan de contingencia del PDF).
--
-- raw jsonb guarda el payload completo → nada se pierde aunque el parser cambie.

begin;

create table if not exists wa_mensajes (
  id             bigint generated by default as identity primary key,
  workspace_id   bigint not null default 1 references workspaces(id) on delete cascade,
  instance_name  text not null,
  chat_jid       text not null,                     -- remoteJid del chat/contacto
  telefono       text,                              -- número normalizado del contacto
  wa_message_id  text not null,                     -- key.id (dedup)
  from_me        boolean not null default false,    -- true = saliente (lo mandó la empresa)
  tipo           text,                              -- text|image|audio|video|document|sticker|otro
  texto          text,                              -- cuerpo o caption
  media_path     text,                              -- ruta en el bucket 'wa-media' (si hay media)
  media_mime     text,
  push_name      text,                              -- nombre que muestra WhatsApp
  lead_id        bigint references leads(id) on delete set null,
  wa_timestamp   timestamptz,                       -- messageTimestamp del mensaje
  raw            jsonb,                             -- payload completo (respaldo)
  created_at     timestamptz not null default now(),
  unique (workspace_id, wa_message_id)
);

create index if not exists idx_wa_mensajes_chat
  on wa_mensajes (workspace_id, chat_jid, wa_timestamp desc);
create index if not exists idx_wa_mensajes_lead
  on wa_mensajes (workspace_id, lead_id);

comment on table wa_mensajes is
  'Espejo total de mensajes del WhatsApp no oficial (Evolution). DB = fuente de verdad; media en bucket wa-media.';

alter table wa_mensajes enable row level security;

-- Bucket privado para la multimedia del WhatsApp no oficial (idempotente). El
-- path se prefija con workspace_id (el bucket no se scopea solo). Acceso solo
-- vía service_role → URLs firmadas.
insert into storage.buckets (id, name, public)
values ('wa-media', 'wa-media', false)
on conflict (id) do nothing;

commit;
