-- =============================================================================
-- 0075_wa_status_bloqueados — ticks de estado + bloqueo del WhatsApp no oficial (F4)
-- =============================================================================
-- (1) wa_mensajes.status: estado de entrega del SALIENTE para pintar los ✓✓, igual
--     que el oficial. Lo setea el envío ('sent') y lo sube el webhook messages.update
--     de Evolution ('delivered'/'read'/'failed').
-- (2) wa_bloqueados: contactos bloqueados en el canal no oficial. El motor de
--     nutrición NO les manda y la UI lo muestra. Evolution v2.3.7 no expone endpoint
--     de bloqueo (404), así que el bloqueo es a nivel app/CRM (por teléfono).

begin;

alter table wa_mensajes add column if not exists status text; -- sent | delivered | read | failed (solo salientes)

create table if not exists wa_bloqueados (
  id           bigint generated by default as identity primary key,
  workspace_id bigint not null default 1 references workspaces(id) on delete cascade,
  telefono     text not null,                     -- normalizado (dígitos)
  lead_id      bigint references leads(id) on delete set null,
  motivo       text,
  created_at   timestamptz not null default now(),
  created_by   text                               -- email del que bloqueó
);

-- Un teléfono se bloquea UNA vez por workspace (target del ON CONFLICT del upsert).
create unique index if not exists uq_wa_bloqueados_tel
  on wa_bloqueados (workspace_id, telefono);

comment on table wa_bloqueados is
  'Contactos bloqueados en el WhatsApp no oficial: el motor no les envía y el inbox lo muestra (bloqueo a nivel app, Evolution no expone endpoint).';

alter table wa_bloqueados enable row level security;

commit;
