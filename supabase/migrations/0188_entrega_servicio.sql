-- =============================================================================
-- 0188 — la ENTREGA de un servicio: las columnas del kanban de Customer Success
-- =============================================================================
-- Martín, textual (05/10/2026): «si un CLIENTE actual llega a X etapa de mi SERVICIO
-- (onboarding, hito 1, hito 2, o lo que sea que el usuario configure en su entrega de
-- servicio…), que le mandes una tarea al chat de customer success que implemente el
-- kanban y copie lo que ya tenemos en el CRM pero para la tab de Customer Success».
-- Y la aclaración que decide la forma de estas dos tablas: «Todo por producto, siempre,
-- justamente pueden tener muchos productos».
--
-- ORDEN DE DESPLIEGUE: **ANTES o JUNTO** con el deploy. Aditiva, y el código nuevo
-- (lib/entrega-servicio.ts) ya las lee. Ver AGENTS.md → «Toda migración decide su ORDEN
-- de despliegue».
--
-- ─────────────────────────────────────────────────────────────────────────────
-- ⚠️ POR QUÉ ESTO NO ES «OTRO EMBUDO DEL MISMO PRODUCTO»
-- ─────────────────────────────────────────────────────────────────────────────
-- Era la hipótesis razonable —reusar `funnels` y no agregar nada— y está MEDIDA como
-- falsa. Tres hechos que no se pueden tener a la vez:
--
--   · `leads.funnel_id` es UNA columna (migración 0181). Un lead vive en un embudo.
--   · Un cliente ES un lead ganado: no hay tabla de clientes (ver el encabezado de
--     app/customer-success/BarraClientes.tsx).
--   · La etapa del lead también es UNA: `pipeline_stage` + la derivada + `etapa_vista`.
--
-- Las dos etapas son SIMULTÁNEAS, no sucesivas: el mismo cliente es `ganado` en ventas
-- y `hito2` en entrega AL MISMO TIEMPO. Meterlo en un embudo de entrega lo SACARÍA del
-- tablero del CRM donde está ganado — o sea que el CRM perdería un cierre para que
-- Customer Success ganara una columna. Por eso la asignación vive en su propia tabla y
-- lo que se reusa del CRM es la FORMA del catálogo (`data jsonb`), no su almacenamiento.
--
-- ─────────────────────────────────────────────────────────────────────────────
-- LA CLAVE DE UNA ETAPA ES ESTABLE; EL RÓTULO SE EDITA APARTE
-- ─────────────────────────────────────────────────────────────────────────────
-- `cliente_entrega.etapa` guarda la CLAVE (`hito1`), nunca el rótulo. Es la lección de
-- ManyChat, que apunta a todo por nombre y lo admite roto en su propia documentación:
-- renombrar una etapa rompe el flujo en silencio. Acá el rótulo es decoración que vive
-- en `producto_entrega.data` y se puede cambiar sin tocar una fila de clientes.
--
-- Y tres cosas van a apuntar a esa clave, no una: en qué columna está cada cliente, el
-- disparador de una secuencia de mensajes (la sesión del Chatbot engancha
-- `enrolarPorEvento` en el choke point) y el historial del lead.
-- =============================================================================

begin;

-- ─────────────────────────────────────────────────────────────────────────────
-- EL CATÁLOGO: una fila por PRODUCTO con las etapas de su entrega
-- ─────────────────────────────────────────────────────────────────────────────
create table if not exists producto_entrega (
  id           bigint generated by default as identity primary key,
  workspace_id bigint not null default 1 references workspaces(id) on delete cascade,
  producto_id  bigint not null references productos(id) on delete cascade,
  -- `{ etapas: [{ key, label, tone, dot }] }`. MISMA forma que `funnels.data` (0170) a
  -- propósito: así el saneo se escribe una vez y el merge que impide que un tecleo del
  -- editor borre lo que no está en pantalla se hereda del mismo patrón.
  data         jsonb not null default '{}'::jsonb,
  -- ⚠️ `declarado` NO se deriva de que `data` tenga contenido. Una fila que nace con
  -- '{}'::jsonb es truthy en JS, así que un lector que mire el contenido leería
  -- «declarado» donde no se declaró nada — y entonces la pantalla no puede decir
  -- «todavía no configuraste la entrega de este producto» y muestra las etapas
  -- genéricas como si fueran una decisión del cliente. Es el síntoma que ya se pagó
  -- con los funnels: tres productos nuevos indistinguibles del embudo del negocio.
  declarado    boolean not null default false,
  created_at   timestamptz not null default now(),
  updated_at   timestamptz not null default now()
);
-- Único y NO parcial: es el target del ON CONFLICT del guardado del catálogo.
create unique index if not exists producto_entrega_uk on producto_entrega (workspace_id, producto_id);

comment on table producto_entrega is 'Las etapas de ENTREGA de un producto (las columnas del kanban de Customer Success). Una fila por workspace x producto; `declarado` separa «lo configuró» de «está viendo el default».';

alter table producto_entrega enable row level security;
revoke all on producto_entrega from anon, authenticated;

-- ─────────────────────────────────────────────────────────────────────────────
-- LA ASIGNACIÓN: en qué etapa de la entrega de CADA producto está cada cliente
-- ─────────────────────────────────────────────────────────────────────────────
-- ⚠️ `leads.producto_id` (0117) NO sirve para esto y es la confusión fácil: ese campo
-- es el producto con el que se CERRÓ la venta, y es uno. Acá hacen falta N, porque el
-- pedido es explícito: «pueden tener muchos productos». Un cliente que compró la
-- mentoría y después el servicio mensual está en DOS entregas a la vez, cada una con
-- sus propias etapas.
create table if not exists cliente_entrega (
  id           bigint generated by default as identity primary key,
  workspace_id bigint not null default 1 references workspaces(id) on delete cascade,
  -- El cliente ES un lead ganado. Si el lead se borra, su entrega se va con él: una
  -- tarjeta de kanban que apunta a un lead que no existe no se puede dibujar ni
  -- contar, y queda inflando el número de la columna para siempre.
  lead_id      bigint not null references leads(id) on delete cascade,
  producto_id  bigint not null references productos(id) on delete cascade,
  -- La CLAVE de la etapa, no su rótulo. Sin default a propósito: en qué columna está un
  -- cliente es un HECHO declarado por alguien, nunca una deducción. Un default acá
  -- haría que toda fila nueva afirmara «está en onboarding» sin que nadie lo dijera.
  etapa        text not null,
  -- Cuándo ENTRÓ a la etapa en la que está, para «hace cuánto que no se mueve». Es un
  -- campo propio y no `updated_at`: cambiar cualquier otra cosa de la fila no puede
  -- resetear el reloj de la columna, que es lo único que ese número mide.
  etapa_desde  timestamptz not null default now(),
  -- Quién la movió. Mismo vocabulario que `lead_audit.autor` ('CRM' una persona, 'MaKo'
  -- lo automático), así el chip del historial y este campo hablan del mismo actor.
  por          text not null default 'CRM',
  created_at   timestamptz not null default now(),
  updated_at   timestamptz not null default now()
);
-- Único y NO parcial: es el target del ON CONFLICT de moverClienteDeEtapa(), y además
-- es el candado que impide que dos pestañas dejen al mismo cliente en dos columnas del
-- mismo producto — que en un kanban se lee como un cliente duplicado.
create unique index if not exists cliente_entrega_uk on cliente_entrega (workspace_id, lead_id, producto_id);
-- La lectura del tablero es «todos los clientes del producto P agrupados por etapa».
create index if not exists idx_cliente_entrega_tablero on cliente_entrega (workspace_id, producto_id, etapa);

comment on table cliente_entrega is 'En qué etapa de la ENTREGA de cada producto está cada cliente (un lead ganado). Una fila por workspace x lead x producto: un cliente puede estar en varias entregas a la vez, y en ventas sigue siendo `ganado`.';

alter table cliente_entrega enable row level security;
revoke all on cliente_entrega from anon, authenticated;

commit;
