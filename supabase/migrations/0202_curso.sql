-- ── 1. Las clases ────────────────────────────────────────────────────────────
create table if not exists curso_clases (
  id           bigint generated by default as identity primary key,
  workspace_id bigint not null default 1 references workspaces(id) on delete cascade,
  producto_id  bigint not null references productos(id) on delete cascade,
  -- La CLAVE de la etapa de entrega (no su rótulo), igual que `cliente_entrega.etapa`.
  etapa        text not null,
  orden        int  not null default 0,
  titulo       text not null,
  -- Lo que ve el cliente arriba del video: el objetivo y los puntos. NUNCA el guion de
  -- grabación del programa viejo (`graba`, `puntos`, `atoro` nombraban a otros clientes).
  descripcion  text not null default '',
  tipo         text not null default 'clase'
               check (tipo in ('concepto', 'demostracion', 'clinica', 'clase', 'formulario')),
  minutos      int,
  -- El video. `ninguno` = todavía no está (la clase se ve igual: texto y tarea).
  video_tipo   text not null default 'ninguno'
               check (video_tipo in ('ninguno', 'archivo', 'youtube', 'vimeo', 'loom', 'drive', 'url')),
  video_url    text,          -- el link, para los tipos que son un link
  video_path   text,          -- la ruta en el bucket `curso-videos`, para 'archivo'
  -- La TAREA: la instrucción de llenado y, si hace falta, un formulario con campos tipados
  -- (el molde de `Campo` en lib/curso.ts). Sin campos y con instrucción = una respuesta libre.
  tarea        text not null default '',
  campos       jsonb not null default '[]'::jsonb,
  -- ¿Su tarea cuenta para cerrar la etapa? La etapa se completa cuando el cliente ENVIÓ todas
  -- las obligatorias (lib/curso.ts, `etapaCompleta`).
  obligatoria  boolean not null default false,
  -- De dónde salió, para que la carga sea idempotente ('planilla:0.3', 'catalogo:m1c3').
  origen       text,
  created_at   timestamptz not null default now(),
  updated_at   timestamptz not null default now()
);
create index if not exists idx_curso_clases_etapa on curso_clases (workspace_id, producto_id, etapa, orden);
create unique index if not exists curso_clases_origen_uk on curso_clases (workspace_id, producto_id, origen) where origen is not null;

comment on table curso_clases is 'Las clases del curso de un producto, colgadas de una etapa de su entrega (producto_entrega). Video (link o archivo del bucket curso-videos), tarea y formulario.';

-- ── 2. El avance de cada cliente en cada clase ───────────────────────────────
create table if not exists curso_progreso (
  id            bigint generated by default as identity primary key,
  workspace_id  bigint not null default 1 references workspaces(id) on delete cascade,
  lead_id       bigint not null references leads(id) on delete cascade,
  clase_id      bigint not null references curso_clases(id) on delete cascade,
  -- Lo más lejos que llegó en el video y cuánto dura. El % sale de estos dos, en el server:
  -- un reproductor puede mandar un evento sin duración (Panda ya lo hizo) y un % que llega
  -- armado del navegador es lo que el navegador quiera.
  segundos_max  numeric not null default 0,
  duracion_seg  numeric,
  pct           int not null default 0 check (pct between 0 and 100),
  visto_at      timestamptz,  -- el primer play
  -- Lo que contestó: `{respuesta: '…'}` para la tarea libre, `{campoId: valor}` para un formulario.
  valores       jsonb not null default '{}'::jsonb,
  estado        text not null default 'pendiente' check (estado in ('pendiente', 'enviada', 'aprobada')),
  enviada_at    timestamptz,
  aprobada_at   timestamptz,
  created_at    timestamptz not null default now(),
  updated_at    timestamptz not null default now()
);
create unique index if not exists curso_progreso_uk on curso_progreso (workspace_id, lead_id, clase_id);
create index if not exists idx_curso_progreso_lead on curso_progreso (workspace_id, lead_id);

comment on table curso_progreso is 'Cuánto vio cada cliente de cada clase y qué contestó en su tarea. Una fila por cliente x clase.';

-- ── 3. El acceso especial del cliente (su link personal) ─────────────────────
-- ⚠️ EL LINK NO SE GUARDA: es una firma (`c1.<ws>.<lead>.<version>.<hmac>`, lib/curso-acceso.ts).
-- Acá vive sólo lo que la firma no puede decir: la VERSIÓN vigente (revocar = subirla, y todos
-- los links viejos dejan de valer) y si se cortó. Así el link se puede volver a mandar en cada
-- mensaje sin guardar un secreto en texto plano.
create table if not exists curso_accesos (
  id                bigint generated by default as identity primary key,
  workspace_id      bigint not null default 1 references workspaces(id) on delete cascade,
  lead_id           bigint not null references leads(id) on delete cascade,
  version           int not null default 1,
  revocado_at       timestamptz,
  ingresos          int not null default 0,
  ultimo_ingreso_at timestamptz,
  creado_por        text,
  created_at        timestamptz not null default now()
);
create unique index if not exists curso_accesos_uk on curso_accesos (workspace_id, lead_id);

comment on table curso_accesos is 'El acceso del cliente a su portal del curso. El link es una firma con la version; revocar = subir la version.';

-- ── 4. Las llamadas de la entrega (para los mensajes de antes y después) ──────
-- ⚠️ NO SON `leads.junta_*`: ésas son las R1/R2 de VENTA, alimentan el no-show y los
-- recordatorios de venta. Una sesión de entrega anotada ahí pisaría la venta.
create table if not exists curso_sesiones (
  id                  bigint generated by default as identity primary key,
  workspace_id        bigint not null default 1 references workspaces(id) on delete cascade,
  lead_id             bigint not null references leads(id) on delete cascade,
  producto_id         bigint references productos(id) on delete set null,
  fecha               timestamptz not null,
  nota                text,
  -- Marcas de lo que ya salió: se escriben ANTES de mandar (compare-and-set), o dos corridas
  -- del cron mandan dos veces. Con el envío apagado se anota el motivo y no se miente.
  aviso_previo_at     timestamptz,
  aviso_posterior_at  timestamptz,
  aviso_motivo        text,
  created_at          timestamptz not null default now()
);
create index if not exists idx_curso_sesiones_fecha on curso_sesiones (workspace_id, fecha);
create index if not exists idx_curso_sesiones_lead on curso_sesiones (workspace_id, lead_id, fecha);

comment on table curso_sesiones is 'Las llamadas de la entrega de un cliente. De acá salen el mensaje del día antes y el de después.';

alter table curso_clases   enable row level security;
alter table curso_progreso enable row level security;
alter table curso_accesos  enable row level security;
alter table curso_sesiones enable row level security;
revoke all on curso_clases   from anon, authenticated;
revoke all on curso_progreso from anon, authenticated;
revoke all on curso_accesos  from anon, authenticated;
revoke all on curso_sesiones from anon, authenticated;

-- ── 5. El bucket de los videos subidos ───────────────────────────────────────
-- PRIVADO: el video se sirve detrás del link del cliente con una URL firmada de vida corta.
-- 2 GiB por archivo (debajo del tope global del plan) y sólo video. La subida va directo del
-- navegador a Storage con una URL firmada: una server action topa en 1 MB y una función de
-- Vercel en ~4,5 MB.
insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values ('curso-videos', 'curso-videos', false, 2147483648, array['video/mp4', 'video/webm', 'video/quicktime', 'video/x-m4v'])
on conflict (id) do update set public = false, file_size_limit = excluded.file_size_limit, allowed_mime_types = excluded.allowed_mime_types;
