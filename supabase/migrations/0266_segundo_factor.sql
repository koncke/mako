-- =============================================================================
-- 0266_segundo_factor — 2FA en el login de MaKo
-- =============================================================================
-- Pedido de Martín (13/10/2026, textual): «Activar 2FA en todos lados... Si me llegan a
-- entrar en la cuenta de email, toda la app está en riesgo. Activar 2FA de varias
-- maneras... App de Auth, mensaje de WhatsApp, codigo en correo, preguntas de
-- verificación, 2FA rápido para dispositivos seguros, como huella o face id, etc...».
--
-- Hasta hoy el login era Google y nada más: quien entrara a la cuenta de Google entraba a
-- MaKo, con rol de super admin si era la de Martín. Esta migración guarda los segundos
-- factores; la regla («el super admin no tiene sesión sin segundo factor») vive en
-- `verificarToken` (lib/auth-session.ts), que es el único lugar por donde pasan el proxy
-- y el server.
--
-- Qué NO hay acá, a propósito: **preguntas de verificación**. Son el factor más débil que
-- existe (la respuesta se saca de redes o se adivina) y no se ofrecen como segundo factor.
--
-- Todas las tablas son GLOBALES (cuelgan de `usuarios`, que no es de un workspace) y van
-- con RLS prendido y sin políticas: sólo las lee el server con la service key.
-- =============================================================================
begin;

-- El flag que se lee en CADA request, desnormalizado a propósito: `getUsuarioActual` ya
-- consulta `usuarios` en cada llamada, así que viaja en esa misma fila sin otra consulta.
-- Lo mantiene `sincronizarMfaActivo()` (lib/mfa.ts) cada vez que se agrega o quita un factor.
alter table usuarios add column if not exists mfa_activo boolean not null default false;

create table if not exists usuario_mfa (
  usuario_id        bigint primary key references usuarios(id) on delete cascade,
  -- App de autenticación (TOTP, RFC 6238). El secreto va CIFRADO (gcm2, AAD = el usuario).
  totp_cifrado      text,
  totp_activo       boolean not null default false,
  -- El último paso de 30 s aceptado: un código ya usado no vale dos veces.
  totp_ultimo_paso  bigint,
  -- Código por WhatsApp, desde la línea de MaKo. En dígitos, con código de país.
  whatsapp_tel      text,
  whatsapp_activo   boolean not null default false,
  -- Código por correo. ⚠️ Tiene que ser DISTINTO del correo con el que se entra: el login
  -- ES la cuenta de Google, así que un código al mismo correo no protege del robo de ese
  -- correo, que es justo el riesgo que motivó el pedido.
  email_respaldo    text,
  email_activo      boolean not null default false,
  updated_at        timestamptz not null default now()
);

-- Passkeys (WebAuthn): la huella, el Face ID o el PIN del dispositivo.
create table if not exists usuario_passkeys (
  id             bigint generated by default as identity primary key,
  usuario_id     bigint not null references usuarios(id) on delete cascade,
  credential_id  text not null unique,
  public_key     text not null,          -- base64url de la clave pública COSE
  contador       bigint not null default 0,
  transports     text[],
  nombre         text,
  created_at     timestamptz not null default now(),
  usado_at       timestamptz
);
create index if not exists idx_usuario_passkeys_usuario on usuario_passkeys (usuario_id);

-- Códigos de recuperación: de un solo uso, guardados como HMAC (nunca en claro).
create table if not exists usuario_codigos_recuperacion (
  id          bigint generated by default as identity primary key,
  usuario_id  bigint not null references usuarios(id) on delete cascade,
  hash        text not null,
  usado_at    timestamptz,
  created_at  timestamptz not null default now()
);
create index if not exists idx_codigos_recuperacion_usuario on usuario_codigos_recuperacion (usuario_id);

-- Desafíos de corta vida: el código mandado por WhatsApp o correo (como HMAC), el
-- challenge de una passkey, o el secreto TOTP a medio enrolar (cifrado).
create table if not exists mfa_desafios (
  id          bigint generated by default as identity primary key,
  usuario_id  bigint not null references usuarios(id) on delete cascade,
  tipo        text not null check (tipo in (
                'login-whatsapp', 'login-email', 'login-passkey',
                'enrolar-totp', 'enrolar-whatsapp', 'enrolar-email', 'enrolar-passkey')),
  dato        text not null,
  destino     text,
  intentos    int not null default 0,
  expira_at   timestamptz not null,
  usado_at    timestamptz,
  created_at  timestamptz not null default now()
);
create index if not exists idx_mfa_desafios_usuario on mfa_desafios (usuario_id, tipo, created_at desc);

-- «Recordar este dispositivo»: el token va en una cookie y acá sólo su HMAC, para poder
-- revocarlo desde la pantalla de seguridad.
create table if not exists usuario_dispositivos (
  id           bigint generated by default as identity primary key,
  usuario_id   bigint not null references usuarios(id) on delete cascade,
  token_hash   text not null unique,
  nombre       text,
  expira_at    timestamptz not null,
  revocado_at  timestamptz,
  created_at   timestamptz not null default now(),
  usado_at     timestamptz
);
create index if not exists idx_usuario_dispositivos_usuario on usuario_dispositivos (usuario_id);

-- El registro de cada intento. Sirve de auditoría Y de freno contra la fuerza bruta: el
-- límite se cuenta acá, en la base, porque `lib/rate-limit.ts` vive en la memoria de UNA
-- instancia y en Vercel cada request puede caer en otra.
create table if not exists mfa_eventos (
  id          bigint generated by default as identity primary key,
  usuario_id  bigint references usuarios(id) on delete cascade,
  tipo        text not null,
  ok          boolean not null,
  detalle     text,
  created_at  timestamptz not null default now()
);
create index if not exists idx_mfa_eventos_usuario on mfa_eventos (usuario_id, created_at desc);

alter table usuario_mfa                  enable row level security;
alter table usuario_passkeys             enable row level security;
alter table usuario_codigos_recuperacion enable row level security;
alter table mfa_desafios                 enable row level security;
alter table usuario_dispositivos         enable row level security;
alter table mfa_eventos                  enable row level security;

commit;
