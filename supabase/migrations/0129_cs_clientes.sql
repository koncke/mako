-- =============================================================================
-- 0129_cs_clientes — un cliente del programa termina en algún momento
-- =============================================================================
-- Hasta ahora un cliente entraba a la cartera cuando la venta se marcaba
-- «ganado» y no salía nunca. Jorge Negrete cerró en noviembre de 2025 con un
-- contrato de 3 meses: en agosto de 2026 seguía apareciendo como activo, en la
-- semana 37 de un programa de 13. La cartera se llena de fantasmas y deja de
-- servir para lo único que sirve, que es mirar quién necesita algo HOY.
--
-- ⚠️ POR QUÉ NO ALCANZA CON DERIVARLO DEL CONTRATO. El contrato dice cuándo
-- TERMINA el plazo, no si el trabajo se terminó. Un cliente puede pasarse tres
-- semanas y seguir activo —la garantía de Sergio Esquer dice textual «continuar
-- sesiones sin costo hasta instalación completa»— y otro puede irse antes.
-- «Se pasó del plazo» es un cálculo; «graduado» es una DECISIÓN de Mauricio, y
-- las decisiones se guardan, no se infieren.
--
-- Y por eso no se toca `leads.estado_lead`: ahí «ganado» significa que la VENTA
-- se cerró, y lo lee medio CRM. Que la entrega haya terminado es otra cosa.
-- =============================================================================
begin;

create table if not exists cs_clientes (
  id            bigint generated by default as identity primary key,
  workspace_id  bigint not null default 1 references workspaces(id) on delete cascade,
  lead_id       bigint not null references leads(id) on delete cascade,

  -- 'activo'    → en el programa
  -- 'graduado'  → terminó, y terminó bien
  -- 'baja'      → se fue antes de terminar
  -- 'pausado'   → suspendido, vuelve
  estado        text not null default 'activo'
                check (estado in ('activo','graduado','baja','pausado')),
  estado_at     timestamptz,
  /** Por qué. En una baja es lo único que después sirve para no repetirla. */
  motivo        text,
  /** Nota privada de Mauricio sobre este cliente. No la ve el cliente. */
  nota          text,

  created_at    timestamptz not null default now(),
  updated_at    timestamptz not null default now()
);

-- Un cliente, una fila. Es el target del ON CONFLICT al cambiar el estado.
create unique index if not exists uq_cs_clientes_lead
  on cs_clientes (workspace_id, lead_id);

create index if not exists idx_cs_clientes_ws on cs_clientes (workspace_id, estado);

comment on table cs_clientes is
  'El estado de un cliente DENTRO del programa. Separado de leads.estado_lead, que habla de la VENTA: que se haya cobrado no dice si la entrega terminó.';
comment on column cs_clientes.estado is
  'graduado y baja son DECISIONES de Mauricio, no cálculos: el contrato dice cuándo vence el plazo, no si el trabajo se terminó.';

alter table cs_clientes enable row level security;

commit;
