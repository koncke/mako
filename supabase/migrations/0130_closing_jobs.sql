-- =============================================================================
-- 0130_closing_jobs — el estado de "estoy analizando esta llamada", persistido
-- =============================================================================
-- El análisis de una llamada corre en background (after()) y tarda minutos. Sin
-- una fila, la pantalla no tiene cómo saber que ya está corriendo: al volver
-- mostraría el botón de nuevo y un segundo click pagaría a Claude dos veces por
-- la misma grabación. Una fila por lead: es un ESTADO, no un log de corridas.
-- =============================================================================
begin;

create table if not exists closing_jobs (
  id           bigint generated by default as identity primary key,
  workspace_id bigint not null default 1 references workspaces(id) on delete cascade,
  lead_id      bigint not null,
  -- corriendo → listo | error. No hay 'pendiente': la fila nace cuando arranca.
  estado       text not null default 'corriendo',
  -- Qué encontró (o por qué falló), en castellano y listo para pintar.
  detalle      text,
  started_at   timestamptz not null default now(),
  finished_at  timestamptz,
  created_at   timestamptz not null default now()
);

-- Unique y NO parcial: es el target del ON CONFLICT que hace de candado
-- (un solo job por lead) y de upsert del estado.
create unique index if not exists idx_closing_jobs_ws_lead on closing_jobs (workspace_id, lead_id);
create index if not exists idx_closing_jobs_ws on closing_jobs (workspace_id);

comment on table closing_jobs is
  'Estado del análisis on-demand de las llamadas de UN lead (botón "Analizar la llamada"). Una fila por lead: el último estado, no el historial.';

-- RLS on sin políticas = solo server-side (service_role), igual que el resto.
alter table closing_jobs enable row level security;

commit;
