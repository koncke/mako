-- =============================================================================
-- 0157 — meta_campaign_drafts, por fin en la base, y POR CLIENTE
-- =============================================================================
-- La 0045 definió esta tabla y NUNCA se aplicó en producción: medido el 2026-09-11,
-- `to_regclass('public.meta_campaign_drafts')` daba null. `campaign-create` y `ad-add`
-- escriben ahí best-effort con un `try { … } catch {}`, así que durante meses ningún
-- intento de publicar una campaña dejó rastro — ni los exitosos ni los rechazados.
-- Por eso los rechazos de Meta del 11/09 en Código Inmobiliario se tuvieron que
-- REPRODUCIR en vez de leerse.
--
-- ⚠️ Y LA 0045 NO TENÍA `workspace_id`. Aplicarla tal cual habría mezclado en una
-- tabla las campañas de todos los clientes (la bitácora de /admin/dev ya lo tenía
-- anotado). Esta migración la crea completa con la columna, o se la agrega si la
-- 0045 llegara a estar aplicada en algún entorno.
--
-- ⚠️ SIN `default 1`, a propósito, aunque la plantilla de migraciones lo ponga. El 1
-- es Mauricio —un CLIENTE, no la plataforma (AGENTS.md, «OWNER_WS NO es la
-- plataforma»)—: con default, un insert que se olvide del workspace le atribuye a
-- Mauricio la campaña de otro cliente, en silencio. `not null` sin default hace que
-- ese olvido falle en vez de mentir. Las rutas escriben el workspace explícito.
-- =============================================================================

begin;

create table if not exists meta_campaign_drafts (
  id                bigint generated by default as identity primary key,
  workspace_id      bigint not null references workspaces(id) on delete cascade,
  name              text not null,
  objective         text not null default 'OUTCOME_LEADS',
  status            text not null default 'borrador'
                      check (status in ('borrador','creando','publicada','error')),
  spec              jsonb not null default '{}'::jsonb,
  rationale         text,
  prompt            text,
  meta_campaign_id  text,
  meta_adset_ids    jsonb not null default '[]'::jsonb,
  meta_ad_ids       jsonb not null default '[]'::jsonb,
  meta_creative_ids jsonb not null default '[]'::jsonb,
  error             text,
  uso               jsonb,
  created_at        timestamptz not null default now(),
  updated_at        timestamptz not null default now()
);

-- Si la 0045 llegó a aplicarse en algún entorno, la tabla existe sin la columna.
alter table meta_campaign_drafts add column if not exists workspace_id bigint references workspaces(id) on delete cascade;

create index if not exists idx_meta_campaign_drafts_ws       on meta_campaign_drafts (workspace_id, created_at desc);
create index if not exists idx_meta_campaign_drafts_status   on meta_campaign_drafts (status);
create index if not exists idx_meta_campaign_drafts_campaign on meta_campaign_drafts (meta_campaign_id);

comment on table meta_campaign_drafts is
  'Campañas armadas con MaKo y publicadas en Meta (siempre en PAUSA), por workspace. Spec, explicación de MaKo, costo, ids creados y el último rechazo de Meta explicado. Mig 0045 (nunca aplicada) + 0157.';
comment on column meta_campaign_drafts.workspace_id is
  'Cliente dueño de la campaña. SIN default a propósito: un default 1 le atribuiría a Mauricio la campaña de otro cliente (mig 0157).';

alter table meta_campaign_drafts enable row level security;

commit;

notify pgrst, 'reload schema';
