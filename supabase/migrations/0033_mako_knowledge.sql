-- Entradas de metodología con su embedding. El embedding se guarda como jsonb
-- (array de floats) y la similitud (coseno) se calcula en la app — sin pgvector
-- y sin sumar otro proveedor (los embeddings salen de la API de OpenAI ya usada).
-- estado: 'indexado' | 'pendiente' | 'error'. Se re-embebe SOLO si cambia el cuerpo.

create table if not exists mako_knowledge (
  id           bigint generated by default as identity primary key,
  titulo       text not null,
  categoria    text,
  cuerpo       text not null default '',
  activo       boolean not null default true,
  embedding    jsonb,
  content_hash text,
  estado       text not null default 'pendiente',
  error        text,
  created_at   timestamptz not null default now(),
  updated_at   timestamptz not null default now()
);

create index if not exists mako_knowledge_activo_idx on mako_knowledge (activo);

-- Solo acceso server-side (service_role / conexión directa); sin políticas = sin
-- acceso anónimo, igual que el resto de las tablas.
alter table mako_knowledge enable row level security;
