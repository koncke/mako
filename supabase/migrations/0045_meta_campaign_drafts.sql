-- =============================================================================
-- 0045_meta_campaign_drafts — Campañas armadas con MaKo y publicadas en Meta
-- =============================================================================
-- "Nueva campaña": el usuario describe la campaña, MaKo propone una estructura
-- (campaña → conjuntos → anuncios + segmentación + creativos), el usuario edita
-- y publica. Toda campaña se crea en Meta SIEMPRE en PAUSA; se activa después con
-- el toggle de Ads Manager (mismo /api/meta-write op:'status' que ya funciona).
--
-- Acá guardamos el registro local: el spec completo, la explicación de MaKo, los
-- tokens/costo de la sugerencia y los ids que devuelve Graph al crear el árbol
-- (para idempotencia y para no depender del cron de ingesta para verlos).
-- El status de ENTREGA real lo manda Meta; este 'status' es el del armado/publicado.
-- RLS on sin políticas = solo server-side (service_role), igual que el resto.

begin;

create table if not exists meta_campaign_drafts (
  id                bigint generated by default as identity primary key,
  name              text not null,
  objective         text not null default 'OUTCOME_LEADS',
  status            text not null default 'borrador'
                      check (status in ('borrador','creando','publicada','error')),
  spec              jsonb not null default '{}'::jsonb,   -- CampaignSpec (árbol + targeting + creativos)
  rationale         text,                                 -- explicación de MaKo
  prompt            text,                                 -- lo que pidió el usuario
  -- ids que devuelve Graph al crear (se rellenan a medida que se arma el árbol)
  meta_campaign_id  text,
  meta_adset_ids    jsonb not null default '[]'::jsonb,
  meta_ad_ids       jsonb not null default '[]'::jsonb,
  meta_creative_ids jsonb not null default '[]'::jsonb,
  error             text,                                 -- último error de Meta (si status='error')
  uso               jsonb,                                -- {tokens, costUsd} de la sugerencia de MaKo
  created_at        timestamptz not null default now(),
  updated_at        timestamptz not null default now()
);

create index if not exists idx_meta_campaign_drafts_status   on meta_campaign_drafts (status);
create index if not exists idx_meta_campaign_drafts_campaign on meta_campaign_drafts (meta_campaign_id);

comment on table meta_campaign_drafts is
  'Campañas armadas con MaKo en la app y publicadas en Meta (siempre en PAUSA). El status de entrega real lo manda Meta; acá guardamos el spec, la explicación de MaKo, su costo en tokens y los ids creados.';

alter table meta_campaign_drafts enable row level security;

commit;
