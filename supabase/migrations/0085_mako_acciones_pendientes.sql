-- =============================================================================
-- 0085_mako_acciones_pendientes — confirmaciones seguras del doer de MaKo
-- =============================================================================
-- Cuando MaKo pide un "sí" para ejecutar una acción, crea una fila acá con un
-- VENCIMIENTO. El "sí" del dueño se matchea con la pendiente MÁS RECIENTE del
-- grupo; si hay varias abiertas, MaKo re-pregunta. Las vencidas se invalidan.
-- Así un "sí" nunca dispara algo viejo o equivocado. Scopeado por workspace.

begin;

create table if not exists mako_acciones_pendientes (
  id           bigint generated by default as identity primary key,
  workspace_id bigint not null default 1 references workspaces(id) on delete cascade,
  grupo_jid    text not null,                       -- grupo donde se pidió la confirmación
  tipo         text not null,                       -- slug de la acción (apagar_ad, agendar_r2, …)
  payload      jsonb not null default '{}'::jsonb,  -- params concretos para ejecutar
  resumen      text not null,                       -- descripción legible ("Apagar el ad 'Reel precio'")
  estado       text not null default 'pendiente',   -- pendiente|confirmada|ejecutada|cancelada|vencida|error
  vence_at     timestamptz not null,                -- después de esto, ya no se puede confirmar
  resuelto_at  timestamptz,                         -- cuándo se ejecutó/canceló/venció
  resultado    text,                                -- resultado o error de la ejecución
  origen       text,                                -- 'flujo:<plantilla>' | 'hola-mako' | …
  created_at   timestamptz not null default now()
);

-- Buscar la(s) pendiente(s) VIGENTE(s) de un grupo, la más reciente primero.
create index if not exists ix_mako_pend_grupo
  on mako_acciones_pendientes (workspace_id, grupo_jid, estado, created_at desc);

comment on table mako_acciones_pendientes is
  'Acciones que MaKo dejó a la espera de confirmación del dueño por WhatsApp. Vencen; el "sí" matchea la más reciente vigente del grupo.';

alter table mako_acciones_pendientes enable row level security;

commit;

notify pgrst, 'reload schema';
