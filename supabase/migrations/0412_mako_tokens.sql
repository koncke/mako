-- =============================================================================
-- 0412 — MaKo Tokens: el saldo que impide gastar en IA más de lo que ya se cobró (7/11/2026)
-- =============================================================================
-- Martín, 7/11: «podemos vender MaKo Tokens… que me siga saliendo rentable», y sobre la caja, «no lo tengo que
-- comprar con mi dinero». La aritmética vive en `lib/mako-tokens-reglas.ts` (1.000 MT = US$1 de costo real).
-- Acá vive lo único que la base tiene que garantizar: **que dos generaciones a la vez no gasten el mismo saldo**.
--
-- ⚠️ POR QUÉ NO VA EN `app_settings`, y está pagado con un bug de este repo (migración 0113): `app_settings` se
-- usa con read-modify-write, o sea leer el saldo, restar en el código y escribirlo. Dos pedidos simultáneos leen
-- los dos el mismo saldo, los dos creen que alcanza y los dos escriben: se gastó el doble y el contador dice que
-- se gastó una vez. Con video eso no es teórico — una persona dispara varias piezas de un tirón.
--
-- ⚠️ LA PIEZA QUE LO RESUELVE ES UNA SOLA, Y ES DE SQL, NO DE CÓDIGO: el chequeo y el descuento tienen que ser
-- **la misma sentencia**:
--
--     update mako_tokens_saldo set saldo = saldo - :cuesta
--      where workspace_id = :ws and saldo >= :cuesta
--      returning saldo;
--
-- Si devuelve una fila, se descontó y se puede generar. Si devuelve ninguna, no alcanzaba y **no se tocó nada**.
-- Postgres serializa el `update` sobre la fila, así que no hay carrera posible. Un chequeo en el código seguido
-- de un descuento aparte vuelve a tener el bug de 0113 aunque las dos sentencias sean correctas por separado.
--
-- EL `check (saldo >= 0)` ES LA RED, no el mecanismo: si alguna vez alguien descuenta sin el `where`, la base lo
-- frena en vez de dejar el saldo en negativo y regalar generaciones.
--
-- Los MOVIMIENTOS son un ledger aparte, sólo para poder explicar un saldo. **El saldo NO se calcula sumándolos**:
-- a los pocos meses son millones de filas y la suma se vuelve lenta justo en el camino caliente, que es antes de
-- CADA llamada a un modelo.
--
-- ORDEN DE DESPLIEGUE: esta migración va PRIMERO y el código después. Sin las tablas, `saldoDeWorkspace` devuelve
-- null y `alcanzaElSaldo` falla CERRADO (lib/mako-tokens-reglas.ts), así que lo peor que pasa es que no se genere
-- — nunca que se genere gratis.
--
-- ⚠️ SIN BACKFILL A PROPÓSITO: un workspace sin fila tiene saldo null, que no alcanza. Darle saldo a alguien es
-- una decisión de negocio (su plan, su pago), no un efecto de una migración. Los cupos iniciales los carga el
-- alta del plan.
-- =============================================================================
begin;

-- El saldo vigente. Una fila por negocio: es el dato que se lee y se descuenta antes de cada llamada.
create table if not exists mako_tokens_saldo (
  workspace_id bigint primary key references workspaces(id) on delete cascade,
  -- En MaKo Tokens, enteros. 1.000 MT = US$1 de costo real (lib/mako-tokens-reglas.ts).
  saldo bigint not null default 0 check (saldo >= 0),
  actualizado_en timestamptz not null default now()
);

-- El ledger: para explicar un saldo, no para calcularlo.
create table if not exists mako_tokens_movimientos (
  id bigint generated by default as identity primary key,
  workspace_id bigint not null references workspaces(id) on delete cascade,
  -- Positivo = entró saldo (el cupo del plan, una compra). Negativo = se gastó.
  delta bigint not null check (delta <> 0),
  -- De dónde salió: el cupo mensual, una compra suelta, un gasto, o un ajuste a mano del super admin.
  motivo text not null check (motivo in ('cupo', 'compra', 'gasto', 'ajuste', 'devolucion')),
  -- Qué lo gastó, para poder decir «el video se llevó el 80 %». Mismo vocabulario que `anthropic_usage.feature`.
  feature text check (feature is null or char_length(feature) between 1 and 80),
  -- El costo real que representó, por si alguna vez cambia la tasa de conversión y hay que reconstruir.
  costo_usd numeric(12, 6),
  -- Quién lo pidió, cuando aplica: sirve para una devolución dirigida.
  referencia text check (referencia is null or char_length(referencia) between 1 and 200),
  creado_en timestamptz not null default now()
);

-- Lo que se consulta de verdad: el movimiento de un negocio, lo último primero.
create index if not exists mako_tokens_movimientos_ws_idx
  on mako_tokens_movimientos (workspace_id, creado_en desc);

-- ⚠️ Un cupo mensual NO se puede acreditar dos veces: la misma referencia (por ejemplo «cupo:2026-11») entra una
-- sola vez por negocio. Sin esto, un reintento del cron que acredita los cupos regala un mes entero de IA.
create unique index if not exists mako_tokens_movimientos_cupo_unico
  on mako_tokens_movimientos (workspace_id, referencia)
  where motivo = 'cupo' and referencia is not null;

alter table mako_tokens_saldo enable row level security;
alter table mako_tokens_movimientos enable row level security;
revoke all on mako_tokens_saldo, mako_tokens_movimientos from anon, authenticated;
grant all on mako_tokens_saldo, mako_tokens_movimientos to service_role;

comment on table mako_tokens_saldo is
  'Saldo de MaKo Tokens por negocio. 1.000 MT = US$1 de costo real de IA. Se descuenta con un UPDATE condicional (where saldo >= :cuesta) que es chequeo y descuento a la vez: separarlos reintroduce el bug no atomico de la migracion 0113.';

comment on table mako_tokens_movimientos is
  'Ledger para EXPLICAR un saldo, no para calcularlo: sumar millones de filas en el camino caliente (antes de cada llamada a un modelo) no escala. El saldo vigente vive en mako_tokens_saldo.';

commit;
