-- =============================================================================
-- 0207 — Un lead en VARIOS productos del CRM: los productos que no son su casa
-- =============================================================================
-- ⚠️ ORDEN DE DESPLIEGUE: ANTES del deploy. La tabla es NUEVA y el código nuevo la LEE al
-- dibujar cada tablero del CRM; sin ella la lectura cae a «sólo su casa» (lo de siempre),
-- pero «Agregar a otro producto» fallaría al guardar. Agrega y no saca nada.
--
-- Pedido de Martín (06/10/2026), textual: «Le acabo de dar a un lead a "Mover a prueba" y
-- se desapareció del producto principal de Mauricio. Eso JAMÁS debe pasar... No se debe
-- "Mover" se debe agregar al otro producto... Y para eso en el desplegable, tal como lo
-- hacemos en Customer Success, cuando está en más de 2 productos, salta el botón de X para
-- sacarlo de alguno... Y si hay productos en los que no está, en lugar del botón de X, un
-- ícono que indique que se lo puede agregar.»
--
-- EL MODELO (calco de cliente_entrega, mig 0188):
--   · La CASA de un lead sigue siendo leads.funnel_id (NULL = el producto del negocio) con
--     su leads.pipeline_stage. Métricas, CAPI, el CRM automático, MaKo, la nutrición y la
--     etiqueta de WhatsApp siguen leyendo SÓLO la casa: no cambia nada para ellos.
--   · Cada OTRO producto donde está es una fila acá, con la etapa propia de ese tablero.
--   · NUNCA hay fila para la casa. Y el producto del negocio, cuando no es la casa, se
--     guarda con SU id (la FK no admite NULL): los lectores lo traducen.
--
-- Va en TENANT_TABLES (lib/workspace.ts) y en TABLAS_DE_INQUILINO: sin eso getTenantDb no
-- la acota por cliente y la lectura devuelve las filas de todos.
create table if not exists lead_funnel (
  id           bigint generated by default as identity primary key,
  workspace_id bigint not null default 1 references workspaces(id) on delete cascade,
  lead_id      bigint not null references leads(id) on delete cascade,
  funnel_id    bigint not null references funnels(id) on delete cascade,
  etapa        text not null,
  etapa_desde  timestamptz not null default now(),
  -- Mismo vocabulario que lead_audit.autor.
  por          text not null default 'CRM',
  created_at   timestamptz not null default now(),
  updated_at   timestamptz not null default now()
);
-- Idempotente: agregar dos veces (dos pestañas, un doble clic) es UNA fila.
create unique index if not exists lead_funnel_uk on lead_funnel (workspace_id, lead_id, funnel_id);
-- El tablero de un producto pide sus filas por funnel.
create index if not exists lead_funnel_tablero on lead_funnel (workspace_id, funnel_id);

comment on table lead_funnel is 'Los productos del CRM donde está un lead ADEMÁS de su casa (leads.funnel_id), cada uno con su etapa en ese tablero. Nunca hay fila para la casa. Métricas, CAPI, automatismos y nutrición siguen leyendo sólo la casa.';

alter table lead_funnel enable row level security;
revoke all on lead_funnel from anon, authenticated;
