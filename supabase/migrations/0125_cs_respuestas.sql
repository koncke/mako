-- =============================================================================
-- 0125_cs_respuestas — la tarea de cada bloque del programa, por cliente
-- =============================================================================
-- Es el objeto sobre el que gira el bucle de entrega: el cliente contesta antes
-- de la junta, la IA reescribe la respuesta con lo que se habló, y el cliente la
-- aprueba. Tres manos sobre el MISMO renglón, y por eso lo que escribió cada una
-- se guarda por separado: `respuesta` no se pisa nunca con `respuesta_ia`.
--
-- POR QUÉ NO ES UN jsonb EN app_settings. Es last-write-wins sin CAS: un
-- formulario largo con guardado parcial se pisa solo, y lo que se pierde es
-- texto que el cliente escribió a mano. Una fila por bloque, con su propio
-- updated_at, no tiene ese problema.
--
-- `clase_id` sale de lib/programa-catalogo.ts y es ESTABLE: no se renumera.
-- tests/programa-catalogo.test.ts lo fija, porque si un id se reusa la respuesta
-- guardada queda apuntando a la clase equivocada, en silencio.
--
-- `area` existe porque los módulos 6 a 9 se repiten UNA VEZ POR ÁREA del cliente
-- (palancas, evidencia, umbrales y carta de expectativas). El video es el mismo;
-- la tarea, no. Va NOT NULL con default '' —y no nullable— para que el índice
-- único sea sobre columnas exactas: un índice parcial o con coalesce() no sirve
-- como target de ON CONFLICT.
-- =============================================================================
begin;

create table if not exists cs_respuestas (
  id            bigint generated by default as identity primary key,
  workspace_id  bigint not null default 1 references workspaces(id) on delete cascade,
  -- El cliente de Mauricio. Vive en el CRM como lead: no se duplica su ficha acá.
  lead_id       bigint not null references leads(id) on delete cascade,
  clase_id      text   not null,
  area          text   not null default '',

  -- Lo que escribió el CLIENTE. No lo pisa nadie, nunca.
  respuesta     text,
  -- Lo que reescribió la IA con lo hablado en la junta. Es una PROPUESTA hasta
  -- que el cliente la aprueba; por eso vive en su propia columna.
  respuesta_ia  text,
  -- De qué grabación salió la reescritura, para poder rastrear de dónde vino un
  -- párrafo que el cliente no reconoce.
  fuente_reunion text,

  estado        text not null default 'pendiente'
                check (estado in ('pendiente','contestada','revisada_ia','aprobada')),

  contestada_at timestamptz,
  revisada_at   timestamptz,
  aprobada_at   timestamptz,
  created_at    timestamptz not null default now(),
  updated_at    timestamptz not null default now()
);

-- Un bloque por cliente y por área. Es el target de ON CONFLICT del guardado.
create unique index if not exists uq_cs_respuestas_bloque
  on cs_respuestas (workspace_id, lead_id, clase_id, area);

create index if not exists idx_cs_respuestas_ws on cs_respuestas (workspace_id);
-- Para «qué le falta a este cliente», que es la pregunta de cada semana.
create index if not exists idx_cs_respuestas_lead on cs_respuestas (workspace_id, lead_id, estado);

comment on table cs_respuestas is
  'La tarea de cada bloque del programa, por cliente. clase_id sale de lib/programa-catalogo.ts. Escriben tres manos: el cliente (respuesta), la IA (respuesta_ia) y el cliente otra vez al aprobar.';
comment on column cs_respuestas.area is
  'Los módulos 6 a 9 se repiten una vez por área del cliente. Vacío = el módulo no se repite.';
comment on column cs_respuestas.respuesta_ia is
  'Propuesta de la IA. Nunca pisa a respuesta: el cliente compara las dos y aprueba.';

-- RLS on sin políticas = solo server-side (service_role), igual que el resto.
alter table cs_respuestas enable row level security;

commit;
