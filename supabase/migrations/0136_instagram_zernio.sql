-- =============================================================================
-- 0136_instagram_zernio — Base del canal Instagram vía Zernio
-- =============================================================================
-- Zernio (https://zernio.com/api/v1) envuelve la API de Instagram: DMs, posts y
-- automatizaciones de comentarios. Esta migración crea la base del canal:
--   · zernio_workspace   — mapeo ws → profile de Zernio (con key de plataforma,
--                          un profile por workspace aísla los datos de cada
--                          cliente dentro de la MISMA cuenta de Zernio; con key
--                          propia/BYOK, profile_id NULL = default de SU cuenta).
--   · ig_conversaciones  — conversaciones de DM (espejo local del inbox).
--   · ig_mensajes        — mensajes por conversación; el borrador del chatbot es
--                          una fila estado='borrador' (patrón wa_borradores:
--                          un humano lo envía con 1 clic).
--   · contenido_posts    — posts del planificador de contenido (borrador →
--                          programado → publicado vía POST /v1/posts).
--   · bucket 'ig-media'  — binarios de los posts (privado, path <ws>/…).
-- Las 4 tablas van también a TENANT_TABLES (lib/workspace.ts) en este commit.
-- =============================================================================

begin;

-- ── Mapeo workspace → profile de Zernio ──────────────────────────────────────
create table if not exists zernio_workspace (
  workspace_id bigint      not null primary key references workspaces(id) on delete cascade,
  -- NULL = BYOK: el ws usa su propia key de Zernio y el profile Default de SU
  -- cuenta ("default de la key"). Con key de plataforma siempre hay un id.
  profile_id   text,
  webhook_ok   boolean     not null default false,
  created_at   timestamptz not null default now()
);

comment on table zernio_workspace is
  'Mapeo workspace → profile de Zernio. profile_id NULL = BYOK (profile Default de la cuenta propia del cliente). webhook_ok = el webhook de Zernio ya entregó al menos un evento de este ws.';

alter table zernio_workspace enable row level security;

-- ── Conversaciones de Instagram (DMs) ────────────────────────────────────────
create table if not exists ig_conversaciones (
  id                     bigint      generated by default as identity primary key,
  workspace_id           bigint      not null default 1 references workspaces(id) on delete cascade,
  -- id INTERNO de Zernio (conversation.id del webhook / data[].id del listado):
  -- es el que se pasa verbatim al endpoint de envío. Opaco, no parsear.
  zernio_conversation_id text        not null,
  zernio_account_id      text,       -- social account ID de Zernio (cuenta IG del ws)
  igsid                  text,       -- Instagram-scoped sender ID (sender.id del webhook)
  username               text,       -- username del participante
  -- SIN cascada de borrado a propósito: borrar un lead no borra su historial de
  -- DMs (mismo criterio que wa_borradores.lead_id).
  lead_id                bigint      references leads(id) on delete set null,
  ultimo_mensaje_at      timestamptz,
  -- Ventana de mensajería de Meta: 24h desde el último mensaje ENTRANTE. Fuera
  -- de la ventana, Instagram solo acepta messageTag HUMAN_AGENT.
  ventana_expira_at      timestamptz,
  created_at             timestamptz not null default now()
);

-- Único por ws (target del ON CONFLICT del upsert del webhook). NO parcial.
create unique index if not exists uq_ig_conversaciones_zernio
  on ig_conversaciones (workspace_id, zernio_conversation_id);
create index if not exists idx_ig_conversaciones_ws
  on ig_conversaciones (workspace_id, ultimo_mensaje_at desc);
-- FK sin índice = seq scan en cada borrado/merge de lead.
create index if not exists idx_ig_conversaciones_lead
  on ig_conversaciones (lead_id);
-- El fallback de ruteo del webhook (wsPorAccountId, app/api/webhooks/zernio)
-- busca por zernio_account_id SIN workspace (todavía no lo sabe): índice propio.
create index if not exists idx_ig_conversaciones_account
  on ig_conversaciones (zernio_account_id);

comment on table ig_conversaciones is
  'Conversaciones de DM de Instagram (vía Zernio). zernio_conversation_id es el id interno de Zernio que se usa para enviar. ventana_expira_at = fin de la ventana de 24h de Meta.';

alter table ig_conversaciones enable row level security;

-- ── Mensajes ─────────────────────────────────────────────────────────────────
create table if not exists ig_mensajes (
  id                bigint      generated by default as identity primary key,
  conversacion_id   bigint      not null references ig_conversaciones(id) on delete cascade,
  workspace_id      bigint      not null default 1 references workspaces(id) on delete cascade,
  direccion         text        not null check (direccion in ('entrante', 'saliente')),
  -- 'borrador' = sugerencia del chatbot esperando el 1 clic de un humano
  -- (patrón wa_borradores). 'error' guarda el porqué en la columna error.
  estado            text        not null default 'recibido'
                                check (estado in ('recibido', 'borrador', 'enviado', 'error')),
  texto             text,
  -- [{type, url, refreshUrl, …}]. OJO (contrato Zernio): la url de IG es una CDN
  -- de Meta firmada que EXPIRA — lo persistible es refreshUrl, no url.
  adjuntos          jsonb       not null default '[]'::jsonb,
  zernio_message_id text,       -- message.id de Zernio (entrantes) / messageId del send (salientes)
  error             text,
  created_at        timestamptz not null default now()
);

create index if not exists idx_ig_mensajes_conv
  on ig_mensajes (workspace_id, conversacion_id, created_at);
-- La bandeja de borradores pendientes (patrón idx_wa_borradores_pend).
create index if not exists idx_ig_mensajes_estado
  on ig_mensajes (workspace_id, estado, created_at);
-- Dedup de la entrega at-least-once del webhook: un mismo mensaje de Zernio se
-- inserta UNA vez por ws. NO parcial (target de ON CONFLICT). Los borradores
-- tienen zernio_message_id NULL → los NULL no colisionan entre sí.
create unique index if not exists uq_ig_mensajes_zernio
  on ig_mensajes (workspace_id, zernio_message_id);

comment on table ig_mensajes is
  'Mensajes de DM de Instagram. estado=borrador es la sugerencia del chatbot que un humano envía con 1 clic; el dedup del webhook (at-least-once) es uq_ig_mensajes_zernio.';

alter table ig_mensajes enable row level security;

-- ── Posts del planificador de contenido ──────────────────────────────────────
create table if not exists contenido_posts (
  id                bigint      generated by default as identity primary key,
  workspace_id      bigint      not null default 1 references workspaces(id) on delete cascade,
  tipo              text        not null default 'feed'
                                check (tipo in ('feed', 'reel', 'story', 'carrusel')),
  caption           text,
  -- [{path, mime, …}] con path del bucket 'ig-media', SIEMPRE prefijado <ws>/…
  -- (el bucket no se scopea solo). A Zernio se le manda una URL firmada.
  media             jsonb       not null default '[]'::jsonb,
  -- Espeja los estados de Zernio: draft|scheduled|publishing|published|partial|failed.
  estado            text        not null default 'borrador'
                                check (estado in ('borrador', 'programado', 'publicando', 'publicado', 'parcial', 'error')),
  programado_at     timestamptz,
  publicado_at      timestamptz,
  zernio_post_id    text,       -- post._id de Zernio (los webhooks post.* rutean por acá)
  zernio_profile_id text,
  error             text,
  created_at        timestamptz not null default now()
);

create index if not exists idx_contenido_posts_ws
  on contenido_posts (workspace_id, estado, created_at desc);
-- SIN workspace_id adelante a propósito: el ruteo del webhook (wsPorZernioPostId)
-- busca por zernio_post_id ANTES de saber el workspace — un compuesto con
-- workspace_id primero no le sirve. El update tenant-scoped (workspace_id +
-- zernio_post_id) usa este mismo índice: zernio_post_id ya es casi único.
create index if not exists idx_contenido_posts_zernio
  on contenido_posts (zernio_post_id);

comment on table contenido_posts is
  'Posts de Instagram del planificador (vía Zernio). media guarda paths del bucket ig-media (prefijo <ws>/); zernio_post_id enlaza con los webhooks post.published/post.failed.';

alter table contenido_posts enable row level security;

-- ── Bucket PRIVADO para la media de los posts (patrón 'archivero'/'wa-media') ─
insert into storage.buckets (id, name, public)
values ('ig-media', 'ig-media', false)
on conflict (id) do nothing;

commit;

notify pgrst, 'reload schema';
