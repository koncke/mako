-- =============================================================================
-- 0124_agente_telemetria — qué trabaja cada cliente en SU Claude Code
-- =============================================================================
-- El plugin de MaKo que el cliente instala reporta, al terminar cada sesión, un ACTA
-- (de qué se trató, cuántos turnos, qué señales) y los TURNOS QUE ESCRIBIÓ LA PERSONA.
-- Sirve para dos cosas declaradas por el dueño: saber en qué trabajan sus clientes
-- para priorizar features por demanda real, y detectar mal uso para recomendarles
-- cómo prompear mejor.
--
-- DOS VIDAS DISTINTAS, Y ESA ES LA DECISIÓN DE DISEÑO:
--   · el ACTA se queda (pesa ~4 kB y es lo que contesta «en qué trabajan»);
--   · los TURNOS caducan (`purgar_despues`), porque son lo único que puede traer
--     contenido del negocio del cliente y solo hacen falta un tiempo para leer CÓMO
--     prompea. Un cron los borra; el acta sobrevive.
--
-- POR QUÉ SOLO LOS TURNOS HUMANOS Y NO EL TRANSCRIPT ENTERO: las credenciales y los
-- datos de terceros aparecen en las SALIDAS DE HERRAMIENTAS (un .env que el agente
-- leyó, una fila de la base), casi nunca en lo que la persona tipea. Filtrar por
-- «esto lo escribió un humano» es una guarda más fuerte que cualquier expresión
-- regular, y corre ANTES que la redacción, no en lugar de ella.
--
-- ⚠️ ESTA TABLA LA MIRA EL SUPER-ADMIN. Cruza el aislamiento por workspace A
-- PROPÓSITO y es el único lugar del sistema donde eso pasa: guarda `workspace_id`
-- como cualquier tabla por-cliente (y va en TENANT_TABLES para que el proxy la
-- scopee cuando la lee el CLIENTE en su propio panel), pero el panel del dueño la
-- lee con el cliente de servicio, sin scope. Las dos lecturas existen y son
-- distintas: el cliente ve lo suyo, el dueño ve todo.
-- =============================================================================
begin;

-- ── El acta de una sesión ────────────────────────────────────────────────────
create table if not exists agente_sesiones (
  id            bigint generated by default as identity primary key,
  workspace_id  bigint not null default 1 references workspaces(id) on delete cascade,
  -- El id de sesión que trae Claude Code. Único por workspace: si el hook reintenta
  -- porque no hubo internet, actualiza en vez de duplicar.
  sesion_id     text not null,
  -- Cuándo arrancó y cuánto duró, en la máquina del cliente.
  empezo_en     timestamptz,
  termino_en    timestamptz,
  -- El acta: { titulo, resumen, turnos, herramientas, archivos_tocados, señales… }.
  -- jsonb y no columnas porque la forma va a cambiar y no quiero una migración por
  -- cada señal nueva que se nos ocurra medir.
  acta          jsonb not null default '{}'::jsonb,
  -- Los turnos que escribió la PERSONA, ya redactados: [{ ts, texto }]. Se vacía
  -- cuando pasa `purgar_despues`; el acta se queda.
  turnos        jsonb not null default '[]'::jsonb,
  -- Cuántas veces la redacción tuvo que tapar algo. Si esto sube, la guarda de
  -- «solo turnos humanos» está fallando y hay que mirar por qué.
  redacciones   integer not null default 0,
  purgar_despues timestamptz,
  created_at    timestamptz not null default now()
);
create unique index if not exists idx_agente_sesiones_ws_sesion on agente_sesiones (workspace_id, sesion_id);
create index if not exists idx_agente_sesiones_ws on agente_sesiones (workspace_id);
-- El panel del dueño ordena por fecha sobre TODOS los workspaces.
create index if not exists idx_agente_sesiones_fecha on agente_sesiones (created_at desc);
-- El cron de purga busca por esta columna.
create index if not exists idx_agente_sesiones_purga on agente_sesiones (purgar_despues) where purgar_despues is not null;

comment on table agente_sesiones is
  'Una fila por sesión de Claude Code del cliente. `acta` se queda; `turnos` caduca en `purgar_despues`. La lee el super-admin sin scope y el cliente con scope.';
comment on column agente_sesiones.turnos is
  'Solo lo que ESCRIBIÓ la persona, ya redactado. Nunca salidas de herramientas: ahí es donde aparecen las credenciales.';

-- ── El acta de consentimiento ────────────────────────────────────────────────
-- Va en su propia tabla y NO en un setting porque tiene que sobrevivir a todo: es la
-- prueba de que el cliente aceptó, con qué texto y cuándo. Sin fila acá no se acuña
-- token, y sin token el plugin no habla con MaKo.
create table if not exists agente_consentimiento (
  workspace_id  bigint primary key references workspaces(id) on delete cascade,
  -- Quién aceptó (email de la sesión) y con qué versión del texto. La versión importa:
  -- si mañana cambia lo que se reporta, hay que volver a pedirlo, y sin esto no hay
  -- forma de saber quién aceptó qué.
  acepto_email  text not null,
  version       text not null,
  acepto_en     timestamptz not null default now()
);

comment on table agente_consentimiento is
  'Sin fila acá no se acuña el token del agente. Guarda QUIÉN aceptó y con qué VERSIÓN del texto: si el texto cambia, hay que volver a pedirlo.';

-- RLS on sin políticas = solo server-side (service_role), igual que el resto del repo.
alter table agente_sesiones enable row level security;
alter table agente_consentimiento enable row level security;

commit;
