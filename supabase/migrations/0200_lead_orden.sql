-- ⚠️ ORDEN DE DESPLIEGUE: ANTES del deploy. La tabla es NUEVA y el código nuevo la LEE al
-- dibujar /crm; un deploy sin ella no rompe la pantalla (la lectura cae a «sin orden
-- manual»), pero arrastrar una tarjeta fallaría al guardar. Agrega y no saca nada, así que
-- aplicarla antes no molesta a la versión desplegada.
--
-- Pedido de Martín (06/10/2026), por el chat de Customer Success: el hueco del arrastre
-- seguía al cursor también en la MISMA columna, y soltar ahí no movía nada.
--   «cuando se hace esto, es como poner un "ORDENAMIENTO" dentro de filtros... normalmente
--   se ordena por orden de llegada. Para quitar eso y volver a antes, simplemente es volver
--   a ordenar por fecha y listo. Y luego si quiero volver a la posición que había dejado las
--   tarjetas es simplemente quitar filtros.»
--
-- Es la gemela de `cliente_entrega_orden` (mig 0196, Customer Success): UNA fila por
-- (embudo, etapa) con la lista de leads en el orden en que se arrastraron, y no una posición
-- por lead — una posición por lead obliga a reescribir media columna en cada arrastre.
--
-- ⚠️ `funnel_id` NULL = el embudo del NEGOCIO, igual que en `leads.funnel_id` (el CRM pide
-- los leads de ese embudo con `.is('funnel_id', null)`). Por eso el índice único va con
-- NULLS NOT DISTINCT (Postgres 15+; prod corre 17.6): sin eso, cada arrastre en el embudo
-- del negocio insertaría una fila nueva en vez de pisar la suya, y el `upsert` no tendría
-- contra qué chocar.
--
-- ⚠️ La lista puede nombrar leads que ya no están en esa columna (se movieron, se
-- borraron): no se poda al escribir, se IGNORA al leer. Los que están y no figuran van
-- después, en el orden de llegada.
create table if not exists lead_orden (
  id           bigint generated by default as identity primary key,
  workspace_id bigint not null default 1 references workspaces(id) on delete cascade,
  funnel_id    bigint references funnels(id) on delete cascade,
  etapa        text not null,
  lead_ids     bigint[] not null default '{}',
  updated_at   timestamptz not null default now()
);
create unique index if not exists lead_orden_uk on lead_orden (workspace_id, funnel_id, etapa) nulls not distinct;

comment on table lead_orden is 'El orden manual de cada columna del kanban del CRM: la lista de lead_ids de una etapa de un embudo (funnel_id NULL = el embudo del negocio). Se ignora lo que ya no está en la columna.';

alter table lead_orden enable row level security;
revoke all on lead_orden from anon, authenticated;
