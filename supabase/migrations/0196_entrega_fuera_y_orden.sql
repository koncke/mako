-- 0196 — Customer Success: quitar a un cliente de su producto, y el orden manual
-- =============================================================================
-- ⚠️ ORDEN DE DESPLIEGUE: ANTES del deploy. Las dos tablas son NUEVAS y el código nuevo
-- las LEE al dibujar /customer-success; un deploy sin ellas no rompe la pantalla (la
-- lectura cae a «nadie fuera, sin orden manual»), pero «Quitar» y el orden manual
-- fallarían al guardar. Agrega y no saca nada, así que aplicarla antes no molesta a la
-- versión desplegada.
--
-- Pedido de Martín (06/10/2026):
--   1. «agregá "Quitar de este producto", pero solo para los leads que estén en más de 1
--      producto».
--   4. «si a un cliente lo arrastro abajo de otro, no se ve esa animación» — y, al
--      preguntarle si esa posición se guarda: «Se guarda + "Manual"».
--
-- ── 1. cliente_entrega_fuera ────────────────────────────────────────────────
-- Un cliente es de un producto si es su CASA (el producto de su embudo del CRM) o si tiene
-- una fila en `cliente_entrega` (app/customer-success/pertenencia.ts). La casa se DERIVA,
-- así que sacarlo de ella no se puede hacer borrando nada: hace falta decir «éste no».
--
-- ⚠️ UNA TABLA APARTE y no una columna de `cliente_entrega`, a propósito: TODO lo que lee
-- `cliente_entrega` (el tablero, la nutrición, el choke point) entiende «hay fila» como «está
-- en esta etapa». Una fila con un «fuera = true» sería un cliente en una etapa que no está,
-- en cada lector que no se enteró. Acá nadie la lee salvo la regla de pertenencia.
create table if not exists cliente_entrega_fuera (
  id           bigint generated by default as identity primary key,
  workspace_id bigint not null default 1 references workspaces(id) on delete cascade,
  lead_id      bigint not null references leads(id) on delete cascade,
  producto_id  bigint not null references productos(id) on delete cascade,
  -- Mismo vocabulario que `lead_audit.autor`.
  por          text not null default 'CRM',
  created_at   timestamptz not null default now()
);
-- Idempotente: quitar dos veces (dos pestañas, un doble click) es UNA fila.
create unique index if not exists cliente_entrega_fuera_uk on cliente_entrega_fuera (workspace_id, lead_id, producto_id);

comment on table cliente_entrega_fuera is 'Clientes que se SACARON de un producto que era su casa (el de su embudo del CRM). La casa se deriva, así que sacarlo es una fila acá, no un borrado. La lee sólo la regla de pertenencia de Customer Success.';

alter table cliente_entrega_fuera enable row level security;
revoke all on cliente_entrega_fuera from anon, authenticated;

-- ── 2. cliente_entrega_orden ────────────────────────────────────────────────
-- El orden manual de una columna del kanban: la lista de clientes, en el orden en que se
-- arrastraron. UNA fila por (producto, etapa) y no una posición por cliente, porque la
-- mayoría de los clientes NO tiene fila en `cliente_entrega` (está en la primera etapa por
-- regla derivada): una posición por cliente obligaría a escribirle una fila —con un reloj
-- de etapa que arranca hoy— a cada uno que se reordene.
--
-- ⚠️ La lista puede nombrar a clientes que ya no están en esa columna (se movieron, se
-- quitaron): no se poda al escribir otra cosa, se IGNORA al leer. Los que están y no figuran
-- van después, en el orden de «Ordenar».
create table if not exists cliente_entrega_orden (
  id           bigint generated by default as identity primary key,
  workspace_id bigint not null default 1 references workspaces(id) on delete cascade,
  producto_id  bigint not null references productos(id) on delete cascade,
  etapa        text not null,
  lead_ids     bigint[] not null default '{}',
  updated_at   timestamptz not null default now()
);
create unique index if not exists cliente_entrega_orden_uk on cliente_entrega_orden (workspace_id, producto_id, etapa);

comment on table cliente_entrega_orden is 'El orden manual de cada columna del kanban de entrega: la lista de lead_ids de una etapa de un producto. Se ignora lo que ya no está en la columna.';

alter table cliente_entrega_orden enable row level security;
revoke all on cliente_entrega_orden from anon, authenticated;
