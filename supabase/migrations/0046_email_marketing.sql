-- =============================================================================
-- 0046_email_marketing — Email Marketing (Resend) sobre el motor de nutrición
-- =============================================================================
-- El canal email reutiliza el motor de nutrición (nutricion_secuencias /
-- nutricion_inscripciones / nutricion_envios): las "secuencias de email" son
-- filas single-channel (todos los pasos canal='email') en nutricion_secuencias,
-- con claves 'email-*' para no colisionar con las de WhatsApp. Comparten cohorte,
-- rate-limiter y guard de 20h por lead con WhatsApp.
--
-- Agrega además:
--  • leads.email_opt_out — supresión (un lead que se dio de baja no recibe email).
--  • email_broadcasts — envíos puntuales a un segmento (one-off).
--  • email_broadcast_envios — log por destinatario de cada broadcast.
--  • índices por proveedor_id (id de Resend) para el webhook de eventos.
--
-- Las secuencias de email se siembran PAUSADAS (activa=false): doble gate para
-- el envío real → hay que activarlas en /email Y poner EMAIL_SEND_ENABLED=true.
-- RLS on sin políticas = solo server-side (service_role), igual que el resto.

begin;

-- 1) Supresión de email (baja / unsubscribe). El motor saltea estos leads.
alter table leads
  add column if not exists email_opt_out boolean not null default false;

-- 2) Broadcasts: envío puntual de email a un segmento de leads.
create table if not exists email_broadcasts (
  id                  bigint generated by default as identity primary key,
  asunto              text not null default '',
  preheader           text,                              -- texto de vista previa
  cuerpo              text not null default '',          -- cuerpo en texto plano (con {nombre})
  segmento            text not null default 'activos',   -- clave de segmento (ver lib/email-marketing.ts)
  estado              text not null default 'borrador',  -- borrador|programado|enviando|enviado|cancelado
  programado_at       timestamptz,                       -- cuándo enviar (si está programado)
  enviado_at          timestamptz,                       -- cuándo se terminó de enviar
  total_destinatarios int not null default 0,            -- snapshot de cuántos recibieron
  created_at          timestamptz not null default now(),
  updated_at          timestamptz not null default now()
);

create index if not exists idx_email_broadcasts_estado
  on email_broadcasts (estado, programado_at);

-- 3) Log por destinatario de cada broadcast (mide open/clic/rebote vía webhook).
create table if not exists email_broadcast_envios (
  id           bigint generated by default as identity primary key,
  broadcast_id bigint not null references email_broadcasts(id) on delete cascade,
  lead_id      bigint references leads(id) on delete set null,
  destino      text,                                     -- email destino
  estado       text not null,                            -- simulado|enviado|fallo
  proveedor_id text,                                      -- id del email en Resend
  error        text,
  abierto_at   timestamptz,
  clic_at      timestamptz,
  created_at   timestamptz not null default now()
);

create index if not exists idx_email_bcast_envios_bcast
  on email_broadcast_envios (broadcast_id);
create index if not exists idx_email_bcast_envios_prov
  on email_broadcast_envios (proveedor_id);

-- 4) Índice por proveedor_id en nutricion_envios para que el webhook de Resend
--    encuentre rápido el envío a marcar como abierto/clic/rebote.
create index if not exists idx_nutri_envios_prov
  on nutricion_envios (proveedor_id);

comment on table email_broadcasts is
  'Broadcasts de Email Marketing: envíos puntuales a un segmento de leads (Resend).';
comment on table email_broadcast_envios is
  'Log por destinatario de cada broadcast. Mide open/clic/rebote vía webhook de Resend.';
comment on column leads.email_opt_out is
  'true = el lead se dio de baja del email. El motor de nutrición y los broadcasts lo saltean.';

alter table email_broadcasts       enable row level security;
alter table email_broadcast_envios enable row level security;

