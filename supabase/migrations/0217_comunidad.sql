-- 0217 — La COMUNIDAD de un producto (tipo Skool): el modelo de datos ENTERO
-- =============================================================================
-- ⚠️ ORDEN DE DESPLIEGUE: ANTES del deploy. Son tablas NUEVAS que el código nuevo lee al dibujar
-- /customer-success/comunidad y la comunidad del portal del alumno (/api/compartido/comunidad). Agrega
-- y no saca nada: aplicarla antes no molesta a la versión desplegada, que no las mira.
--
-- Pedido de Martín (07/10/2026, item 10), textual: «quiero implementar una nueva tab dentro del
-- desplegable de la sidebar de Customer Success, que sea Comunidad, replica lo que tiene skool tal
-- cual, todas las funcionalidades de comunidad.» Las decisiones están en docs/diseno-curso-skool.md
-- (D8) y el relevo de cómo es Skool por dentro, en la cosecha de esa corrida.
--
-- ⚠️ ESTA MIGRACIÓN TRAE TODAS LAS TABLAS DE LA COMUNIDAD, también las que usa la SEGUNDA mitad
-- (calendario, notificaciones, seguimientos, About y moderación): la segunda mitad construye encima
-- de ésta y no tiene que volver a tocar el modelo para empezar. Lo que lee y escribe cada mitad:
--   · primera: categorías, posts, comentarios, likes (= puntos), votos, perfiles, ajustes (nombres de
--     nivel), y escribe notificaciones (likes, comentarios, menciones) y lee baneos (el portón).
--   · segunda: eventos y sus avisos, la campana (lee notificaciones), seguimientos, About (ajustes),
--     moderación (baneos). La segunda mitad le sumó a ESTE archivo (no a otro, como pedía el reparto)
--     las columnas que le faltaban: `comunidad_posts.comentarios_cerrados_at`, `ocurrencia` y `clave`
--     en las notificaciones (con su índice único), y `ocurrencia_fecha` + `portada` en los eventos. Cada
--     una va también como `add column if not exists`, por si la versión anterior ya se aplicó.
--
-- ── LA IDENTIDAD DE UN MIEMBRO ─────────────────────────────────────────────────────────────────
-- La columna `miembro` es la misma en todas las tablas: `u:<usuarios.id>` para el EQUIPO y
-- `l:<leads.id>` para un ALUMNO. ⚠️ NO ES EL EMAIL: la clave viaja al navegador del alumno (tarjetas,
-- menciones, ranking) y el email del equipo ahí sería un dato que no es suyo. El alumno además lleva
-- su `lead_id` como FK con cascada: si se borra el lead (un pedido de baja de datos), se va lo suyo.
-- El equipo NO lleva FK a `usuarios`: una sesión de super admin no es una fila del workspace, y lo
-- que escribió el equipo sobrevive a que la persona se vaya (con `autor_nombre`, su nombre de entonces).
--
-- ── EL SCOPE ───────────────────────────────────────────────────────────────────────────────────
-- Todas llevan `workspace_id` NOT NULL y SIN default. ⚠️ Las del curso (0202) tienen `default 1`, y
-- eso convierte un insert que se olvidó del workspace en una fila del ws1 (un cliente). Acá un insert
-- sin workspace FALLA. El código (lib/comunidad-datos.ts) pone el `.eq('workspace_id')` a mano en cada
-- consulta, y las tablas van además a TENANT_TABLES (lib/workspace.ts) y TABLAS_DE_INQUILINO.

begin;

-- ── 1. Ajustes de la comunidad (uno por producto) ─────────────────────────────────────────────
create table if not exists comunidad_ajustes (
  id                  bigint generated by default as identity primary key,
  workspace_id        bigint not null references workspaces(id) on delete cascade,
  producto_id         bigint not null references productos(id) on delete cascade,
  -- `null` = el nombre del producto. Es el título de la comunidad (About / barra lateral).
  nombre              text check (nombre is null or length(nombre) <= 80),
  -- La descripción corta de la barra lateral (Skool: hasta 150).
  descripcion         text not null default '' check (length(descripcion) <= 150),
  -- La pantalla About: `{ texto }` (el texto largo, hasta 5000; lib/comunidad-reglas.ts, `sanearAbout`).
  about               jsonb not null default '{}'::jsonb check (length(coalesce(about->>'texto', '')) <= 5000),
  reglas              text not null default '' check (length(reglas) <= 4000),
  -- Los 9 nombres de nivel; `''` = «Nivel N» (lib/comunidad-niveles.ts, sanearNombresNivel).
  nombres_nivel       jsonb not null default '[]'::jsonb,
  -- El plugin de Skool «Unlock Posting at Level N». 1 = postea cualquiera. El equipo postea siempre.
  nivel_para_postear  int not null default 1 check (nivel_para_postear between 1 and 9),
  -- La zona por defecto del calendario (segunda mitad). `null` = la del workspace.
  zona_horaria        text,
  actualizado_por     text,
  created_at          timestamptz not null default now(),
  updated_at          timestamptz not null default now()
);
create unique index if not exists comunidad_ajustes_uk on comunidad_ajustes (workspace_id, producto_id);
comment on table comunidad_ajustes is 'Ajustes de la comunidad de un producto: nombre, descripción, About, reglas, nombres de los 9 niveles y nivel mínimo para postear.';

-- ── 2. Categorías ─────────────────────────────────────────────────────────────────────────────
-- Skool: hasta 10, nombre de hasta 30, permiso «todos» o «solo admins», y un orden por defecto. El
-- tope de 10 lo aplica el código (validarCategoria): un trigger para eso sería más regla que la que vale.
create table if not exists comunidad_categorias (
  id             bigint generated by default as identity primary key,
  workspace_id   bigint not null references workspaces(id) on delete cascade,
  producto_id    bigint not null references productos(id) on delete cascade,
  nombre         text not null check (length(btrim(nombre)) between 1 and 30),
  permiso        text not null default 'todos' check (permiso in ('todos', 'equipo')),
  orden_default  text not null default 'default' check (orden_default in ('default', 'nuevos', 'top_semana', 'top_mes')),
  orden          int not null default 0,
  created_at     timestamptz not null default now()
);
create index if not exists idx_comunidad_categorias on comunidad_categorias (workspace_id, producto_id, orden);
comment on table comunidad_categorias is 'Categorías del feed de una comunidad (hasta 10). permiso=equipo: sólo el equipo publica ahí.';

-- ── 3. Posts ──────────────────────────────────────────────────────────────────────────────────
create table if not exists comunidad_posts (
  id              bigint generated by default as identity primary key,
  workspace_id    bigint not null references workspaces(id) on delete cascade,
  producto_id     bigint not null references productos(id) on delete cascade,
  -- Borrar una categoría no borra sus posts: quedan sin categoría.
  categoria_id    bigint references comunidad_categorias(id) on delete set null,
  miembro         text not null,
  lead_id         bigint references leads(id) on delete cascade,
  -- El nombre de quien lo escribió, AL ESCRIBIRLO. Se dibuja el vivo (usuarios/leads) y éste es el
  -- respaldo cuando la persona ya no está.
  autor_nombre    text not null default '',
  titulo          text not null check (length(btrim(titulo)) between 1 and 200),
  -- Texto con saltos de línea, links y @menciones. NUNCA HTML: se dibuja como texto (lib/comunidad-reglas.ts).
  cuerpo          text not null default '' check (length(cuerpo) <= 10000),
  -- Claves de los miembros mencionados (validadas al guardar: miembros de ESTA comunidad, nombrados en el texto).
  menciones       jsonb not null default '[]'::jsonb,
  video_url       text check (video_url is null or (video_url ~ '^https?://' and length(video_url) <= 600)),
  -- El adjunto: `<ws>/<producto>/<uuid>.<ext>` en el bucket `comunidad-adjuntos`. El nombre va aparte.
  adjunto_path    text,
  adjunto_nombre  text,
  adjunto_mime    text,
  adjunto_bytes   bigint,
  -- `{ opciones: [{ id: 'o1', texto }] }`, o null. Una encuesta publicada no se edita: el voto guarda el id.
  encuesta        jsonb,
  fijado_at       timestamptz,
  -- Moderación: con los comentarios cerrados no comenta nadie (`puedeComentar`) hasta que el equipo
  -- los vuelva a abrir. Lo que ya estaba se sigue viendo.
  comentarios_cerrados_at timestamptz,
  -- La actividad: se publica o se le comenta. Es el orden «Default» de Skool.
  actividad_at    timestamptz not null default now(),
  editado_at      timestamptz,
  created_at      timestamptz not null default now(),
  constraint comunidad_posts_miembro check (
    miembro ~ '^(u|l):[1-9][0-9]*$'
    and ((lead_id is null) = (miembro like 'u:%'))
    and (lead_id is null or miembro = 'l:' || lead_id::text)
  ),
  constraint comunidad_posts_adjunto check ((adjunto_path is null) = (adjunto_nombre is null))
);
-- Por si la versión anterior de esta migración ya se aplicó (ver la nota en las notificaciones).
alter table comunidad_posts add column if not exists comentarios_cerrados_at timestamptz;
create index if not exists idx_comunidad_posts_actividad on comunidad_posts (workspace_id, producto_id, actividad_at desc);
create index if not exists idx_comunidad_posts_nuevos on comunidad_posts (workspace_id, producto_id, created_at desc);
create index if not exists idx_comunidad_posts_fijados on comunidad_posts (workspace_id, producto_id) where fijado_at is not null;
create index if not exists idx_comunidad_posts_lead on comunidad_posts (workspace_id, lead_id) where lead_id is not null;
comment on table comunidad_posts is 'Posts del feed de la comunidad de un producto. miembro = u:<usuario> (equipo) o l:<lead> (alumno).';

-- ── 4. Comentarios (DOS niveles) ──────────────────────────────────────────────────────────────
create table if not exists comunidad_comentarios (
  id            bigint generated by default as identity primary key,
  workspace_id  bigint not null references workspaces(id) on delete cascade,
  producto_id   bigint not null references productos(id) on delete cascade,
  post_id       bigint not null references comunidad_posts(id) on delete cascade,
  -- `null` = primer nivel. Una respuesta cuelga SIEMPRE de uno de primer nivel (trigger de abajo).
  padre_id      bigint references comunidad_comentarios(id) on delete cascade,
  miembro       text not null,
  lead_id       bigint references leads(id) on delete cascade,
  autor_nombre  text not null default '',
  cuerpo        text not null check (length(btrim(cuerpo)) between 1 and 4000),
  menciones     jsonb not null default '[]'::jsonb,
  editado_at    timestamptz,
  created_at    timestamptz not null default now(),
  constraint comunidad_comentarios_miembro check (
    miembro ~ '^(u|l):[1-9][0-9]*$'
    and ((lead_id is null) = (miembro like 'u:%'))
    and (lead_id is null or miembro = 'l:' || lead_id::text)
  )
);
create index if not exists idx_comunidad_comentarios_post on comunidad_comentarios (workspace_id, post_id, created_at);
create index if not exists idx_comunidad_comentarios_lead on comunidad_comentarios (workspace_id, lead_id) where lead_id is not null;
comment on table comunidad_comentarios is 'Comentarios de un post: dos niveles (comentario y respuesta). Responder a una respuesta queda en el mismo hilo.';

-- ⚠️ LOS DOS NIVELES TAMBIÉN EN LA BASE. El código ya cuelga la respuesta de una respuesta del mismo
-- comentario (`padreDeRespuesta`); esto es la red para un insert que no pase por ahí: el padre tiene
-- que ser de primer nivel, del MISMO post y del MISMO workspace.
create or replace function comunidad_comentario_dos_niveles() returns trigger
language plpgsql set search_path = public as $$
begin
  if new.padre_id is not null and not exists (
    select 1 from comunidad_comentarios p
    where p.id = new.padre_id and p.padre_id is null and p.post_id = new.post_id and p.workspace_id = new.workspace_id
  ) then
    raise exception 'comunidad: una respuesta cuelga de un comentario de primer nivel del mismo post';
  end if;
  return new;
end $$;
revoke all on function comunidad_comentario_dos_niveles() from public, anon, authenticated;
drop trigger if exists comunidad_comentario_dos_niveles on comunidad_comentarios;
create trigger comunidad_comentario_dos_niveles before insert or update of padre_id, post_id on comunidad_comentarios
  for each row execute function comunidad_comentario_dos_niveles();

-- ── 5. Likes (= puntos) ───────────────────────────────────────────────────────────────────────
-- 1 like recibido = 1 punto (Skool). Los puntos se CUENTAN de estas filas, no se suman en un contador:
-- sacar el like borra la fila y el punto se va solo.
create table if not exists comunidad_likes (
  id             bigint generated by default as identity primary key,
  workspace_id   bigint not null references workspaces(id) on delete cascade,
  producto_id    bigint not null references productos(id) on delete cascade,
  -- `p:<post>` o `c:<comentario>`: UNA columna para que el índice único sea completo (un upsert de
  -- PostgREST no puede apuntar a un índice parcial).
  objetivo       text not null check (objetivo ~ '^(p|c):[1-9][0-9]*$'),
  post_id        bigint references comunidad_posts(id) on delete cascade,
  comentario_id  bigint references comunidad_comentarios(id) on delete cascade,
  -- Quién dio el like.
  miembro        text not null,
  lead_id        bigint references leads(id) on delete cascade,
  -- Quién lo RECIBE (el autor de lo likeado): de acá salen los puntos sin un join.
  autor_miembro  text not null,
  autor_lead_id  bigint references leads(id) on delete cascade,
  created_at     timestamptz not null default now(),
  constraint comunidad_likes_destino check ((post_id is null) <> (comentario_id is null)),
  constraint comunidad_likes_objetivo check (objetivo = case when post_id is not null then 'p:' || post_id::text else 'c:' || comentario_id::text end),
  constraint comunidad_likes_miembro check (
    miembro ~ '^(u|l):[1-9][0-9]*$'
    and ((lead_id is null) = (miembro like 'u:%'))
    and (lead_id is null or miembro = 'l:' || lead_id::text)
  ),
  constraint comunidad_likes_autor check (
    autor_miembro ~ '^(u|l):[1-9][0-9]*$'
    and ((autor_lead_id is null) = (autor_miembro like 'u:%'))
    and (autor_lead_id is null or autor_miembro = 'l:' || autor_lead_id::text)
  ),
  -- Nadie se da like a sí mismo: un like propio sería un punto por cada post que uno escribe.
  constraint comunidad_likes_propio check (miembro <> autor_miembro)
);
create unique index if not exists comunidad_likes_uk on comunidad_likes (workspace_id, objetivo, miembro);
create index if not exists idx_comunidad_likes_puntos on comunidad_likes (workspace_id, producto_id, autor_miembro, created_at);
create index if not exists idx_comunidad_likes_fecha on comunidad_likes (workspace_id, producto_id, created_at);
comment on table comunidad_likes is 'Likes de posts y comentarios. Cada fila es 1 punto para autor_miembro (los puntos se cuentan, no se acumulan).';

-- ── 6. Votos de las encuestas ─────────────────────────────────────────────────────────────────
create table if not exists comunidad_votos (
  id            bigint generated by default as identity primary key,
  workspace_id  bigint not null references workspaces(id) on delete cascade,
  producto_id   bigint not null references productos(id) on delete cascade,
  post_id       bigint not null references comunidad_posts(id) on delete cascade,
  opcion        text not null check (opcion ~ '^o[0-9]{1,2}$'),
  miembro       text not null,
  lead_id       bigint references leads(id) on delete cascade,
  created_at    timestamptz not null default now(),
  updated_at    timestamptz not null default now(),
  constraint comunidad_votos_miembro check (
    miembro ~ '^(u|l):[1-9][0-9]*$'
    and ((lead_id is null) = (miembro like 'u:%'))
    and (lead_id is null or miembro = 'l:' || lead_id::text)
  )
);
-- Un voto por persona por encuesta (cambiar de opción reescribe la fila).
create unique index if not exists comunidad_votos_uk on comunidad_votos (workspace_id, post_id, miembro);
comment on table comunidad_votos is 'Votos de las encuestas de los posts. Uno por miembro por encuesta.';

-- ── 7. Perfiles (por persona y por workspace) ─────────────────────────────────────────────────
-- La bio, los links y la ubicación que la persona elige mostrar, y su última actividad («en línea» =
-- los últimos 5 minutos). Por WORKSPACE y no por producto: la persona es la misma en las dos
-- comunidades de un negocio (en Skool el perfil es uno y el nivel es por grupo).
create table if not exists comunidad_perfiles (
  id                   bigint generated by default as identity primary key,
  workspace_id         bigint not null references workspaces(id) on delete cascade,
  miembro              text not null,
  lead_id              bigint references leads(id) on delete cascade,
  bio                  text not null default '' check (length(bio) <= 300),
  -- `{ web, instagram, youtube, facebook, x, linkedin }`, sólo http/https (sanearPerfil).
  links                jsonb not null default '{}'::jsonb,
  ubicacion            text not null default '' check (length(ubicacion) <= 80),
  ultima_actividad_at  timestamptz,
  created_at           timestamptz not null default now(),
  updated_at           timestamptz not null default now(),
  constraint comunidad_perfiles_miembro check (
    miembro ~ '^(u|l):[1-9][0-9]*$'
    and ((lead_id is null) = (miembro like 'u:%'))
    and (lead_id is null or miembro = 'l:' || lead_id::text)
  )
);
create unique index if not exists comunidad_perfiles_uk on comunidad_perfiles (workspace_id, miembro);
comment on table comunidad_perfiles is 'Perfil de un miembro de la comunidad (bio, links, ubicación) y su última actividad. Uno por persona por workspace.';

-- ── 8. Notificaciones (la campana) ────────────────────────────────────────────────────────────
-- Las escriben lib/comunidad-datos.ts (like, comentario, respuesta, mención, post seguido) y
-- lib/comunidad-calendario.ts (el evento que empieza pronto); las lee lib/comunidad-campana.ts.
create table if not exists comunidad_notificaciones (
  id             bigint generated by default as identity primary key,
  workspace_id   bigint not null references workspaces(id) on delete cascade,
  producto_id    bigint not null references productos(id) on delete cascade,
  para_miembro   text not null check (para_miembro ~ '^(u|l):[1-9][0-9]*$'),
  para_lead_id   bigint references leads(id) on delete cascade,
  tipo           text not null check (tipo in ('like', 'comentario', 'respuesta', 'mencion', 'seguidor', 'post_seguido', 'post_nuevo', 'evento')),
  de_miembro     text check (de_miembro is null or de_miembro ~ '^(u|l):[1-9][0-9]*$'),
  de_lead_id     bigint references leads(id) on delete cascade,
  post_id        bigint references comunidad_posts(id) on delete cascade,
  comentario_id  bigint references comunidad_comentarios(id) on delete cascade,
  -- La FK a comunidad_eventos va abajo (la tabla se crea después), con cascada.
  evento_id      bigint,
  -- El aviso de un evento: la ocurrencia de la que avisa, y la `clave` que lo deduplica
  -- (`e:<evento>:<fecha local>`): abrir la campana diez veces no avisa diez. Null en los demás tipos
  -- (y un NULL no choca con nada en el índice único de abajo).
  ocurrencia     timestamptz,
  clave          text check (clave is null or length(clave) <= 80),
  leida_at       timestamptz,
  created_at     timestamptz not null default now(),
  constraint comunidad_notificaciones_para check ((para_lead_id is null) = (para_miembro like 'u:%'))
);
create index if not exists idx_comunidad_notif_para on comunidad_notificaciones (workspace_id, para_miembro, created_at desc);
create index if not exists idx_comunidad_notif_sin_leer on comunidad_notificaciones (workspace_id, para_miembro) where leida_at is null;
-- Las columnas de la segunda mitad, por si la versión ANTERIOR de esta migración ya se aplicó en alguna
-- base: `create table if not exists` no se las agrega a una tabla que ya existe. Van ANTES del índice
-- que las usa. Sobre una base nueva no hacen nada.
alter table comunidad_notificaciones add column if not exists ocurrencia timestamptz;
alter table comunidad_notificaciones add column if not exists clave text;
-- COMPLETO (no parcial) a propósito: un upsert de PostgREST no puede apuntar a un índice parcial.
create unique index if not exists comunidad_notificaciones_clave_uk on comunidad_notificaciones (workspace_id, para_miembro, clave);
comment on table comunidad_notificaciones is 'La campana de la comunidad: likes, comentarios, respuestas, menciones, seguidores, posts seguidos y eventos.';

-- ── 9. Seguimientos: seguir un post (la campana del post) o a una persona ─────────────────────
-- El autor sigue lo suyo por default (se escribe al publicar) y lo puede dejar de seguir: sin fila,
-- no le llegan los comentarios nuevos de su post. Seguir a una persona todavía no tiene pantalla.
create table if not exists comunidad_seguimientos (
  id             bigint generated by default as identity primary key,
  workspace_id   bigint not null references workspaces(id) on delete cascade,
  producto_id    bigint not null references productos(id) on delete cascade,
  miembro        text not null,
  lead_id        bigint references leads(id) on delete cascade,
  -- `p:<post>` o `m:<clave del miembro seguido>`: una columna para el índice único completo.
  objetivo       text not null check (objetivo ~ '^(p:[1-9][0-9]*|m:(u|l):[1-9][0-9]*)$'),
  post_id        bigint references comunidad_posts(id) on delete cascade,
  sigue_miembro  text,
  sigue_lead_id  bigint references leads(id) on delete cascade,
  created_at     timestamptz not null default now(),
  constraint comunidad_seguimientos_destino check ((post_id is null) <> (sigue_miembro is null)),
  constraint comunidad_seguimientos_miembro check (
    miembro ~ '^(u|l):[1-9][0-9]*$'
    and ((lead_id is null) = (miembro like 'u:%'))
    and (lead_id is null or miembro = 'l:' || lead_id::text)
  )
);
create unique index if not exists comunidad_seguimientos_uk on comunidad_seguimientos (workspace_id, producto_id, objetivo, miembro);
comment on table comunidad_seguimientos is 'Quién sigue qué: un post (avisa de comentarios nuevos) o a una persona (avisa cuando postea).';

-- ── 10. Baneos («sacar a alguien de la comunidad») ────────────────────────────────────────────
-- El portón del alumno (`actorDelAlumno`) los LEE: un baneado vigente no entra, ni a leer. NO corta
-- el curso (eso es `curso_accesos`). Volver a admitir pone `levantado_at`; volver a sacar reescribe la
-- fila (el índice único es uno por persona y comunidad).
create table if not exists comunidad_baneos (
  id               bigint generated by default as identity primary key,
  workspace_id     bigint not null references workspaces(id) on delete cascade,
  producto_id      bigint not null references productos(id) on delete cascade,
  miembro          text not null check (miembro ~ '^l:[1-9][0-9]*$'),
  lead_id          bigint not null references leads(id) on delete cascade,
  motivo           text not null default '' check (length(motivo) <= 300),
  por              text,
  borro_contenido  boolean not null default false,
  levantado_at     timestamptz,
  created_at       timestamptz not null default now(),
  constraint comunidad_baneos_lead check (miembro = 'l:' || lead_id::text)
);
create unique index if not exists comunidad_baneos_uk on comunidad_baneos (workspace_id, producto_id, miembro);
comment on table comunidad_baneos is 'Alumnos sacados de la comunidad de un producto. Vigente mientras levantado_at sea null.';

-- ── 11. Eventos (el calendario) ───────────────────────────────────────────────────────────────
-- La regla de una serie (sus ocurrencias, el horario de verano, «este / este y los siguientes /
-- todos», el .ics) vive en lib/comunidad-eventos.ts, pura y con test.
create table if not exists comunidad_eventos (
  id             bigint generated by default as identity primary key,
  workspace_id   bigint not null references workspaces(id) on delete cascade,
  producto_id    bigint not null references productos(id) on delete cascade,
  titulo         text not null check (length(btrim(titulo)) between 1 and 120),
  descripcion    text not null default '' check (length(descripcion) <= 4000),
  -- El primer inicio, en UTC, y la zona en la que se ELIGIÓ. Cada ocurrencia se arma desde la FECHA
  -- local de la anterior + la hora de pared de ésta, con dos pasadas (AGENTS.md, «un horario que se
  -- repite se ancla en la ocurrencia anterior»): sumar 7 días en milisegundos deriva una hora en el
  -- cambio de horario.
  inicio         timestamptz not null,
  zona           text not null check (length(zona) between 1 and 64),
  duracion_min   int not null default 60 check (duracion_min between 30 and 1440),
  -- `{ frecuencia: diaria|semanal|mensual, cada, dias: [0-6], fin: { tipo: nunca|fecha|veces, fecha?, veces? } }`
  -- o null (no se repite).
  recurrencia    jsonb,
  -- Las FECHAS locales (`'2026-10-15'`) que la serie no tiene: borradas o movidas («este evento»). Por
  -- fecha y no por instante: una serie tiene a lo sumo una por día, y la fecha sobrevive a que se le
  -- cambie la hora a «todos».
  excepciones    jsonb not null default '[]'::jsonb,
  -- `serie_de`: el evento del que nació éste. Dos casos:
  --   · con `ocurrencia_fecha` → es UNA ocurrencia movida («editar este evento»): reemplaza esa fecha
  --     de la serie (que la tiene en `excepciones`) y se borra con la serie («todos»);
  --   · sin `ocurrencia_fecha` → es la serie nueva de «este y los siguientes» (otra serie, sobrevive).
  serie_de       bigint references comunidad_eventos(id) on delete set null,
  ocurrencia_fecha date,
  lugar_tipo     text not null default 'link' check (lugar_tipo in ('link', 'direccion')),
  lugar          text not null default '' check (length(lugar) <= 600),
  -- Lo que devuelve el selector de portadas (lib/portadas.ts, `saneaPortada`): `grad:<id>` o una foto
  -- https de un origen permitido. Null = sin portada.
  portada        text check (portada is null or length(portada) <= 600),
  -- Quién puede entrar: `{ tipo: 'todos' }`, `{ tipo: 'nivel', nivel }` o `{ tipo: 'modulo', clave }`
  -- (los que tienen ese módulo del curso en sus permisos, `curso_accesos.alcance`).
  acceso         jsonb not null default '{"tipo":"todos"}'::jsonb,
  creado_por     text,
  created_at     timestamptz not null default now(),
  updated_at     timestamptz not null default now()
);
