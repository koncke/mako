-- 0171 — funnel_ofertas: la N:M de la respuesta 1 del dueño
-- =============================================================================
-- Es la **0127** del documento `docs/modelo-oferta-producto-funnel.md` (§2).
-- Renumerada. Va ÚLTIMA porque necesita las dos tablas anteriores:
--     0169 (ofertas) → 0170 (funnels) → **0171 (funnel_ofertas)**
--
-- ⛔ ORDEN DE DESPLIEGUE — **ANTES O JUNTO** CON EL DEPLOY, igual que las otras dos
--    (AGENTS.md § «toda migración decide su orden de despliegue y lo dice en su
--    cabecera»). Degrada más suave que la 0169: `ofertasDeFunnels()` está envuelta
--    en `.catch(() => [])`, así que sin la tabla la pantalla de ofertas carga y lo
--    único que falta son los chips de funnel; ligar una oferta a un funnel sí da
--    error. Aun así va antes: la pantalla se entrega entera o no se entrega.
--
-- Por qué la arista va a la OFERTA y no al producto: «TOFU distinto, BOFU
-- compartido» son dos funnels vendiendo lo mismo con distinta entrada. Si el
-- funnel colgara del producto, no habría dónde guardar que el funnel orgánico
-- promete otra garantía y otro bono que el de ads. Eso es una OFERTA distinta
-- sobre el MISMO producto.
--
-- Molde: nutricion_inscripciones (0034:28-43), la ÚNICA junction N:M con
-- atributos propios del repo. Se copia: PK propia (no compuesta), FKs not null
-- on delete cascade, workspace_id PROPIO (getTenantDb filtra y estampa POR esa
-- columna — no la hereda de las FK) y DOS índices.
-- =============================================================================

begin;

create table if not exists funnel_ofertas (
  id           bigint generated by default as identity primary key,
  workspace_id bigint not null references workspaces(id),
  funnel_id    bigint not null references funnels(id) on delete cascade,
  oferta_id    bigint not null references ofertas(id) on delete cascade,
  -- Qué se ofrece PRIMERO en el wizard de cierre y cuál es el foco por defecto del
  -- writer. Es una decisión DECLARADA, nunca array[0] (AGENTS.md: «lo que se ve sin
  -- abrir se elige a mano, nunca por el índice de un array»).
  es_principal boolean not null default false,
  orden        int not null default 0,
  origen       text not null default 'manual',  -- 'manual'|'propuesto'|'migracion'
  created_at   timestamptz not null default now(),
  unique (funnel_id, oferta_id)
);
create unique index if not exists funnel_ofertas_principal_uk on funnel_ofertas (funnel_id) where es_principal;
create index if not exists idx_funnel_ofertas_oferta on funnel_ofertas (oferta_id);
create index if not exists idx_funnel_ofertas_ws     on funnel_ofertas (workspace_id);

-- El N:M producto ↔ funnel que pidió el dueño: DERIVADO, no una tercera tabla que
-- alguien tenga que mantener sincronizada.
create or replace view v_funnel_productos as
select fo.workspace_id, fo.funnel_id, op.producto_id, op.rol,
       bool_or(fo.es_principal and op.rol = 'principal') as es_principal
from funnel_ofertas fo
join oferta_productos op on op.oferta_id = fo.oferta_id
group by fo.workspace_id, fo.funnel_id, op.producto_id, op.rol;

comment on view v_funnel_productos is
  'Qué productos vende un funnel. DERIVADO de funnel_ofertas ⋈ oferta_productos: producto↔funnel no tiene tabla propia a propósito (AGENTS.md § Una cosa, un lugar).';

-- ⛔ UNA VISTA NO TIENE RLS, Y ESA ES LA TRAMPA. `alter table … enable row level
-- security` no existe para una vista, y una vista corre con los permisos de SU
-- DUEÑO: aunque `funnel_ofertas` y `oferta_productos` tengan RLS, quien pueda
-- hacerle SELECT a la vista lee las filas de TODOS los workspaces.
--
-- Que el grant llegue o no depende de QUIÉN aplique el DDL, y por eso el revoke
-- va explícito igual que en cada tabla. Medido en prod el 26/09:
--   · `v_cohortes_semanales` (vista, mig 0001) tiene HOY `anon=arwdDxtm` y
--     `security_invoker` apagado.
--   · `funnel_config` y `productos`, aplicadas con el `postgres` de
--     scripts/apply-migration.mjs, tienen sólo postgres+service_role.
-- O sea: el camino del grant a `anon` es real en este proyecto y lo único que
-- mantiene afuera a las tablas nuevas es este revoke. La vista era el único
-- objeto de las tres migraciones que no lo tenía.
--
-- `security_invoker = on` es la segunda capa: con ella la vista deja de prestar
-- los permisos del dueño y el RLS de las dos tablas de abajo vuelve a aplicar.
-- El servidor sigue leyendo con service_role, que no cambia.
alter view v_funnel_productos set (security_invoker = on);
revoke all on v_funnel_productos from anon, authenticated;

-- Backfill: el funnel default vende la oferta principal, si las dos existen.
-- Hoy no existe ninguna oferta todavía (el seed es de F2, en TypeScript), así que
-- esto copia 0 filas y queda acá para cuando el seed corra.
insert into funnel_ofertas (workspace_id, funnel_id, oferta_id, es_principal, origen)
select o.workspace_id, f.id, o.id, true, 'migracion'
from ofertas o
join funnels f on f.workspace_id = o.workspace_id and f.es_default
where o.es_principal
  and not exists (select 1 from funnel_ofertas fo where fo.funnel_id = f.id and fo.oferta_id = o.id);

-- RLS on sin políticas = solo server-side (service_role), igual que el resto.
alter table funnel_ofertas enable row level security;
revoke all on funnel_ofertas from anon, authenticated;

commit;

notify pgrst, 'reload schema';
