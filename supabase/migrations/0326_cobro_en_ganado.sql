-- =============================================================================
-- 0326 · «Vincular cobro» en el ⋯ de la etapa Ganado (22/10/2026, punto 3 del feedback de Martín)
-- =============================================================================
-- La etapa Ganado de un CRM se vincula a un producto del catálogo, cobrable por una o varias cuentas (Stripe y Mercado
-- Pago a la vez). Cuando alguien paga ese producto, pasa a Ganado EN ESE CRM, con su plan (lib/cobro-etapa.ts).
--
--   · productos.cuotas: en cuántos pagos se cobra un producto de pago único (null = uno). El primero lo cobra el link;
--     el resto queda como el plan del trato (la regla está en `planDelProducto`).
--   · cobro_etapa_vinculos: el vínculo. UN producto cobra en UN CRM a la vez (el índice único de abajo): un pago del
--     producto tiene que saber a qué trato va, sin elegir entre dos.
--
-- Sólo lo lee y escribe el servidor (service role, `getTenantDb`): sin acceso de anon ni authenticated.
-- =============================================================================

begin;

alter table productos add column if not exists cuotas smallint;
do $$
begin
  if not exists (select 1 from pg_constraint where conname = 'productos_cuotas_check') then
    alter table productos add constraint productos_cuotas_check check (cuotas is null or cuotas between 1 and 7);
  end if;
end $$;
comment on column productos.cuotas is 'En cuántos pagos se cobra un producto de pago único (mig 0326). null = uno. El link cobra el primero; el resto es el plan del trato.';

create table if not exists cobro_etapa_vinculos (
  id           bigint generated by default as identity primary key,
  workspace_id bigint not null references workspaces(id) on delete cascade,
  funnel_id    bigint not null references funnels(id) on delete cascade,
  etapa        text not null check (char_length(etapa) between 1 and 80),
  producto_id  bigint not null references productos(id) on delete cascade,
  -- Las cuentas que lo cobran: 'stripe:principal', 'mercadopago:principal', y las que se sumen (`CuentaPago.id`).
  cuentas      text[] not null default '{}',
  creado_por   text,
  created_at   timestamptz not null default now(),
  updated_at   timestamptz not null default now()
);
create unique index if not exists cobro_etapa_vinculos_un_crm_por_producto on cobro_etapa_vinculos (workspace_id, producto_id);
create index if not exists cobro_etapa_vinculos_etapa_idx on cobro_etapa_vinculos (workspace_id, funnel_id, etapa);

comment on table cobro_etapa_vinculos is 'La etapa (Ganado) de un CRM vinculada a un producto (mig 0326): quien paga ese producto pasa a esa etapa con su plan. lib/cobro-etapa.ts.';

alter table cobro_etapa_vinculos enable row level security;
revoke all on cobro_etapa_vinculos from anon, authenticated;

-- El cobro guarda lo que cobró y a qué trato fue (revisión adversarial del 22/10/2026):
--   · plan_producto: el precio y las cuotas del producto AL CREAR el link ({precio, cuotas}). El plan del trato sale de acá,
--     no del producto de hoy: editarlo entre el link y el pago armaba un plan que no era el que se cobró.
--   · trato_estado / trato_at / trato: el trato se RECLAMA antes de armarse (compare-and-set: 'armando', y a los 2 minutos
--     se puede volver a reclamar) y queda escrito al terminar ('listo'). Dos avisos del mismo pago no arman dos tratos, y un
--     reembolso sabe si ese pago armó un plan.
alter table cobros
  add column if not exists plan_producto jsonb,
  add column if not exists trato_estado  text,
  add column if not exists trato_at      timestamptz,
  add column if not exists trato         jsonb;
do $$
begin
  if not exists (select 1 from pg_constraint where conname = 'cobros_trato_estado_check') then
    alter table cobros add constraint cobros_trato_estado_check check (trato_estado is null or trato_estado in ('armando', 'listo'));
  end if;
end $$;
comment on column cobros.plan_producto is 'El precio y las cuotas del producto al crear el link (mig 0326): el plan del trato sale de acá, no del producto de hoy.';
comment on column cobros.trato is 'A qué trato fue el pago y si armó un plan (mig 0326, lib/cobro-etapa-server.ts). trato_estado: armando | listo.';

commit;
