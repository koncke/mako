-- ⚠️ ORDEN DE DESPLIEGUE: ANTES del deploy. Las dos tablas son NUEVAS y el código nuevo las
-- LEE al dibujar la ficha del lead, el CRUD, el selector del paso «⚡ Acción» y —del lado del
-- motor— las condiciones y el disparador por etiqueta. Sin ellas la ficha no puede listar las
-- etiquetas y poner una falla al guardar. Agrega y no saca nada: la versión desplegada no
-- mira ninguna de estas cosas.
--
-- Pedido de Martín (08/10/2026, punto 12 del rediseño de /chatbot), textual: «Deberías agregar
-- todo un sistema de ETIQUETAS... si no respondió, se le pone la etiqueta de seguimiento. Si
-- respondió y está cualificado, se le pone la etiqueta de "Cualificado"... Pero esas etiquetas
-- debería poder editarse, como un CRUD, que el usuario elija qué nombres ponerles y si están
-- vinculadas a etapas del CRM. Y claro, debería también poder salir acciones y CRON desde
-- etiquetas... esas mismas etiquetas que se asignan en MaKo, se pongan en esas ambas
-- plataformas.» El contrato entre las partes, en docs/chatbot-flujo-ramas-diseno.md.
