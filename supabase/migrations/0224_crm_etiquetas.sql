-- ── 1. crm_etiquetas ─────────────────────────────────────────────────────────
-- El catálogo. TODO lo que apunta a una etiqueta (condiciones del flujo, disparadores,
-- `nutricion_secuencias.etiqueta_id`, la fila del lead) guarda su ID, NUNCA el nombre: ManyChat
-- referencia por nombre y se rompe al renombrar (docs/hallazgos-comunicacion.md), y acá ya pasó
-- con `desenlace.logradoSecuencia`. El nombre es sólo para mostrar.
--   · `funnel_id` + `etapa_key`: el vínculo a una etapa del CRM va SIEMPRE como el PAR. Las keys
--     de etapa se REPITEN entre productos del mismo workspace (medido: ws11 tiene 3 productos con
--     las mismas 5 keys), así que la key sola no dice de qué tablero es. `funnel_id` NULL = el
--     producto del negocio (el embudo default), la misma convención que `leads.funnel_id`.
--     Un `funnel_id` sin `etapa_key` no significa nada: lo rechaza el CHECK.
--   · `wa_instance` + `wa_label_id`: a qué etiqueta del CELULAR corresponde (WhatsApp no oficial,
--     Evolution). Van juntas porque el id de una etiqueta es de UN número: cambia al re-escanear
--     otro y choca entre dos líneas del mismo workspace (mig 0198). Evolution 2.3.7 no expone
--     CREAR etiquetas: se elige una que ya existe en el celular.
--   · `chatwoot_label`: el slug con el que se creó en Chatwoot (oficial). Se GUARDA y no se
--     recalcula: Chatwoot pasa el título a minúscula y sin espacios, y renombrar en MaKo no
--     renombra allá.
--   · `archivada_at`: no se borra nunca una etiqueta que algo usa (lib/etiquetas.ts cuenta las
--     secuencias y las condiciones antes). La unicidad del nombre es entre las NO archivadas, así
--     que se puede volver a crear una con el nombre de una archivada.
create table if not exists crm_etiquetas (
  id            bigint generated by default as identity primary key,
  workspace_id  bigint not null references workspaces(id) on delete cascade,
  nombre        text not null check (length(btrim(nombre)) between 1 and 40),
  color         text not null default '#5E81AC' check (color ~ '^#[0-9A-Fa-f]{6}$'),
  emoji         text check (emoji is null or length(emoji) between 1 and 16),
  funnel_id     bigint references funnels(id) on delete set null,
  etapa_key     text check (etapa_key is null or length(btrim(etapa_key)) between 1 and 60),
  wa_instance   text,
  wa_label_id   text,
  chatwoot_label text check (chatwoot_label is null or length(chatwoot_label) between 1 and 255),
  orden         int not null default 0,
  archivada_at  timestamptz,
  created_at    timestamptz not null default now(),
  updated_at    timestamptz not null default now(),
  constraint crm_etiquetas_vinculo check (funnel_id is null or etapa_key is not null),
  constraint crm_etiquetas_whatsapp check ((wa_instance is null) = (wa_label_id is null))
);
-- El nombre, único por negocio entre las vivas y sin mirar mayúsculas ni espacios de los bordes.
-- El mismo criterio lo aplica el código antes de insertar (`claveNombre`, lib/etiquetas-reglas.ts):
-- esto es la red para dos altas en paralelo.
create unique index if not exists crm_etiquetas_nombre_uk
  on crm_etiquetas (workspace_id, lower(btrim(nombre))) where archivada_at is null;
-- Para la FK compuesta de abajo: una fila de un lead sólo puede nombrar una etiqueta de SU negocio.
create unique index if not exists crm_etiquetas_ws_id_uk on crm_etiquetas (workspace_id, id);
-- El espejo con las etapas busca «qué etiquetas cuelgan de esta etapa» en cada movimiento.
create index if not exists crm_etiquetas_etapa on crm_etiquetas (workspace_id, etapa_key) where etapa_key is not null;

comment on table crm_etiquetas is 'Etiquetas del CRM de cada negocio. Todo lo que apunta a una etiqueta guarda su id. Vínculo opcional a una etapa como el par (funnel_id, etapa_key), NULL = producto del negocio. wa_instance+wa_label_id: la etiqueta del celular (Evolution); chatwoot_label: el slug creado en Chatwoot.';

-- ⚠️ BORRAR UN PRODUCTO NO PUEDE DEJAR UN VÍNCULO A MEDIAS. Con sólo `on delete set null`, el
-- `funnel_id` pasaría a NULL y la `etapa_key` quedaría: el vínculo pasaría a leerse como «esa
-- etapa del producto del NEGOCIO», que es otro tablero, y la etiqueta empezaría a mover leads
-- donde nadie la ató. Este trigger suelta el PAR antes de que el borrado llegue a la FK.
create or replace function crm_etiquetas_soltar_producto() returns trigger
language plpgsql set search_path = public as $$
begin
  update crm_etiquetas set funnel_id = null, etapa_key = null, updated_at = now()
  where funnel_id = old.id and workspace_id = old.workspace_id;
  return old;
end $$;
revoke all on function crm_etiquetas_soltar_producto() from public, anon, authenticated;
drop trigger if exists crm_etiquetas_soltar_producto on funnels;
create trigger crm_etiquetas_soltar_producto before delete on funnels
  for each row execute function crm_etiquetas_soltar_producto();

alter table crm_etiquetas enable row level security;
revoke all on crm_etiquetas from anon, authenticated;

-- ── 2. crm_lead_etiquetas ────────────────────────────────────────────────────
-- Qué lead tiene qué etiqueta. La ÚNICA puerta de escritura es lib/etiquetas.ts (`ponerEtiqueta`
-- / `sacarEtiqueta`): ahí vive la idempotencia, el historial del lead, el disparo de las
-- automatizaciones (salvo en lote) y la sincronización con WhatsApp y Chatwoot.
--   · unique (lead_id, etiqueta_id): poner dos veces es UNA fila, y el segundo intento se entera
--     (`yaEstaba`) porque el insert con ignore-duplicates no devuelve nada.
--   · `puesta_por`: el mismo vocabulario que `lead_audit.autor` (una persona, «MaKo», «MaKo ·
--     automatización «x»»).
--   · Lo lee también el motor de /chatbot: la condición «tiene la etiqueta X» y el cohorte del
--     disparador `etiqueta_puesta` (parte M del rediseño).
create table if not exists crm_lead_etiquetas (
  id           bigint generated by default as identity primary key,
  workspace_id bigint not null references workspaces(id) on delete cascade,
  lead_id      bigint not null references leads(id) on delete cascade,
  etiqueta_id  bigint not null,
  puesta_at    timestamptz not null default now(),
  puesta_por   text not null default 'CRM',
  constraint crm_lead_etiquetas_uk unique (lead_id, etiqueta_id),
  constraint crm_lead_etiquetas_etiqueta_fk foreign key (workspace_id, etiqueta_id)
    references crm_etiquetas (workspace_id, id) on delete cascade
);
-- «Los leads con la etiqueta X»: el cohorte del disparador, el segmento de email y el conteo del CRUD.
create index if not exists crm_lead_etiquetas_por_etiqueta on crm_lead_etiquetas (workspace_id, etiqueta_id);

comment on table crm_lead_etiquetas is 'Qué lead tiene qué etiqueta (crm_etiquetas). Se escribe SÓLO por lib/etiquetas.ts (ponerEtiqueta/sacarEtiqueta). puesta_por con el vocabulario de lead_audit.autor.';

alter table crm_lead_etiquetas enable row level security;
revoke all on crm_lead_etiquetas from anon, authenticated;
