-- 0276 — Los pedidos del «Botón de pago» de una landing: el candado y el techo
-- =============================================================================
-- ⚠️ ORDEN DE DESPLIEGUE: ANTES o JUNTO con el deploy que trae `ejecutarPago`
-- (lib/editor-landing/pago-pedido.ts). El código nuevo TOLERA que la tabla falte (PGRST205/42P01):
-- corre sin candado ni techo, como antes, y lo dice en el log — pero mientras falte, un doble clic en
-- «Ir a pagar» sigue dejando dos fichas y dos checkouts. Agrega y no saca nada: la versión desplegada no
-- la nombra, así que aplicarla antes no le molesta a nadie.
--
-- (Si al integrar alguien ya tomó el 0276, se renumera ANTES de aplicarla: el 14/10/2026 main llegaba a
-- 0274 y la 0275 la tenía el worktree de chats.)
--
-- Revisión de la tanda 4 del editor de landings (14/10/2026, dos hallazgos MEDIA):
--
-- · EL CANDADO. El POST público del paso de pago (app/api/landing-generator/pagar) busca el lead por
--   email y, si no está, lo crea; después reusa el cobro pendiente o crea uno. Son lecturas seguidas de
--   escrituras, y ni `leads` tiene un único por email ni `cobros` uno por (lead, producto, pendiente): dos
--   pedidos a la vez (un doble clic, que en un formulario sin JavaScript es lo esperable) dejaban DOS
--   fichas de la misma persona en el CRM del cliente y dos Checkout Sessions en su Stripe. Cada pedido
--   toma un candado: una fila `en_curso` por `clave`, con el índice único PARCIAL de abajo. El segundo
--   choca (23505), espera a que el primero la suelte (`en_curso = false`) y entonces encuentra la ficha
--   y el pendiente que dejó: redirige al MISMO checkout. Una fila colgada (la función murió) se suelta
--   pasados 90 s (`CANDADO_VENCE_MS`, la ruta corta a los 60).
--   `clave` = sha256 de «<workspace>:<email comparable>»: POR NEGOCIO, porque la ficha es del negocio
--   (dos landings suyas a la vez también la duplicarían). La tabla no guarda el email.
-- · EL TECHO. Los topes de antes (por IP y por email) viven en la memoria de cada instancia
--   (lib/rate-limit.ts: «best-effort»). Las filas de acá cuentan los pedidos de una landing en la última
--   hora en la BASE (`TECHO_PAGOS_HORA`), sin importar qué instancia atiende.
--
-- Sin `workspace_id` a propósito: es un registro interno de la plataforma, colgado de la landing
-- (`doc_id`, que borra en cascada) y leído SÓLO por el server con el cliente crudo y el `doc_id` de la
-- fila de la landing. No va en TENANT_TABLES (lib/workspace.ts): ese proxy le agregaría un
-- `.eq('workspace_id')` a una columna que no existe.
--
-- ⚠️ Crece con cada pedido de pago (con el techo: como mucho 120 filas por landing y hora). Nadie las
-- poda todavía: queda anotado en docs/hallazgos-editor-landing.md.
-- =============================================================================
begin;

create table if not exists landing_pago_pedidos (
  id            bigint generated by default as identity primary key,
  doc_id        bigint not null references landing_docs(id) on delete cascade,
  clave         text not null check (clave ~ '^[0-9a-f]{64}$'),
  en_curso      boolean not null default true,
  -- Lo que pasó (redirigir, no-disponible, fallo, excepcion, vencido): para mirar después, no decide nada.
  resultado     text check (resultado is null or char_length(resultado) <= 40),
  created_at    timestamptz not null default now(),
  terminado_at  timestamptz
);

-- El candado: UN pedido en curso por clave. Parcial: los terminados no bloquean a nadie.
create unique index if not exists landing_pago_pedidos_en_curso_uk on landing_pago_pedidos (clave) where en_curso;
-- El techo cuenta los pedidos de una landing desde hace una hora.
create index if not exists landing_pago_pedidos_doc_fecha_idx on landing_pago_pedidos (doc_id, created_at);

comment on table landing_pago_pedidos is
  'Pedidos del Botón de pago de una landing: candado por (negocio, email) y techo por landing y hora. Sin email (clave = sha256). Mig 0276.';

-- RLS sin políticas = sólo el server (service_role). Y el revoke explícito: que el grant llegue o no
-- depende de quién aplique el DDL (AGENTS.md, «Toda migración decide su ORDEN»).
alter table landing_pago_pedidos enable row level security;
revoke all on landing_pago_pedidos from anon, authenticated;

commit;
