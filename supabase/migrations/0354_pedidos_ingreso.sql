-- =============================================================================
-- Martín, 30/10: «Me llegó una solicitud de ingreso de Gabriela González por la landing, eso como en agencia debería
-- aparecerme en super admin para aceptarla». Medido ese día: quien entraba con Google sin tener cuenta veía «no autorizada» y
-- no quedaba NADA, ni un registro ni un aviso. Los que no tenían el WhatsApp de Martín se iban sin que nadie se enterara.
--
--   · Una fila por correo: quien insiste suma `intentos`, no filas (y el aviso sale una sola vez).
--   · `correo_verificado`: true sólo si lo dijo Google. Los pedidos de /planes llegan con el correo que escribió la persona: se
--     ven con ese rótulo, para que aceptar uno sea una decisión con esa información.
--   · No hay estado «aceptado»: aceptar es crear la cuenta, y la bandeja no muestra a quien ya tiene usuario. Dos lugares que
--     dijeran si tiene cuenta podrían contradecirse.
--   · `descartado` se guarda, no se borra: si no, quien insiste volvería a la bandeja y a mandar el aviso.
--
-- DE LA PLATAFORMA (RLS sin acceso para anon/authenticated, como partner_creditos): todo con el cliente de servicio.
-- TODO ADITIVO: una tabla nueva, que ninguna lectura vieja mira. Seguro de re-ejecutar. Sin la tabla, entrar y pedir un plan
-- funcionan igual: el registro es best effort y la pantalla de login dice lo de siempre.
-- =============================================================================

create table if not exists pedidos_ingreso (
  id bigint generated by default as identity primary key,
  email text not null check (email = lower(email) and char_length(email) between 3 and 254),
  nombre text check (nombre is null or char_length(nombre) <= 200),
  origen text not null check (origen in ('google', 'planes')),
  correo_verificado boolean not null default false,
  detalle text check (detalle is null or char_length(detalle) <= 300),
  whatsapp text check (whatsapp is null or whatsapp ~ '^[0-9]{8,15}$'),
  lead_id bigint,
  intentos integer not null default 1 check (intentos >= 1),
  primer_at timestamptz not null default now(),
  ultimo_at timestamptz not null default now(),
  estado text not null default 'pendiente' check (estado in ('pendiente', 'descartado')),
  decidido_por text,
  decidido_at timestamptz
);

create unique index if not exists pedidos_ingreso_email_uq on pedidos_ingreso (email);
create index if not exists pedidos_ingreso_pendientes_idx on pedidos_ingreso (ultimo_at desc) where estado = 'pendiente';

alter table pedidos_ingreso enable row level security;

