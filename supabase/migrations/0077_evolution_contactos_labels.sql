-- =============================================================================
-- 0077_evolution_contactos_labels — nombres/fotos + etiquetas del WhatsApp no oficial
-- =============================================================================
-- (1) evolution_contactos: nombre + foto de perfil del contacto, del evento
--     contacts.upsert de Evolution (así no pedimos fetchProfilePictureUrl en vivo).
-- (2) evolution_labels: catálogo de etiquetas de WhatsApp del número (labels.edit).
-- (3) evolution_stage_labels: mapeo etapa del funnel → etiqueta (para auto-etiquetar).
-- Todo por workspace, a nivel app.

begin;

create table if not exists evolution_contactos (
  id           bigint generated by default as identity primary key,
  workspace_id bigint not null default 1 references workspaces(id) on delete cascade,
  telefono     text not null,                     -- normalizado (dígitos)
  nombre       text,
  foto_url     text,
  updated_at   timestamptz not null default now()
);
create unique index if not exists uq_evolution_contactos_tel on evolution_contactos (workspace_id, telefono);
alter table evolution_contactos enable row level security;

create table if not exists evolution_labels (
  id           bigint generated by default as identity primary key,
  workspace_id bigint not null default 1 references workspaces(id) on delete cascade,
  label_id     text not null,                     -- id de la etiqueta en WhatsApp
  name         text,
  color        int,
  updated_at   timestamptz not null default now()
);
create unique index if not exists uq_evolution_labels_lid on evolution_labels (workspace_id, label_id);
alter table evolution_labels enable row level security;

create table if not exists evolution_stage_labels (
  id           bigint generated by default as identity primary key,
  workspace_id bigint not null default 1 references workspaces(id) on delete cascade,
  etapa        text not null,                     -- key de etapa del funnel (derivarEtapa)
  label_id     text not null,                     -- etiqueta de WhatsApp a poner en esa etapa
  updated_at   timestamptz not null default now()
);
create unique index if not exists uq_evolution_stage_labels on evolution_stage_labels (workspace_id, etapa);
alter table evolution_stage_labels enable row level security;

commit;
