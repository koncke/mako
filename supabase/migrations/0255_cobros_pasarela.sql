-- =============================================================================
-- 0255 — cobros: la pasarela de pagos (Stripe y Mercado Pago), su rastro y la cuota que salda
-- =============================================================================
-- ⚠️ ORDEN DE DESPLIEGUE: ANTES del deploy que trae lib/cobros.ts, app/api/webhooks/stripe,
-- app/api/webhooks/mercadopago y la tab Pagos de la ficha. El código nuevo LEE `cobros` y las
-- columnas nuevas de `pagos` (un select de PostgREST con una columna que no existe rechaza la
-- consulta ENTERA). Agrega y no saca nada: la versión desplegada no la mira, así que aplicarla antes
-- no le molesta a nadie.
--
-- Pedido de Martín (11/10/2026), textual: «Esta tab se llama "Integraciones". Quiero que implementes
-- end-to-end la integración con Mercado Pago y con Stripe, tipo pasarela de pagos... Lo voy a utilizar
-- yo como superadmin para vender MaKo, pero también los usuarios pueden alojarlo...». El contrato
-- entero está en docs/diseno-pasarela-pagos.md.
--
-- TRES COSAS:
--   · `cobros`: UN pago que MaKo le pide a UNA persona con UNA pasarela. La crea MaKo (la ficha, la
--     API, el super admin) y tiene un link público estable /pagar/<token>. NO se llama `pagos`: esa
--     tabla YA EXISTE y son las CUOTAS del CRM (mig 0014). La moneda va en una columna, no en el
--     nombre (AGENTS.md «Un campo con una moneda o un país en el NOMBRE»): `monto_usd` es sólo el
--     valor en dólares para los reportes, y null cuando nadie lo declaró (nunca se inventa una tasa).
--   · `pasarela_eventos`: la deduplicación y el rastro de los avisos de las pasarelas (molde:
--     email_entrantes, 0245). Stripe y Mercado Pago REINTENTAN: el reintento choca con el único
--     (proveedor, evento_id) en vez de cobrar dos veces en el CRM. `workspace_id` admite null: un
--     aviso que no es de ningún negocio también queda escrito, con su motivo.
--   · `pagos` gana de qué cobro y de qué pasarela salió cada cuota. El único parcial
--     (workspace_id, proveedor, proveedor_pago_id) es lo que hace idempotente la RENOVACIÓN de una
--     suscripción: cada factura cobrada es una cuota nueva, y su reentrega choca acá.
--
-- ⚠️ `cobros.workspace_id` va SIN default: el 1 es Mauricio, un cliente, y un default le atribuye a
-- él lo de otro (tests/eliminar-workspace.test.ts).
--
-- ⚠️ Y VA A LAS DOS LISTAS DE INQUILINO, que el compilador no ve:
--   · `cobros` → TENANT_TABLES (lib/workspace.ts; sin ella getTenantDb es PASSTHROUGH y una lectura
--     devolvería los cobros de TODOS los negocios) y TABLAS_DE_INQUILINO (lib/tablas-de-inquilino.ts).
--   · `pasarela_eventos` → sólo TABLAS_DE_INQUILINO (workspace nullable, como email_entrantes).

begin;

create table if not exists cobros (
  id                       bigint generated by default as identity primary key,
  workspace_id             bigint not null references workspaces(id) on delete cascade,
  -- Público: /pagar/<token>. 32 caracteres base64url al azar (192 bits): no se adivina ni se enumera.
  token                    text not null check (token ~ '^[A-Za-z0-9_-]{32}$'),
  lead_id                  bigint references leads(id) on delete set null,
  -- La cuota del CRM que salda, si el link salió de una. `set null`: saveLeadPlanManual BORRA y
  -- reinserta las cuotas no pagadas, y un link no puede impedirlo.
  pago_id                  bigint references pagos(id) on delete set null,
  producto_id              bigint references productos(id) on delete set null,
  proveedor                text not null check (proveedor in ('stripe', 'mercadopago')),
  modo                     text not null default 'real' check (modo in ('real', 'prueba')),
  tipo                     text not null check (tipo in ('unico', 'suscripcion')),
  concepto                 text not null check (char_length(concepto) between 1 and 200),
  monto                    numeric(14, 2) not null check (monto > 0),
  moneda                   text not null check (moneda ~ '^[A-Z]{3}$'),
  monto_usd                numeric(12, 2) check (monto_usd is null or monto_usd > 0),
  email                    text check (email is null or char_length(email) <= 320),
  nombre                   text check (nombre is null or char_length(nombre) <= 200),
  estado                   text not null default 'pendiente'
                             check (estado in ('pendiente', 'pagado', 'fallido', 'reembolsado', 'anulado')),
  suscripcion_estado       text check (suscripcion_estado in ('activa', 'cancelada')),
  proveedor_ref            text,   -- cs_… (Stripe) | id de la preferencia o del preapproval (MP)
  proveedor_pago_id        text,   -- el PRIMER pago confirmado: pi_… / in_… | id del pago de MP
  proveedor_suscripcion_id text,   -- sub_… | id del preapproval
  url_proveedor            text,   -- el checkout del proveedor (el de Stripe VENCE)
  url_vence_at             timestamptz,
  -- SÓLO la plataforma (wsSuperAdmin): al pagar, alta de MaKo con esta capa. En otro workspace
  -- lib/cobros.ts lo rechaza al crear: un inquilino no crea inquilinos.
  alta_capa                text,
  alta_ws                  bigint references workspaces(id) on delete set null,
  alta_estado              text check (alta_estado in ('pendiente', 'hecha', 'ya_tenia_cuenta', 'error')),
  alta_motivo              text check (alta_motivo is null or char_length(alta_motivo) <= 300),
  alta_email_cambios       smallint not null default 0,
  motivo                   text check (motivo is null or char_length(motivo) <= 300),
  creado_por               text,
  created_at               timestamptz not null default now(),
  updated_at               timestamptz not null default now(),
  pagado_at                timestamptz,
  reembolsado_at           timestamptz
);

create unique index if not exists cobros_token_uk on cobros (token);
create index if not exists cobros_ws_idx on cobros (workspace_id, created_at desc);
create index if not exists cobros_lead_idx on cobros (workspace_id, lead_id);
create unique index if not exists cobros_ref_uk on cobros (proveedor, proveedor_ref) where proveedor_ref is not null;
create index if not exists cobros_sus_idx on cobros (proveedor, proveedor_suscripcion_id) where proveedor_suscripcion_id is not null;
create index if not exists cobros_pago_idx on cobros (proveedor, proveedor_pago_id) where proveedor_pago_id is not null;
-- El cron de reconciliación barre los pendientes recientes de cada workspace.
create index if not exists cobros_pendientes_idx on cobros (workspace_id, created_at) where estado = 'pendiente';

alter table cobros enable row level security;
revoke all on cobros from anon, authenticated;

create table if not exists pasarela_eventos (
  id           bigint generated by default as identity primary key,
  proveedor    text not null check (proveedor in ('stripe', 'mercadopago')),
  evento_id    text not null check (char_length(evento_id) between 1 and 200),
  -- null = no se supo de quién es: queda el rastro, nunca se le asigna uno «por default».
  workspace_id bigint references workspaces(id) on delete cascade,
  tipo         text not null default '' check (char_length(tipo) <= 120),
  cobro_id     bigint references cobros(id) on delete set null,
  estado       text not null check (estado in ('procesando', 'procesado', 'ignorado', 'error')),
  motivo       text check (motivo is null or char_length(motivo) <= 300),
  intentos     integer not null default 1,
  created_at   timestamptz not null default now(),
  updated_at   timestamptz not null default now()
);

create unique index if not exists pasarela_eventos_uk on pasarela_eventos (proveedor, evento_id);
create index if not exists pasarela_eventos_ws_idx on pasarela_eventos (workspace_id, created_at desc);

alter table pasarela_eventos enable row level security;
revoke all on pasarela_eventos from anon, authenticated;

alter table pagos add column if not exists cobro_id bigint references cobros(id) on delete set null;
alter table pagos add column if not exists proveedor text check (proveedor is null or proveedor in ('stripe', 'mercadopago'));
alter table pagos add column if not exists proveedor_pago_id text;
alter table pagos add column if not exists moneda text check (moneda is null or moneda ~ '^[A-Z]{3}$');
alter table pagos add column if not exists monto_original numeric(14, 2);
create unique index if not exists pagos_proveedor_uk
  on pagos (workspace_id, proveedor, proveedor_pago_id) where proveedor_pago_id is not null;

commit;

notify pgrst, 'reload schema';
