-- =============================================================================
-- 0293_agenda_evento_etapa — un evento de Calendly o Cal.com VINCULADO a una etapa de reunión
-- =============================================================================
-- Pedido de Martín (16/10/2026): «que una etapa catalogada como "reunion" se pueda vincular a un
-- evento de calendly o cal, para que sepa que leads deben caer allí cuando se agendan y no caer en
-- otra etapa u otro funnel». Una fila = un tipo de evento de la agenda del negocio → UN embudo y UNA
-- etapa de reunión. Quien reserva ese evento cae ahí; un evento sin fila hace lo de antes (J1/J2 →
-- el funnel principal). Las reglas, en lib/agenda-evento-etapa.ts; la base, en
-- lib/agenda-evento-etapa-server.ts.
--
-- ⚠️ ORDEN DE DESPLIEGUE: ANTES del deploy o JUNTO. Es aditiva y el código nuevo la LEE en cada
-- reserva: sin la tabla, los dos webhooks leen «no hay vínculos» (`faltaLaTabla`) y hacen
-- EXACTAMENTE lo de antes, así que el orden no rompe nada; lo que no anda hasta aplicarla es
-- VINCULAR (la API de MaKo y la pantalla contestan que falta la migración). No saca nada.
--
-- Va en TENANT_TABLES (lib/workspace.ts) y en TABLAS_DE_INQUILINO (lib/tablas-de-inquilino.ts).
-- RLS prendido y nada para anon ni authenticated: se lee sólo con service role.
--
-- ⚠️ `workspace_id` SIN default, a propósito: el molde de las tablas de al lado trae `default 1`, y
-- el 1 es Mauricio, un cliente. Una fila sin workspace tiene que fallar, no caer en su CRM.
-- (getTenantDb estampa el workspace en cada insert.)
--
-- ⚠️ La fila NO alcanza para que la reserva entre: el webhook resuelve de qué negocio es por
-- `webhook_routing`, y esa fila la reclama el server al vincular (primer reclamante gana) y la suelta
-- al desvincular si ya nadie la usa. Borrar el embudo borra el vínculo (cascade) pero NO suelta esa
-- fila: queda reclamada por este negocio y sus reservas vuelven a lo de antes (J1/J2).
-- =============================================================================
begin;

create table if not exists agenda_evento_etapa (
  id            bigint generated by default as identity primary key,
  workspace_id  bigint not null references workspaces(id) on delete cascade,
  proveedor     text not null check (proveedor in ('calendly', 'calcom')),
  -- Tal como llega en el webhook: Calendly la URI del event type, Cal.com su id. Es el mismo valor
  -- que queda en webhook_routing.
  identificador text not null check (char_length(identificador) between 1 and 300),
  -- El nombre del evento para mostrar (el de la cuenta del negocio al vincular).
  nombre        text check (nombre is null or char_length(nombre) <= 200),
  funnel_id     bigint not null references funnels(id) on delete cascade,
  etapa         text not null check (char_length(etapa) between 1 and 80),
  -- Quién lo vinculó. Mismo vocabulario que lead_audit.autor.
  por           text not null default 'CRM',
  created_at    timestamptz not null default now(),
  updated_at    timestamptz not null default now()
);

-- UN evento, UN lugar: el segundo vínculo del mismo evento choca acá aunque dos pestañas lo
-- intenten a la vez. Varios eventos SÍ pueden ir a la misma etapa.
create unique index if not exists agenda_evento_etapa_uk on agenda_evento_etapa (workspace_id, proveedor, identificador);
-- La pantalla de etapas pide los vínculos de un embudo.
create index if not exists agenda_evento_etapa_funnel on agenda_evento_etapa (workspace_id, funnel_id);

comment on table agenda_evento_etapa is 'Un tipo de evento de Calendly o Cal.com vinculado a UNA etapa de reunión de UN embudo: quien lo reserva cae ahí. Sin fila, la reserva hace lo de antes (CALENDLY/CALCOM_EVENT_TYPE_J1/J2 y el funnel principal). La fila de webhook_routing la maneja el server al vincular y desvincular.';

alter table agenda_evento_etapa enable row level security;
revoke all on agenda_evento_etapa from anon, authenticated;

commit;
