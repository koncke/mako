-- =============================================================================
-- 0034_nutricion — Motor de nutrición del VSL funnel (app = cerebro)
-- =============================================================================
-- Tres tablas: secuencias (definición + pasos como jsonb), inscripciones (un
-- lead dentro de una secuencia, con su próximo envío) y envios (log por mensaje;
-- alimenta /email y /whatsapp y mide open/clic/respuesta). Canales: email
-- (Resend) y whatsapp (Chatwoot) — se enchufan en hitos siguientes. La decisión
-- de a quién/qué/cuándo la toma el cron /api/cron/nutricion leyendo el estado
-- del lead + su comportamiento del VSL (Camino 1). n8n queda fuera de este funnel.
-- RLS on sin políticas = solo server-side (service_role), igual que el resto.

begin;

-- 1) Secuencias: definición editable + pasos como jsonb
create table if not exists nutricion_secuencias (
  id           bigint generated by default as identity primary key,
  clave        text not null unique,            -- 'form-sin-agenda', 'vio-vsl-sin-agendar', ...
  nombre       text not null,
  etapa        text not null default 'nutri',   -- nutri | nopaga | noshow | postagenda | manual
  trigger_tipo text not null,                   -- cohorte que inscribe (ver lib/nutricion.ts)
  activa       boolean not null default true,
  pasos        jsonb not null default '[]'::jsonb, -- [{orden,canal,delay_horas,asunto,cuerpo,template_wa}]
  created_at   timestamptz not null default now(),
  updated_at   timestamptz not null default now()
);

-- 2) Inscripciones: un lead dentro de una secuencia
create table if not exists nutricion_inscripciones (
  id               bigint generated by default as identity primary key,
  lead_id          bigint not null references leads(id) on delete cascade,
  secuencia_id     bigint not null references nutricion_secuencias(id) on delete cascade,
  paso_actual      int not null default 0,      -- cuántos pasos ya se enviaron
  estado           text not null default 'activa', -- activa|pausada|completada|respondio|no_responde|cancelada
  proximo_envio_at timestamptz,                 -- cuándo toca el próximo paso
  inscripto_at     timestamptz not null default now(),
  updated_at       timestamptz not null default now(),
  unique (lead_id, secuencia_id)
);

create index if not exists idx_nutri_insc_due
  on nutricion_inscripciones (estado, proximo_envio_at);
create index if not exists idx_nutri_insc_lead
  on nutricion_inscripciones (lead_id);

-- 3) Envíos: log por mensaje (alimenta las pantallas y mide open/clic/respuesta)
create table if not exists nutricion_envios (
  id             bigint generated by default as identity primary key,
  inscripcion_id bigint references nutricion_inscripciones(id) on delete set null,
  lead_id        bigint not null references leads(id) on delete cascade,
  secuencia_id   bigint references nutricion_secuencias(id) on delete set null,
  paso           int,
  canal          text not null,                 -- email | whatsapp
  estado         text not null,                 -- simulado | enviado | fallo
  destino        text,                          -- email o teléfono
  asunto         text,
  proveedor_id   text,                          -- id de Resend / Chatwoot
  error          text,
  abierto_at     timestamptz,
  clic_at        timestamptz,
  respondio_at   timestamptz,
  created_at     timestamptz not null default now()
);

create index if not exists idx_nutri_envios_lead on nutricion_envios (lead_id, created_at);

comment on table nutricion_secuencias is
  'Secuencias de nutrición del VSL funnel: definición + pasos (jsonb). Canales email/whatsapp.';
comment on table nutricion_inscripciones is
  'Un lead dentro de una secuencia, con su próximo envío y estado.';
comment on table nutricion_envios is
  'Log de cada mensaje de nutrición. Alimenta /email y /whatsapp y mide open/clic/respuesta.';

alter table nutricion_secuencias    enable row level security;
alter table nutricion_inscripciones enable row level security;
alter table nutricion_envios        enable row level security;

