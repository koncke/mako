-- =============================================================================
-- 0051_experimentos_retro_todo — Retro (retrospectivas) + To-do (kanban)
-- =============================================================================
-- Amplía la vista /experimentos de una sola pantalla a cuatro tabs:
--   Retro · Experiments · To-do · Conclusions.
--
-- retros: una RETROSPECTIVA por período. MaKo lee el funnel real + los
--   experimentos + las conclusiones + las tareas del período y produce un
--   reporte (narrativo) con destacados y RECOMENDACIONES separadas en "probá
--   esto" (→ experimento) y "hacé esto" (→ tarea). Se guarda como snapshot
--   histórico para poder comparar retros en el tiempo.
--
-- experimento_tareas: el tablero KANBAN de To-do (por_hacer | en_curso | hecho).
--   Cada tarea puede nacer de una Retro, de un experimento, o cargarse a mano.
--
-- RLS on sin políticas = solo server-side (service_role), igual que el resto.
-- =============================================================================

begin;

-- 1) Retrospectivas (snapshots por período) ────────────────────────────────────
create table if not exists retros (
  id              bigint generated by default as identity primary key,

  periodo_desde   date not null,
  periodo_hasta   date not null,

  titulo          text not null default '',
  resumen         text not null default '',        -- reporte narrativo (markdown de MaKo)
  destacados      jsonb,                            -- [{label, valor, delta, tono}] highlights del funnel
  recomendaciones jsonb,                            -- [{tipo:'experimento'|'tarea', ...}]
  snapshot        jsonb,                            -- métricas del funnel al generar (para comparar)

  model           text,
  created_at      timestamptz not null default now()
);

create index if not exists idx_retros_created on retros (created_at desc);

comment on table retros is
  'Retrospectivas de /experimentos (tab Retro). MaKo lee funnel+experimentos+conclusiones+tareas de un período y deja un reporte + recomendaciones (probá/hacé). Snapshot histórico, comparable.';

-- 2) Tareas del kanban To-do ───────────────────────────────────────────────────
create table if not exists experimento_tareas (
  id              bigint generated by default as identity primary key,

  titulo          text not null default '',
  detalle         text,
  estado          text not null default 'por_hacer',   -- por_hacer | en_curso | hecho
  prioridad       text not null default 'media',        -- alta | media | baja
  origen          text not null default 'manual',       -- manual | mako | retro | experimento

  experimento_id  bigint,                               -- de qué experimento nació (nullable)
  retro_id        bigint,                               -- de qué retro nació (nullable)

  orden           double precision not null default 0,  -- orden dentro de la columna del kanban
  hecho_at        timestamptz,

  created_at      timestamptz not null default now(),
  updated_at      timestamptz not null default now()
);

create index if not exists idx_tareas_estado on experimento_tareas (estado, orden);
create index if not exists idx_tareas_exp on experimento_tareas (experimento_id);

comment on table experimento_tareas is
  'Tablero kanban To-do de /experimentos (por_hacer|en_curso|hecho). Tareas que nacen de una Retro, de un experimento o a mano.';

commit;
