-- =============================================================================
-- 0400 — Los COMPROBANTES que lee la tarjeta «Pagos › Leer comprobante» de Automations (5/11/2026)
-- =============================================================================
-- Martín: «una tarjeta nueva de automations que sea un lector de comprobantes de pago [...] para leer comprobantes que
-- vienen». El diseño: docs/relevo/pagos-automations-encargo.md; lo que se construyó: docs/relevo/nube-recibos.md y
-- docs/hallazgos-chatbot.md («La tarjeta Pagos»).
--
-- EN PALABRAS: una tabla nueva, una fila por foto o PDF que un lead mandó y que una automatización leyó. Guarda lo que dijo
-- el modelo (monto, moneda, fecha, medio, a quién, N.º de operación) y lo que decidió el CÓDIGO (lib/comprobante-reglas.ts):
-- si se leyó bien, si cubre la cuota que tocaba y si el N.º de operación ya se había usado. NUNCA marca nada pagado: eso lo
-- hace una persona, o la tarjeta que sigue en el flujo.
--
--   · Una lectura por MENSAJE (`wa_mensaje_id` único por negocio): el motor reintenta, y una automatización que vuelve a
--     correr no gasta otra lectura de IA ni crea otra fila.
--   · UN N.º DE OPERACIÓN CUENTA UNA SOLA VEZ: `operacion_unica` lleva el número sólo en la primera fila que lo trae, con un
--     índice único por negocio. La segunda (el mismo comprobante mandado dos veces, o el de otro lead) entra con
--     `repetido = true` y `operacion_unica` null. Lo decide la base, no una lectura previa: dos mensajes a la vez no pasan
--     los dos como nuevos.
--   · Con `workspace_id` (va en TENANT_TABLES) y la FK al lead `on delete cascade`: la papelera de leads (mig 0340) la
--     guarda en su foto y la devuelve.
--
-- ORDEN DE DESPLIEGUE: ANTES del código, o junto. La tarjeta, sin la tabla, contesta «No pude guardar la lectura» y la
-- condición «Su comprobante» lee «No mandó un comprobante»: no se rompe nada, pero no anda. Número elegido en la nube el
-- 5/11/2026 barriendo main, las puntas, ci-rojo y las etiquetas (main llega a 0394; 0396 está en `punta/codigo-primer-contacto`
-- y 0397 es la de los recibos de MaKo): confirmarlo con el Cerebro al aplicar.
-- =============================================================================

begin;

create table if not exists comprobantes_leidos (
  id bigint generated by default as identity primary key,
  workspace_id bigint not null references workspaces(id) on delete cascade,
  lead_id bigint not null references leads(id) on delete cascade,
  -- De dónde salió el archivo: el mensaje de WhatsApp (no oficial) que lo trajo.
  wa_mensaje_id text not null check (char_length(wa_mensaje_id) between 1 and 200),
  media_path text not null check (char_length(media_path) between 3 and 500),
  media_mime text not null check (media_mime in ('image/jpeg', 'image/png', 'application/pdf')),
  -- Quién lo leyó: la automatización y su paso (null si se pidió por el chat o la API).
  secuencia_id bigint,
  origen text not null default 'flujo' check (origen in ('flujo', 'chat', 'api')),
  -- Lo que decidió el código (lib/comprobante-reglas.ts).
  estado text not null check (estado in ('leido', 'dudoso', 'ilegible')),
  cobertura text check (cobertura is null or cobertura in ('total', 'parcial', 'de_mas', 'otra_moneda', 'sin_cuota')),
  repetido boolean not null default false,
  resultado text not null check (resultado in ('cubre', 'parcial', 'repetido', 'dudoso', 'no_es')),
  -- Lo que dijo el modelo, saneado (`lecturaDe`), y lo que tocaba pagar (`Esperado`).
  lectura jsonb not null check (jsonb_typeof(lectura) = 'object'),
  esperado jsonb check (esperado is null or jsonb_typeof(esperado) = 'object'),
  monto numeric(14, 2),
  moneda text check (moneda is null or moneda ~ '^[A-Z]{3,5}$'),
  operacion text check (operacion is null or char_length(operacion) between 4 and 120),
  operacion_unica text check (operacion_unica is null or operacion_unica = operacion),
  -- La cuota que tocaba (si había), y si alguien la marcó cobrada con este comprobante.
  pago_id bigint references pagos(id) on delete set null,
  usado_at timestamptz,
  proveedor text,
  created_at timestamptz not null default now()
);

create unique index if not exists comprobantes_leidos_mensaje_uk on comprobantes_leidos (workspace_id, wa_mensaje_id);
create unique index if not exists comprobantes_leidos_operacion_uk on comprobantes_leidos (workspace_id, operacion_unica) where operacion_unica is not null;
create index if not exists comprobantes_leidos_lead_idx on comprobantes_leidos (workspace_id, lead_id, created_at desc);

alter table comprobantes_leidos enable row level security;
revoke all on comprobantes_leidos from anon, authenticated;
grant all on comprobantes_leidos to service_role;

commit;
