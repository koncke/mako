-- =============================================================================
-- 0221_conocimiento_ajustes — lo que el SUPER ADMIN le cambió a un curso de Conocimientos
-- =============================================================================
-- ⚠️ ORDEN DE DESPLIEGUE: ANTES del deploy. El código nuevo LEE esta tabla en tres caminos:
--   · /conocimientos (el super admin): sin la tabla la lectura falla, el curso se dibuja como en el
--     catálogo y NO se ofrece editar (se editaría encima de algo que no se ve).
--   · /compartido/<token> (un curso suelto o la tab entera, SIN login): la lectura es ESTRICTA,
--     porque decide qué se OCULTA a un tercero. Sin la tabla, el link contesta «No pudimos abrir
--     el curso» en vez de mostrar lo que el super admin escondió. O sea: si esto no está aplicado,
--     todos los links compartidos de cursos dejan de abrir.
--   · /api/compartir (el nombre de cada link en el modal y en el mail): cae al título del catálogo.
-- Agrega y no saca nada: la versión desplegada no mira esta tabla.
--
-- Pedido de Martín (07/10/2026, item 1 de los 19 del curso tipo Skool): «En la tab de
-- CONOCIMIENTOS como SuperAdmin debería poder editar todo, aplicalo también allí. Claro que los
-- links compartidos y otros usuarios no deben poder editar eso.» Es D9 de docs/diseno-curso-skool.md.
--
-- POR QUÉ UNA CAPA EN LA BASE Y NO EDITAR LAS FICHAS: los cursos viven en el CÓDIGO
-- (app/conocimientos/curso-*.ts) y `scripts/curso-a-portal.mjs` reescribe cada ficha ENTERA en cada
-- corrida. Un cambio escrito ahí dura hasta la próxima regeneración, sin aviso. Esto se APLICA
-- ENCIMA del catálogo (lib/conocimiento-ajustes.ts, `aplicarAjustes`), y borrar la fila es volver
-- a lo que dice la ficha.
--
-- UNA FILA POR AJUSTE, como `curso_estilo` (0214): cada cambio es un upsert de UNA clave, así que
-- dos cambios a la vez no se pisan, y «nadie lo cambió» no se mezcla con «lo dejó como estaba».
--   objeto      'curso' | 'modulo' | 'clase'
--   objeto_id   ''  para el curso;
--               el NOMBRE ORIGINAL del grupo para un módulo (es su identidad: viaja en los `#mod=`
--               que ya circulan, y renombrarlo no puede romper un link compartido);
--               el `n` de la clase para una clase (el id de la plataforma de origen, el del `#clase=`).
--   campo       curso: titulo, resumen, acento, portada · módulo: nombre, portada, orden, oculto ·
--               clase: titulo, portada, orden, modulo, oculta. Qué vale cada uno lo decide el código.
--
-- ⚠️ NO REUSA LA CLAVE DE `curso_estilo`: su clave topea en 80 caracteres y sólo acepta
--    `[a-z0-9_]`; acá un módulo se nombra por su grupo, que es texto libre con espacios y tildes y
--    llega a 91 caracteres medidos sobre el catálogo (08/10/2026). Por eso `objeto_id` es texto y
--    va hasta 300.
--
-- ⚠️ SIN `workspace_id`, A PROPÓSITO: es contenido de la PLATAFORMA, no de un cliente. Con la
--    columna habría que meterla en TENANT_TABLES, y entonces la lectura desde /compartido (sin
--    sesión, que cae al workspace del dueño, el ws1, que es un CLIENTE) quedaría acotada a otro
--    inquilino. El molde es `shares`, que es cruzada por diseño (mig 0098). Escribe SÓLO el super
--    admin: `getSesionAdmin()` en la primera línea de cada escritura (lib/conocimiento-ajustes-datos.ts).
--
-- Un ajuste HUÉRFANO (el grupo cambió de nombre en una regeneración, o la clase ya no está) no
-- rompe nada: no encuentra a quién aplicarse y se ignora al leer.
--
-- RLS on sin políticas = sólo server-side (service_role), igual que el resto.
begin;

create table if not exists conocimiento_ajustes (
  id          bigint generated by default as identity primary key,
  curso_slug  text not null check (char_length(curso_slug) between 1 and 200),
  objeto      text not null check (objeto in ('curso', 'modulo', 'clase')),
  objeto_id   text not null default '' check (char_length(objeto_id) <= 300),
  campo       text not null check (campo in ('titulo', 'resumen', 'acento', 'portada', 'nombre', 'orden', 'oculto', 'modulo', 'oculta')),
  valor       text not null check (char_length(valor) between 1 and 2000),
  updated_at  timestamptz not null default now(),
  updated_by  text
);
create unique index if not exists conocimiento_ajustes_uk on conocimiento_ajustes (curso_slug, objeto, objeto_id, campo);
create index if not exists idx_conocimiento_ajustes_curso on conocimiento_ajustes (curso_slug);

comment on table conocimiento_ajustes is
  'Lo que el super admin le cambió a un curso de Conocimientos (título, portada, orden, ocultar...), aplicado encima del catálogo del código. Una fila por ajuste; sin fila = lo de la ficha. Lo valida lib/conocimiento-ajustes.ts.';

alter table conocimiento_ajustes enable row level security;
revoke all on conocimiento_ajustes from anon, authenticated;

commit;
