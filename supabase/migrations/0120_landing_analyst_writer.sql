-- =============================================================================
-- 0120 — Landing Analyst + Landing Generator
-- =============================================================================
-- Las dos tabs existían como ComingSoon desde el rediseño y no tenían NADA
-- detrás: ni tabla, ni lib, ni prompt. Esta migración les pone la persistencia.
--
-- `landing_analyses` — 1 fila por (workspace, url). MaKo BAJA la página del
-- cliente (lib/landing-fetch.ts), le extrae el copy y la estructura, y la cruza
-- con el comportamiento real que ya tenemos de esa misma landing en
-- `landing_visits` + `vsl_events`. Por eso la entidad es la URL normalizada y no
-- un id externo: es lo único que comparten el HTML descargado y el beacon.
--
-- `landing_drafts` — historial del generador. Un writer no persiste una fila por
-- entidad (genera a pedido), pero sin historial el dueño pierde la propuesta al
-- recargar y no puede comparar dos versiones de la misma landing. Guarda el
-- pedido, el spec devuelto y —si salió de un diagnóstico— la URL que lo originó.
--
-- Multi-tenant SIN políticas: todo el runtime entra con service_role y el
-- aislamiento lo hace getTenantDb + TENANT_TABLES (mismo contrato que 0118).
-- Hay que sumar AMBAS a TENANT_TABLES en lib/workspace.ts.
-- =============================================================================
begin;

create table if not exists landing_analyses (
  id               bigint generated by default as identity primary key,
  workspace_id     bigint not null default 1 references workspaces(id) on delete cascade,

  -- Identidad: la URL normalizada (sin querystring de tracking ni barra final).
  url              text not null,
  url_final        text,                 -- a dónde terminó tras redirects
  titulo           text,                 -- <title> de la página

  -- Veredicto de MaKo
  status           text not null default 'pendiente',  -- analizada | pendiente | error
  score            numeric,              -- 0-10, una décima
  veredicto        text,                 -- "Promesa clara, prueba floja"
  veredicto_tone   text,                 -- good | warn | bad
  resumen          text,                 -- 4-6 frases
  promesa          text,                 -- la promesa principal que MaKo leyó
  avatar           text,                 -- a quién le habla la página, según el copy

  -- Cuerpo del análisis (jsonb)
  secciones        jsonb,                -- [{orden,tipo,titulo,copy,diagnostico,tone}]
  hallazgos        jsonb,                -- [{titulo,severidad,seccion,cita,por_que,arreglo}]
  dims             jsonb,                -- [{label,score,note}] claridad/promesa/prueba/CTA/fricción
  recomendaciones  jsonb,                -- [string] accionables, ordenadas por impacto

  -- Cruce con el comportamiento real (lo calcula el código, no la IA)
  comportamiento   jsonb,                -- {visitas,visitantes,scroll_promedio,plays,agendas,rebote}

  -- Trazabilidad del fetch
  fetch_ms         int,
  html_bytes       int,
  palabras         int,
  bloqueada        boolean,              -- true si la página no se pudo leer (JS-only, 403, timeout)

  error            text,
  model            text,
  analysis_version int not null default 1,
  analyzed_at      timestamptz,
  created_at       timestamptz not null default now(),
  updated_at       timestamptz not null default now()
);

create index if not exists idx_landing_analyses_ws on landing_analyses (workspace_id);
-- Índice único NO parcial: es el target del ON CONFLICT del upsert.
create unique index if not exists idx_landing_analyses_ws_url on landing_analyses (workspace_id, url);

comment on table landing_analyses is 'Análisis de una landing por workspace (Landing Analyst). 1 fila por URL normalizada: copy extraído del HTML + diagnóstico de MaKo + cruce con landing_visits/vsl_events.';
comment on column landing_analyses.url is 'URL NORMALIZADA (minúsculas, sin querystring de tracking, sin barra final). Es la entidad: lo único que comparten el HTML bajado y el beacon de la landing.';
comment on column landing_analyses.bloqueada is 'true = no se pudo leer la página (render 100% client-side, 403, timeout). El análisis queda en status=error con la causa en `error`.';

alter table landing_analyses enable row level security;

create table if not exists landing_drafts (
  id            bigint generated by default as identity primary key,
  workspace_id  bigint not null default 1 references workspaces(id) on delete cascade,

  pedido        text not null,     -- lo que pidió el usuario
  objetivo      text,              -- agendar | vender | registrar | descargar
  basado_en_url text,              -- landing_analyses.url que originó el pedido (si la hay)
  spec          jsonb not null,    -- el LandingSpec devuelto por MaKo
  titulo        text,              -- para listar el historial sin abrir el spec
  model         text,
  created_at    timestamptz not null default now()
);

create index if not exists idx_landing_drafts_ws on landing_drafts (workspace_id);
create index if not exists idx_landing_drafts_ws_fecha on landing_drafts (workspace_id, created_at desc);

comment on table landing_drafts is 'Historial del Landing Generator: cada propuesta de copy/estructura que MaKo escribió, con el pedido que la originó. Sin esto la propuesta se pierde al recargar y no se pueden comparar dos versiones.';

alter table landing_drafts enable row level security;

commit;
