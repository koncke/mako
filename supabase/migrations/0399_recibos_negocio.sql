-- =============================================================================
-- 0399 — Los RECIBOS que emite un NEGOCIO a sus clientes: la tarjeta «Pagos › Emitir recibo» de Automations (5/11/2026)
-- =============================================================================
-- Martín: «que dentro de esa tarjeta haya tanto para leer comprobantes que vienen como para emitir factura y tal vez que hayan
-- varios templates de factura que nosotros podemos crear y que el usuario pueda elegir qué template de factura quiere enviar».
-- El diseño: docs/relevo/pagos-automations-encargo.md; lo construido: docs/relevo/nube-recibos.md.
--
-- EN PALABRAS: dos tablas nuevas y una función. Cada negocio numera SUS recibos desde el 0001 (`recibos_negocio_numeracion`,
-- una fila por negocio), y cada pago cobrado tiene a lo sumo UN recibo (`clave` única por negocio: `pago:<id>`). La función
-- `emitir_recibo_negocio` toma el candado de la numeración del negocio, devuelve el recibo si la clave ya lo tiene, y si no
-- suma uno e inserta: correlativo, sin huecos y sin carreras. No toca ninguna tabla que exista.
--
--   · Es un RECIBO DE PAGO, no una factura fiscal, y el PDF lo dice (lib/recibos-reglas.ts, `PIE_FIJO`). Los datos del
--     emisor son los de «Facturado por» del negocio (`identidades_fiscales`): nunca se inventa uno.
--   · Con `workspace_id` (va en TENANT_TABLES). La FK al lead es `on delete cascade`: la papelera de leads (mig 0340) guarda
--     el recibo en su foto y lo devuelve con el lead.
--
-- ORDEN DE DESPLIEGUE: ANTES del código, o junto. Sin ella, la tarjeta contesta «falta la migración 0399» y no manda nada.
-- Número elegido en la nube el 5/11/2026 (0397 los recibos de MaKo, 0398 los comprobantes leídos): confirmarlo al aplicar.
-- =============================================================================

begin;

create table if not exists recibos_negocio_numeracion (
  workspace_id bigint primary key references workspaces(id) on delete cascade,
  ultimo integer not null default 0 check (ultimo >= 0)
);

create table if not exists recibos_negocio (
  id bigint generated by default as identity primary key,
  workspace_id bigint not null references workspaces(id) on delete cascade,
  numero integer not null check (numero > 0),
  clave text not null check (char_length(clave) between 3 and 200),
  lead_id bigint references leads(id) on delete cascade,
  pago_id bigint references pagos(id) on delete set null,
  plantilla text not null check (plantilla in ('clasico', 'compacto', 'marca')),
  a_nombre text not null check (char_length(a_nombre) between 1 and 200),
  -- La FOTO de lo que dice el PDF (lib/recibo-pdf.ts, `FotoRecibo`): reimprimirlo da el mismo documento aunque la cuota cambie.
  foto jsonb not null check (jsonb_typeof(foto) = 'object'),
  pdf_path text check (pdf_path is null or char_length(pdf_path) between 3 and 500),
  pdf_sha256 text check (pdf_sha256 is null or pdf_sha256 ~ '^[0-9a-f]{64}$'),
  canal text not null check (canal in ('whatsapp', 'email', 'grupo')),
  envio_estado text not null default 'pendiente' check (envio_estado in ('pendiente', 'enviado', 'fallo', 'sin_destino')),
  envio_error text,
  enviado_at timestamptz,
  emitido_por text,
  emitido_at timestamptz not null default now()
);

create unique index if not exists recibos_negocio_numero_uk on recibos_negocio (workspace_id, numero);
create unique index if not exists recibos_negocio_clave_uk on recibos_negocio (workspace_id, clave);
create index if not exists recibos_negocio_lead_idx on recibos_negocio (workspace_id, lead_id);

alter table recibos_negocio_numeracion enable row level security;
alter table recibos_negocio enable row level security;
revoke all on recibos_negocio_numeracion from anon, authenticated;
revoke all on recibos_negocio from anon, authenticated;
grant all on recibos_negocio_numeracion to service_role;
grant all on recibos_negocio to service_role;

-- El ÚNICO que da números (tests/recibos-negocio.test.ts frena otro llamador). `p`: workspace_id, clave, lead_id, pago_id,
-- plantilla, a_nombre, foto, canal, emitido_por. Devuelve el recibo y si ya estaba.
create or replace function emitir_recibo_negocio(p jsonb)
returns table (recibo_id bigint, numero integer, ya_estaba boolean)
language plpgsql
set search_path = public
as $$
declare
  v_ws bigint := (p->>'workspace_id')::bigint;
  v_clave text := btrim(coalesce(p->>'clave', ''));
  v_id bigint;
  v_numero integer;
begin
  if v_ws is null or v_clave = '' then
    raise exception 'RECIBO_INVALIDO falta el negocio o la clave';
  end if;
  insert into recibos_negocio_numeracion (workspace_id, ultimo) values (v_ws, 0) on conflict (workspace_id) do nothing;
  perform 1 from recibos_negocio_numeracion n where n.workspace_id = v_ws for update;
  select r.id, r.numero into v_id, v_numero from recibos_negocio r where r.workspace_id = v_ws and r.clave = v_clave;
  if found then
    return query select v_id, v_numero, true;
    return;
  end if;
  update recibos_negocio_numeracion n set ultimo = n.ultimo + 1 where n.workspace_id = v_ws returning n.ultimo into v_numero;
  insert into recibos_negocio (workspace_id, numero, clave, lead_id, pago_id, plantilla, a_nombre, foto, canal, emitido_por)
  values (
    v_ws, v_numero, v_clave, nullif(p->>'lead_id', '')::bigint, nullif(p->>'pago_id', '')::bigint, p->>'plantilla',
    p->>'a_nombre', p->'foto', p->>'canal', nullif(p->>'emitido_por', '')
  )
  returning id into v_id;
  return query select v_id, v_numero, false;
end;
$$;

revoke all on function emitir_recibo_negocio(jsonb) from public, anon, authenticated;
grant execute on function emitir_recibo_negocio(jsonb) to service_role;

commit;
