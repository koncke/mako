-- =============================================================================
-- 0220 — Los MÓDULOS del curso, sus BLOQUEOS, los DESBLOQUEOS a mano y la clase «hecha»
-- =============================================================================
-- ⚠️ ORDEN DE DESPLIEGUE: ANTES del deploy. El código nuevo LEE lo que esto agrega en el camino
-- del PORTAL del alumno, de la ficha, de la tab Curso y del cron:
--   · `curso_clases.bloqueo` entra en `COLUMNAS_CLASE` (lib/curso-datos.ts), junto con
--     `descripcion_html` (mig 0216, ya aplicada). Sin la columna, PostgREST rechaza la consulta
--     ENTERA («column … does not exist») y se caen el portal, /mi-curso, la ficha, la tab y el cron
--     de las llamadas (el precedente es la 0212).
--   · `curso_progreso.hecha_at` entra en la lectura del avance (`COLS_PROGRESO`): lo mismo.
--   · `curso_modulos` y `curso_desbloqueos` las lee el portal en cada pedido para decidir qué se
--     abre (lib/curso-modulos-datos.ts). Sin las tablas, el portal contesta «No pudimos cargar tus
--     clases» en vez de abrir algo que no sabe si está cerrado.
-- Agrega y no saca nada: la versión desplegada no mira ninguna de estas cosas.
--
-- Pedido de Martín (07/10/2026, items 8, 11 y 12 del curso tipo Skool): «Para las Etapas dentro
-- del curso, llamalo Módulos… Es importante un editor para los módulos, para poder desvincularlo
-- del kanban… si quiero crear un módulo que NO sea una etapa dentro del kanban» y «implementes la
-- funcionalidad de Skool de poder bloquear algunas clases, y que se vayan desbloqueando con ciertos
-- requerimientos». Las decisiones y los contratos, en docs/diseno-curso-skool.md (D1 y D2).
--
-- ── 1. curso_modulos ─────────────────────────────────────────────────────────
-- ⚠️ LA LISTA DE MÓDULOS NO VIVE ACÁ: SE DERIVA (lib/curso-modulos.ts, `derivarModulos`). Un módulo
-- VINCULADO es una etapa del kanban (`producto_entrega.data.etapas[]` con `enCurso !== false`): su
-- clave, su nombre y su orden son los de la etapa, y NO necesita fila. Esta tabla guarda sólo lo
-- que la etapa no puede decir:
--   · un módulo SUELTO (`vinculado = false`): clave `m_<azar>`, su nombre y su ANCLA (`despues_de`,
--     la clave del módulo que lo precede; null = al principio). No es una etapa: no mueve clientes.
--   · el BLOQUEO de un módulo vinculado (`vinculado = true`, sin nombre ni ancla): la fila existe
--     sólo para guardar eso.
-- Por qué un ancla y no un número de orden: el orden de los vinculados es el del kanban, y un número
-- propio se desincronizaría del kanban en el primer arrastre del editor de etapas. Un ancla sigue al
-- módulo que la precede adonde lo lleven.
--
-- ── 2. curso_clases.bloqueo ──────────────────────────────────────────────────
-- El bloqueo de UNA clase. NULL = hereda (abierta si su módulo lo está). La forma la sanea el código
-- (lib/curso-bloqueo.ts, `saneaBloqueo`); la base sólo exige que sea un objeto.
--
-- ── 3. curso_desbloqueos ─────────────────────────────────────────────────────
-- «Abrir a mano» un módulo o una clase a UN alumno (la ficha del cliente). Gana sobre cualquier
-- bloqueo. `clave` es la clave del módulo, o el id de la clase escrito como texto. Sin FK a la
-- clase, a propósito: es un texto que nombra dos cosas distintas, y borrar la clase la limpia el
-- código (lib/curso-admin.ts, `borrarClase`).
--
-- ── 4. curso_progreso.hecha_at ───────────────────────────────────────────────
-- El alumno marcó como HECHA una clase que no tiene tarea (el «tilde de completado» de Skool). Es
-- una de las tres formas de completar una clase (D2), y completar abre lo que espera a la anterior.
--
-- RLS on sin políticas = sólo server-side (service_role), igual que el resto del curso.

begin;

create table if not exists curso_modulos (
  id           bigint generated by default as identity primary key,
  workspace_id bigint not null default 1 references workspaces(id) on delete cascade,
  producto_id  bigint not null references productos(id) on delete cascade,
  -- La misma forma que una clave de etapa (lib/servicio-etapas.ts) y que la de una portada de
  -- etapa (lib/curso-estilo.ts): la clave viaja en la URL, en un jsonb y en `curso_clases.etapa`.
  clave        text not null check (clave ~ '^[a-z0-9_]{1,60}$'),
  vinculado    boolean not null default false,
  nombre       text check (nombre is null or char_length(nombre) between 1 and 80),
  despues_de   text check (despues_de is null or despues_de ~ '^[a-z0-9_]{1,60}$'),
  bloqueo      jsonb check (bloqueo is null or jsonb_typeof(bloqueo) = 'object'),
  created_at   timestamptz not null default now(),
  updated_at   timestamptz not null default now(),
  -- Un vinculado no tiene nombre ni ancla propios (son los de su etapa); un suelto tiene nombre.
  constraint curso_modulos_forma check (
    (vinculado and nombre is null and despues_de is null) or (not vinculado and nombre is not null)
  )
);
create unique index if not exists curso_modulos_uk on curso_modulos (workspace_id, producto_id, clave);

comment on table curso_modulos is
  'Los módulos SUELTOS del curso de un producto (nombre y ancla) y el bloqueo de los vinculados. La lista de módulos se deriva con las etapas del kanban (lib/curso-modulos.ts).';
comment on column curso_modulos.despues_de is
  'La clave del módulo que precede a este suelto (null = al principio). Una clave que ya no existe lo manda al final.';
comment on column curso_modulos.bloqueo is
  'Cuándo se abre el módulo. NULL = el default (vinculado: al llegar a su etapa; suelto: abierto). Lo sanea lib/curso-bloqueo.ts.';

alter table curso_clases add column if not exists bloqueo jsonb;
do $$
begin
  if not exists (select 1 from pg_constraint where conname = 'curso_clases_bloqueo_objeto') then
    alter table curso_clases add constraint curso_clases_bloqueo_objeto
      check (bloqueo is null or jsonb_typeof(bloqueo) = 'object');
  end if;
end $$;
comment on column curso_clases.bloqueo is
  'Cuándo se abre la clase. NULL = hereda de su módulo. Lo sanea lib/curso-bloqueo.ts.';

create table if not exists curso_desbloqueos (
  id           bigint generated by default as identity primary key,
  workspace_id bigint not null default 1 references workspaces(id) on delete cascade,
  lead_id      bigint not null references leads(id) on delete cascade,
  producto_id  bigint not null references productos(id) on delete cascade,
  objeto       text not null check (objeto in ('modulo', 'clase')),
  clave        text not null check (char_length(clave) between 1 and 60),
  creado_por   text,
  created_at   timestamptz not null default now()
);
create unique index if not exists curso_desbloqueos_uk on curso_desbloqueos (workspace_id, lead_id, producto_id, objeto, clave);
create index if not exists idx_curso_desbloqueos_lead on curso_desbloqueos (workspace_id, lead_id);

comment on table curso_desbloqueos is
  'Lo que el equipo le abrió A MANO a un alumno (un módulo o una clase). Gana sobre cualquier bloqueo.';

alter table curso_progreso add column if not exists hecha_at timestamptz;
comment on column curso_progreso.hecha_at is
  'El alumno marcó como hecha una clase sin tarea. Completar una clase la cuenta para lo que se abre después.';

alter table curso_modulos enable row level security;
revoke all on curso_modulos from anon, authenticated;
alter table curso_desbloqueos enable row level security;
revoke all on curso_desbloqueos from anon, authenticated;
-- Re-afirmado: es lo único que mantiene las columnas nuevas afuera del navegador si algún día se
-- aplica DDL con otro rol.
alter table curso_clases enable row level security;
revoke all on curso_clases from anon, authenticated;
alter table curso_progreso enable row level security;
revoke all on curso_progreso from anon, authenticated;

commit;
