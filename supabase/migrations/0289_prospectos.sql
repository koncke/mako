-- =============================================================================
-- 0289_prospectos — la lista aparte de la prospección en frío (Leads Scraper)
-- =============================================================================
-- docs/diseno-leads-scraper.md §4 y §7 (decisión 4): los contactos que SE BUSCAN —Google Maps,
-- perfiles públicos de Instagram— no entran directo al CRM. Caen acá, con un puntaje y su razón, y
-- la persona pasa al CRM los que elige (por la puerta del importador: importarLeadsRevisadosAction).
--
--   · prospeccion_busquedas: cada búsqueda que se mandó a correr en Apify (con la key del negocio),
--     su estado, y el hash de la clave con que el aviso de Apify prueba que es de esta búsqueda.
--   · prospectos: un contacto encontrado, único por (workspace, fuente, id externo): repetir la
--     búsqueda no lo duplica.
--
-- ORDEN DE DESPLIEGUE: va ANTES del deploy (o junto). El código nuevo la LEE: sin la tabla, la
-- pantalla de prospectos contesta que falta la migración, y el aviso de Apify no tiene dónde
-- escribir (lib/prospectos.ts distingue «falta la tabla» de cualquier otro error).
--
-- Las dos van en TENANT_TABLES (lib/workspace.ts) y en TABLAS_DE_INQUILINO (lib/tablas-de-inquilino.ts).
-- RLS prendido y nada para anon ni authenticated: se leen sólo con service role.
-- =============================================================================
begin;

create table if not exists prospeccion_busquedas (
  id            bigint generated by default as identity primary key,
  workspace_id  bigint not null default 1 references workspaces(id) on delete cascade,
  fuente        text not null check (fuente in ('google_maps', 'instagram')),
  -- Lo que se pidió (qué, dónde, cuántos), tal como lo guardó lib/prospectos-reglas.ts.
  parametros    jsonb not null default '{}'::jsonb,
  estado        text not null default 'corriendo' check (estado in ('corriendo', 'lista', 'fallo')),
  apify_run_id  text check (apify_run_id is null or char_length(apify_run_id) <= 64),
  -- sha256 de la clave que viaja en el aviso de Apify (lib/ruteo-hash.ts): nunca la clave.
  clave_hash    text check (clave_hash is null or char_length(clave_hash) = 64),
  resultados    integer not null default 0,
  nuevos        integer not null default 0,
  motivo        text check (motivo is null or char_length(motivo) <= 300),
  creado_por    text,
  created_at    timestamptz not null default now(),
  updated_at    timestamptz not null default now()
);
create index if not exists idx_prospeccion_busquedas_ws on prospeccion_busquedas (workspace_id, created_at desc);
comment on table prospeccion_busquedas is 'Leads Scraper: cada búsqueda de prospectos mandada a Apify (docs/diseno-leads-scraper.md).';
alter table prospeccion_busquedas enable row level security;
revoke all on prospeccion_busquedas from anon, authenticated;

create table if not exists prospectos (
  id            bigint generated by default as identity primary key,
  workspace_id  bigint not null default 1 references workspaces(id) on delete cascade,
  busqueda_id   bigint references prospeccion_busquedas(id) on delete set null,
  fuente        text not null check (fuente in ('google_maps', 'instagram')),
  id_externo    text not null check (char_length(id_externo) between 1 and 200),
  nombre        text not null check (char_length(nombre) between 1 and 200),
  empresa       text,
  email         text,
  telefono      text,
  web           text,
  instagram     text,
  ciudad        text,
  rubro         text,
  -- Lo que mide el puntaje (reseñas, rating, seguidores…): datos públicos del negocio, nunca el crudo entero.
  datos         jsonb not null default '{}'::jsonb,
  puntaje       integer not null default 0 check (puntaje between 0 and 100),
  razon         text check (razon is null or char_length(razon) <= 300),
  estado        text not null default 'nuevo' check (estado in ('nuevo', 'descartado', 'en_crm')),
  lead_id       bigint references leads(id) on delete set null,
  created_at    timestamptz not null default now(),
  updated_at    timestamptz not null default now()
);
-- El índice único NO es parcial: es el target del ON CONFLICT con que se escriben los resultados.
create unique index if not exists prospectos_uk on prospectos (workspace_id, fuente, id_externo);
create index if not exists idx_prospectos_lista on prospectos (workspace_id, estado, puntaje desc);
comment on table prospectos is 'Leads Scraper: los contactos encontrados, con puntaje, antes de pasar al CRM.';
alter table prospectos enable row level security;
revoke all on prospectos from anon, authenticated;

commit;
