-- =============================================================================
-- 0246 — El editor de landings copiado de Gamma: documentos, versiones, comentarios y su bucket
-- =============================================================================
-- ⚠️ ORDEN DE DESPLIEGUE: ANTES o JUNTO con el deploy que trae /api/landing-generator,
-- /api/landing-generator/imagenes y /l/<slug>. El código nuevo LEE estas tablas desde el primer
-- request: sin ellas el Panel contesta «relation does not exist» y la página pública no encuentra
-- nada que servir. Agrega y no saca nada: la versión desplegada no mira ninguna de las tres tablas
-- ni el bucket, así que aplicarla antes no le molesta a nadie. `landing_drafts` (el generador
-- anterior) NO se toca: la leen cinco lugares con la forma de `LandingSpec`
-- (lib/api-mako/areas/landing.*).
--
-- Pedido de Martín (11/10/2026), textual: «Quiero que implementes en la tab de "Landing Generator"
-- un editor de landing tipo GAMMA. Replica por completo a Gamma, que se pueda hacer todo lo que ahí
-- se hace.» Decisiones y contratos: docs/diseno-editor-landing.md (D2).
--
-- Las tres tablas: `workspace_id` SIN default (nunca son del dueño por omisión), índice por
-- workspace, RLS prendida sin políticas y `revoke` explícito: el que mantiene afuera a la clave
-- pública es el revoke, no la RLS sola (AGENTS.md, «una VISTA no tiene RLS» y el porqué del grant
-- que depende de quién aplica el DDL). El servidor lee con service_role.
--
-- ⚠️ Y VAN A TRES REGISTROS DEL CÓDIGO (el compilador no ve ninguno): `TENANT_TABLES`
-- (lib/workspace.ts, para que getTenantDb las acote), `TABLAS_DE_INQUILINO`
-- (lib/tablas-de-inquilino.ts, para que el reset y el borrado las vacíen) y el bucket en `BUCKETS`
-- (lib/reset-workspace.ts).

begin;

-- ── 1. Una fila por landing ──────────────────────────────────────────────────
-- `contenido` es el JSON de ProseMirror de TODAS las páginas (`LandingContenido`,
-- lib/editor-landing/doc.ts), SANEADO en el server antes de guardarse (`sanearContenido`). Nunca
-- HTML: el HTML lo fabrica UNA función (lib/editor-landing/render.ts) al publicar.
--
-- `version` es la concurrencia optimista: `guardar` exige la que se abrió y el update es
-- compare-and-set (`where id = … and version = …`). Si otro guardó en el medio, 0 filas = conflicto,
-- y la pantalla ofrece recargar en vez de pisar.
--
-- `publicado` es la FOTO que sirve /l/<slug>: el HTML ya renderizado de cada página, la hoja, las
-- fuentes y la configuración del sitio CONGELADOS al publicar. La página pública nunca lee
-- `contenido` (el borrador): publicar promueve lo GUARDADO (AGENTS.md, «Un BORRADOR no es un
-- DEFAULT»). «Tienes cambios que publicar» = `publicado_version <> version`.
--
-- `slug` es ÚNICO GLOBAL (la URL pública no lleva el workspace): primer reclamante gana. El índice
-- es parcial porque casi todas las filas no tienen slug. Despublicar NO lo suelta: la dirección
-- sigue siendo de esa landing y republicar vuelve a la misma URL.
--
-- `vista_token` es el link privado al BORRADOR (/l/vista/<token>, noindex, sin Pixel). 32 bytes
-- al azar en base64url = 43 caracteres; regenerarlo invalida el anterior.
create table if not exists landing_docs (
  id                 bigint generated by default as identity primary key,
  workspace_id       bigint not null references workspaces(id) on delete cascade,
  titulo             text not null default 'Sin título' check (char_length(titulo) between 1 and 200),
  contenido          jsonb not null,
  config             jsonb not null default '{}'::jsonb,
  version            integer not null default 1 check (version >= 1),
  -- La misma forma que `SLUG_RE` (lib/editor-landing/doc.ts). Los reservados los frena el código.
  slug               text check (slug is null or slug ~ '^[a-z0-9][a-z0-9-]{1,58}[a-z0-9]$'),
  publicado          jsonb,
  publicado_at       timestamptz,
  publicado_version  integer check (publicado_version is null or publicado_version >= 1),
  sitio_activo       boolean not null default true,
  vista_token        text check (vista_token is null or vista_token ~ '^[A-Za-z0-9_-]{43}$'),
  favorito           boolean not null default false,
  carpeta            text check (carpeta is null or char_length(carpeta) between 1 and 80),
  papelera_at        timestamptz,
  -- El `sub` de la sesión y el nombre que se mostraba al crearla. Texto y no FK: una sesión de
  -- super admin no tiene fila en `usuarios` del workspace.
  creado_por         text,
  creado_por_nombre  text,
  created_at         timestamptz not null default now(),
  updated_at         timestamptz not null default now(),
  -- Un techo, y nada más: el tope que vale lo decide el código (TOPES.bytesContenido = 1,5 MB),
  -- más bajo a propósito para que la pantalla diga «demasiado grande» antes que la base.
  constraint landing_docs_contenido_tope check (octet_length(contenido::text) <= 4000000),
  constraint landing_docs_publicado_tope check (publicado is null or octet_length(publicado::text) <= 12000000)
);
create index if not exists idx_landing_docs_ws on landing_docs (workspace_id, updated_at desc);
create unique index if not exists landing_docs_slug_uk on landing_docs (slug) where slug is not null;
create unique index if not exists landing_docs_vista_token_uk on landing_docs (vista_token) where vista_token is not null;

comment on table landing_docs is 'Landings del editor copiado de Gamma (Landing Generator). contenido = JSON de ProseMirror saneado; publicado = la foto que sirve /l/<slug>; version = concurrencia optimista. Diseño: docs/diseno-editor-landing.md.';
comment on column landing_docs.publicado is 'La FOTO publicada: { v, paginas: [{ ruta, titulo, descripcion, html }], css, fuentes, sitio, temaId, version, publicadoAt }. La página pública nunca lee contenido.';
comment on column landing_docs.slug is 'Dirección pública /l/<slug>. Única global (índice parcial). Despublicar no la suelta.';
comment on column landing_docs.vista_token is 'Link privado al borrador (/l/vista/<token>). 32 bytes en base64url. Regenerarlo invalida el anterior.';

alter table landing_docs enable row level security;
revoke all on landing_docs from anon, authenticated;

-- ── 2. El historial de versiones ─────────────────────────────────────────────
-- Una instantánea entera (título, contenido y configuración). Se guarda al publicar, antes de un
-- cambio de la IA, al restaurar (la de ANTES), a mano («Guardar versión») y sola cada 10 minutos de
-- edición (lo decide el server: `tocaVersionAutomatica`, lib/editor-landing/server-reglas.ts).
-- `motivo` es lo que se lee en el panel: «Guardado automático», «Publicada»…
create table if not exists landing_doc_versiones (
  id            bigint generated by default as identity primary key,
  workspace_id  bigint not null references workspaces(id) on delete cascade,
  doc_id        bigint not null references landing_docs(id) on delete cascade,
  titulo        text not null default '',
  contenido     jsonb not null,
  config        jsonb not null default '{}'::jsonb,
  motivo        text not null default '' check (char_length(motivo) <= 120),
  autor         text,
  created_at    timestamptz not null default now()
);
create index if not exists idx_landing_doc_versiones_ws on landing_doc_versiones (workspace_id);
create index if not exists idx_landing_doc_versiones_doc on landing_doc_versiones (doc_id, created_at desc);

comment on table landing_doc_versiones is 'Historial de versiones de una landing del editor: instantáneas enteras con su motivo y autor.';

alter table landing_doc_versiones enable row level security;
revoke all on landing_doc_versiones from anon, authenticated;

-- ── 3. Los comentarios por sección ───────────────────────────────────────────
-- `tarjeta_id` es el id estable de la sección (attrs.id de la tarjeta). Si la sección se borra, el
-- comentario queda (huérfano) y la pantalla lo muestra aparte: borrarlo con la sección sería tirar
-- una conversación por un cambio que se puede deshacer. Las respuestas cuelgan de `parent_id` y se
-- van con su comentario.
create table if not exists landing_doc_comentarios (
  id            bigint generated by default as identity primary key,
  workspace_id  bigint not null references workspaces(id) on delete cascade,
  doc_id        bigint not null references landing_docs(id) on delete cascade,
  tarjeta_id    text not null check (tarjeta_id ~ '^[A-Za-z0-9_-]{1,64}$'),
  parent_id     bigint references landing_doc_comentarios(id) on delete cascade,
  texto         text not null check (char_length(texto) between 1 and 5000),
  autor_sub     text,
  autor_nombre  text not null default '',
  resuelto      boolean not null default false,
  created_at    timestamptz not null default now()
);
create index if not exists idx_landing_doc_comentarios_ws on landing_doc_comentarios (workspace_id);
create index if not exists idx_landing_doc_comentarios_doc on landing_doc_comentarios (doc_id, created_at);

comment on table landing_doc_comentarios is 'Comentarios por sección (tarjeta) de una landing del editor, con respuestas (parent_id) y «Resolver».';

alter table landing_doc_comentarios enable row level security;
revoke all on landing_doc_comentarios from anon, authenticated;

-- ── 4. El bucket de las imágenes y videos ────────────────────────────────────
-- PÚBLICO: lo pinta el navegador de cualquier visitante de /l/<slug>, y una URL firmada vence (la
-- landing quedaría con imágenes rotas a las dos horas). La ruta es `<ws>/<uuid>.<ext>`: no es un
-- secreto, es trazabilidad y lo que vacía el reset del workspace.
--
-- ⚠️ SIN SVG NI HTML, NUNCA: un SVG es un documento ACTIVO (script, onload) y el bucket sirve bajo
-- el dominio de Supabase con nuestra landing apuntándole. Es el mismo criterio que /api/portadas.
-- La subida además se verifica por MAGIC BYTES al registrarla (`sniffMedia`): el `content-type` lo
-- pone el navegador y no decide nada.
--
-- El tope del bucket es el del VIDEO (100 MiB = TOPE_VIDEO_BYTES, lib/editor-landing/api-tipos.ts);
-- el de la imagen (15 MiB) lo aplica el server al firmar y al registrar. La lista de tipos es
-- TIPOS_IMAGEN + TIPOS_VIDEO del mismo archivo, y un test compara las dos
-- (tests/editor-landing-server.test.ts): el bucket rechaza recién al terminar de subir, y la
-- pantalla tiene que poder decir que no antes.
-- ⚠️ NO MEDIDO: el tope GLOBAL de subida del proyecto de Supabase (Settings → Storage). Si es menor
-- que 100 MiB, manda él y un video grande falla con 413 aunque este bucket lo acepte.
insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values ('landing-imagenes', 'landing-imagenes', true, 104857600, array[
  'image/png',
  'image/jpeg',
  'image/webp',
  'image/gif',
  'video/mp4',
  'video/webm'
])
on conflict (id) do update set public = true, file_size_limit = excluded.file_size_limit, allowed_mime_types = excluded.allowed_mime_types;

commit;
