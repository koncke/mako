-- =============================================================================
-- 0401_suscripcion_movimientos — los cambios de una suscripción y a qué mes va cada pago
-- =============================================================================
-- Pedido de Martín (5/11/2026): «la suscripción es suben, bajan… otros casos hay cortes… la pestaña de pagos dentro de
-- lo que sería una venta de suscripción es algo que quisiera cambiarlo completamente». La investigación y lo que se
-- copió (Chargebee): docs/investigacion-suscripciones.md. Las reglas: lib/suscripcion-meses.ts. La base:
-- lib/suscripcion-movimientos.ts.
--
-- Dos cosas, las dos aditivas:
--   1. `suscripcion_movimientos`: cada cambio de una suscripción, con la fecha desde la que vale. Se AGREGA, nunca se
--      edita: cambiar el monto desde diciembre no reescribe octubre (hasta acá había UN monto, `suscripcion_monto_usd`,
--      y cambiarlo cambiaba todos los meses para atrás). `monto` = la mensualidad desde ese mes (y el día de cobro, si
--      cambió); `corte` = deja de pagar desde ese mes; `vuelta` = vuelve desde ese mes (con su monto, si es otro).
--   2. `pagos.suscripcion_mes` y `pagos.suscripcion_ajuste`: el mes que paga un pago (Código Inmobiliario pagó noviembre
--      en DOS pagos, 94 y 144, y cada uno contaba como un mes) y si es un ajuste que no paga ningún mes (el diferencial
--      de un cliente nuevo: sus días hasta el próximo cobro). Suman a lo cobrado igual.
--
-- ⚠️ ORDEN DE DESPLIEGUE: ANTES del deploy o JUNTO. El código nuevo LEE la tabla al abrir una ficha de suscripción y al
-- contar el MRR, y si falta (42P01 / PGRST205) lee «sin cambios» y hace lo de antes. Las columnas de `pagos` se escriben
-- con un UPDATE APARTE que no tira (como `concepto` y `metodo`, mig 0292): sin ellas, el pago se registra igual y su mes
-- sale por orden (el más viejo que falta). Lo que no anda hasta aplicarla: cambiar el monto desde una fecha, cortar y
-- retomar con su historia (la pantalla y la API lo dicen), y elegir el mes de un pago. No saca nada.
--
-- ⚠️ El número es el siguiente libre el 5/11/2026 (main llega a 0394, hay una 0396 y una 0397 en camino): se confirma al
-- aplicar (ya hubo dos veces el mismo número).
--
-- Va en TENANT_TABLES (lib/workspace.ts) y en TABLAS_DE_INQUILINO (lib/tablas-de-inquilino.ts). RLS prendido y nada para
-- anon ni authenticated: se lee sólo con service role. `workspace_id` SIN default (el 1 es un cliente).
-- =============================================================================
begin;

create table if not exists suscripcion_movimientos (
  id            bigint generated by default as identity primary key,
  workspace_id  bigint not null references workspaces(id) on delete cascade,
  lead_id       bigint not null references leads(id) on delete cascade,
  tipo          text not null check (tipo in ('monto', 'corte', 'vuelta')),
  -- Vale desde el MES de esta fecha.
  desde         date not null,
  -- `monto`: la mensualidad nueva (obligatoria). `vuelta`: con cuánto vuelve (null = con la de antes del corte).
  monto_usd     numeric(12, 2) check (monto_usd is null or (monto_usd > 0 and monto_usd <= 10000000)),
  -- La moneda en que se pactó y el monto en ella (null = dólares). El USD lo declara la persona: nunca una tasa inventada.
  moneda        text check (moneda is null or char_length(moneda) = 3),
  monto_original numeric(14, 2) check (monto_original is null or monto_original > 0),
  -- El día de cobro desde ese mes (null = el de antes).
  dia           smallint check (dia is null or (dia between 1 and 31)),
  nota          text check (nota is null or char_length(nota) <= 300),
  -- Quién lo hizo. Mismo vocabulario que lead_audit.autor.
  por           text not null default 'CRM',
  created_at    timestamptz not null default now(),
  constraint suscripcion_movimientos_monto_ck check (tipo <> 'monto' or monto_usd is not null)
);

create index if not exists suscripcion_movimientos_lead on suscripcion_movimientos (workspace_id, lead_id, desde);

comment on table suscripcion_movimientos is 'Los cambios de una suscripción (lib/suscripcion-meses.ts): monto desde un mes, corte y vuelta. Se agregan, nunca se editan: no se reescribe el pasado.';

alter table suscripcion_movimientos enable row level security;
revoke all on suscripcion_movimientos from anon, authenticated;

alter table pagos add column if not exists suscripcion_mes date;
alter table pagos add column if not exists suscripcion_ajuste boolean not null default false;
comment on column pagos.suscripcion_mes is 'El mes que paga este pago de una suscripción (el día 1). null = el más viejo que falta (lib/suscripcion-meses.ts).';
comment on column pagos.suscripcion_ajuste is 'Un cobro de una suscripción que no paga ningún mes (un diferencial, un prorrateo). Suma a lo cobrado.';

commit;
