-- =============================================================================
-- 0415 — Cada formulario que llena un lead, con su nombre y sus respuestas (14/11/2026)
-- =============================================================================
-- La llamada de Martín con Julio Mazariegos (13/11, docs/relevo/llamada-julio-13-11.md, puntos 2, 5b y 6): «creo tres
-- landings: una regalo, otra video, otra para agendar; ¿cómo distingo qué formulario dispara el flujo?». Hasta acá el lead
-- guardaba UNA foto de lo que contestó (`leads.optin_respuestas`, mig 0274), pisada por el último envío, y nada decía QUÉ
-- formulario fue. Desde el Pixel v29 el opt-in trae el id y el nombre del formulario del Web Generator (`data-mako-form`):
-- esta tabla guarda un renglón por envío, para
--   · la ficha y la pestaña Tracking: «Envió el formulario Regalo», con sus respuestas;
--   · el formulario de ORIGEN del lead (el primer renglón);
--   · la condición «Envió el formulario X» de Automations.
-- El código anda SIN la tabla (lib/lead-formularios.ts lee vacío y anota el insert que falla): el ruteo, el disparador y el
-- historial del lead (`lead_audit`) no dependen de ella.
-- Sólo crea una tabla nueva: nada de lo que hay cambia ni se pierde.
-- =============================================================================
begin;

create table if not exists lead_formularios (
  id bigint generated by default as identity primary key,
  workspace_id bigint not null references workspaces(id) on delete cascade,
  lead_id bigint not null references leads(id) on delete cascade,
  -- El id del formulario o quiz del Web Generator (`data-mako-form`), o null si vino de una página de afuera.
  formulario_id text check (formulario_id is null or formulario_id ~ '^[A-Za-z0-9_-]{1,40}$'),
  formulario_nombre text check (formulario_nombre is null or char_length(formulario_nombre) <= 160),
  -- La landing y la página de MaKo («<docId>:<paginaId>», `data-mako-pagina`), si es del Web Generator.
  landing_doc_id bigint,
  pagina_id text check (pagina_id is null or char_length(pagina_id) <= 40),
  -- La URL de la página (sin datos personales: `urlDeEntradaGuardable`).
  pagina text check (pagina is null or char_length(pagina) <= 2000),
  origen text not null default 'formulario' check (origen in ('formulario', 'agenda', 'quiz')),
  respuestas jsonb not null default '[]'::jsonb check (jsonb_typeof(respuestas) = 'array'),
  -- A qué CRM entró por esta pieza (los ids de funnels), si lo decidió una asignación.
  funnels jsonb check (funnels is null or jsonb_typeof(funnels) = 'array'),
  created_at timestamptz not null default now()
);

create index if not exists lead_formularios_lead_idx on lead_formularios (workspace_id, lead_id, created_at desc);
create index if not exists lead_formularios_form_idx on lead_formularios (workspace_id, formulario_id, created_at desc) where formulario_id is not null;

alter table lead_formularios enable row level security;
revoke all on lead_formularios from anon, authenticated;
grant all on lead_formularios to service_role;

comment on table lead_formularios is
  'Un renglón por formulario que llenó un lead (Pixel v29, 14/11/2026): qué formulario del Web Generator, en qué página y qué contestó. El primero es su origen.';

commit;
