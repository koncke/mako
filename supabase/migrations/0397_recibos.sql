-- =============================================================================
-- 0397 — El libro de RECIBOS de MaKo: cada pago que entra a la plataforma tiene su recibo, con número (5/11/2026)
-- =============================================================================
-- Martín: «es súper importante que hagas un template que eso se envíe siempre por email de los recibos de compra. En este caso
-- también por WhatsApp [...] me gustaría que todo esto lo vayamos evidentemente guardando dentro de la aplicación, dentro de
-- SuperAdmin tal vez, para que tengamos un registro». El diseño y sus agujeros: docs/relevo/recibos-encargo.md; lo que se
-- construyó: docs/relevo/nube-recibos.md y docs/hallazgos-planes-y-cobro.md («Los recibos de MaKo»).
--
-- EN PALABRAS: agrega el libro (dos tablas y un contador) y dos funciones: la que da el número y la que dice qué pagos de
-- la pasarela todavía no tienen recibo. No toca ninguna tabla que exista.
--
--   · `recibos_numeracion`: una fila con `ultimo`. Nace en 2: los recibos N.º 0001 y 0002 ya salieron a mano el 5/11/2026
--     (Código Inmobiliario, por Binance). Los carga scripts/recibos-cargar-codigo.mts con su número forzado.
--   · `recibos`: el documento. SIN `workspace_id`: es el libro de la PLATAFORMA (no entra en TENANT_TABLES), y sobrevive al
--     borrado de un cliente (las FK a `workspaces` van `on delete set null`, y el nombre queda como foto en `a_nombre`).
--   · `recibo_pagos`: cada entrada de plata de un recibo (uno o varios: noviembre de Código fueron dos órdenes de Binance).
--   · `emitir_recibo(p jsonb)`: el ÚNICO que da números (tests/recibos.test.ts frena otro llamador). Toma el candado de la
--     numeración, mira si el pago o la clave ya tienen recibo y recién ahí suma uno e inserta, todo en una transacción:
--     correlativo, sin huecos y sin carreras. Arreglos de la revisión (docs/relevo/recibos-encargo.md, «Los agujeros»):
--       - una clave o un pago que YA tienen recibo devuelven ese recibo (`ya_estaba`) sólo si TODOS los pagos pedidos están
--         en él; si falta alguno, tira nombrando el número y la orden (antes, un segundo pago del mismo mes se perdía);
--       - los totales los calcula la función, por moneda, desde los renglones y los pagos (nunca vienen de afuera);
--       - acepta `estado` (la red emite `devuelto` sin mandar nada si la plata ya se devolvió).
--   · `recibos_que_faltan(ws, desde, tope)`: lo que la red (el cron de cobros) tiene que emitir. PostgREST no hace ese
--     anti-join; por eso es una función.
--
-- ORDEN DE DESPLIEGUE: da igual. El código tolera que falte (42P01, PGRST205, 42883 o PGRST202: lo dice en el log y el pago
-- sigue; un recibo nunca frena un pago). Número elegido en la nube el 5/11/2026 barriendo main, las 189 puntas, ci-rojo,
-- espera-main y las etiquetas de origin (main llega a 0394, `punta/agencia-cobro` trae OTRA 0394 y hay una 0396 en camino):
-- confirmarlo con el Cerebro al aplicar.
-- =============================================================================

begin;

create table if not exists recibos_numeracion (
  unica boolean primary key default true check (unica),
  ultimo integer not null check (ultimo >= 0)
);
-- 0001 y 0002 ya salieron a mano el 5/11/2026: el próximo es el 0003.
insert into recibos_numeracion (unica, ultimo) values (true, 2) on conflict do nothing;

create table if not exists recibos (
  id bigint generated by default as identity primary key,
  numero integer not null unique check (numero > 0),
  clave text not null check (char_length(clave) between 3 and 200),
  origen text not null check (origen in ('pasarela', 'manual')),
  estado text not null default 'emitido' check (estado in ('emitido', 'devuelto', 'devuelto_parcial', 'contracargo', 'anulado')),
  -- Quién paga ESE recibo, congelado al emitir (lib/recibos-reglas.ts, `destinoDelRecibo`): decide a quién le llega.
  paga text not null check (paga in ('solo', 'cliente', 'agencia', 'manual')),
  -- Sólo correo, ni grupo ni hilo: el grupo de un cliente de agencia lo ven los admins de la agencia.
  solo_correo boolean not null default false,
  cobro_id bigint references cobros(id) on delete set null,
  destino_ws bigint references workspaces(id) on delete set null,
  agencia_ws bigint references workspaces(id) on delete set null,
  cliente_ws bigint references workspaces(id) on delete set null,
  a_nombre text not null check (char_length(a_nombre) between 1 and 200),
  email_cobro text check (email_cobro is null or char_length(email_cobro) <= 320),
  -- El mes que cubre, si lo dijo quien lo cargó (para el aviso «ya hay recibo de noviembre»). No es una llave.
  mes text check (mes is null or mes ~ '^[0-9]{4}-(0[1-9]|1[0-2])$'),
  lineas jsonb not null check (jsonb_typeof(lineas) = 'array' and jsonb_array_length(lineas) between 1 and 30),
  total_detalle numeric(14, 2) not null,
  moneda_detalle text not null check (moneda_detalle ~ '^[A-Z0-9]{3,5}$'),
  -- Por moneda: [{ "moneda": "USDT", "monto": 238 }]. `total_recibido`/`moneda_recibido` son los de la ÚNICA moneda, o null
  -- si se pagó en más de una (nunca se suma entre monedas).
  totales_recibido jsonb not null check (jsonb_typeof(totales_recibido) = 'array'),
  total_recibido numeric(14, 2),
  moneda_recibido text check (moneda_recibido is null or moneda_recibido ~ '^[A-Z0-9]{3,5}$'),
  impuesto numeric(14, 2),
  emisor jsonb not null,
  zona text not null,
  nota_pdf text check (nota_pdf is null or char_length(nota_pdf) <= 500),
  nota_interna text check (nota_interna is null or char_length(nota_interna) <= 500),
  -- El PDF que se mandó, guardado en `contratos` (plataforma/recibos/pdf/<id>.pdf) en el primer despacho: «Bajar» da lo que
  -- recibió el cliente, aunque un deploy cambie la plantilla. Con su huella.
  pdf_path text check (pdf_path is null or pdf_path like 'plataforma/recibos/%'),
  pdf_sha256 text check (pdf_sha256 is null or pdf_sha256 ~ '^[0-9a-f]{64}$'),
  fecha_pago timestamptz not null,
  emitido_por text not null check (char_length(emitido_por) between 1 and 120),
  emitido_at timestamptz not null default now(),
  correo_estado text not null default 'pendiente' check (correo_estado in ('pendiente', 'enviando', 'enviado', 'fallo', 'reboto', 'sin_destino', 'no_va')),
  correo_intentos smallint not null default 0,
  correo_lote smallint not null default 1,
  correo_tomado_at timestamptz,
  -- Los destinatarios, CONGELADOS en el primer compare-and-set del lote: la clave de idempotencia de Resend no admite otro cuerpo.
  correo_a text[],
  -- Un id de Resend por destinatario (un POST por persona: nadie ve el correo del otro).
  correo_ids text[],
  correo_at timestamptz,
  correo_error text check (correo_error is null or char_length(correo_error) <= 300),
  wa_estado text not null default 'pendiente' check (wa_estado in ('pendiente', 'enviando', 'enviado', 'en_app', 'sin_grupo', 'fallo', 'no_va')),
  wa_tomado_at timestamptz,
  wa_ws bigint references workspaces(id) on delete set null,
  wa_id text,
  wa_at timestamptz,
  wa_error text check (wa_error is null or char_length(wa_error) <= 300),
  devuelto_at timestamptz,
  devuelto_monto numeric(14, 2),
  -- El estado de devolución que YA se le avisó a quien pagó: un parcial y después un total avisan dos veces, nunca más.
  devolucion_avisada text check (devolucion_avisada is null or devolucion_avisada in ('devuelto', 'devuelto_parcial')),
  devolucion_correo_at timestamptz,
  disputa_texto text check (disputa_texto is null or char_length(disputa_texto) <= 300),
  anulado_at timestamptz,
  anulado_por text,
  historial jsonb not null default '[]' check (jsonb_typeof(historial) = 'array'),
  updated_at timestamptz not null default now()
);
-- Una clave por recibo vivo. Anular libera la clave (se corrige emitiendo otro, con número nuevo).
create unique index if not exists recibos_clave_uk on recibos (clave) where estado <> 'anulado';
create index if not exists recibos_lista_idx on recibos (emitido_at desc);
create index if not exists recibos_destino_idx on recibos (destino_ws, emitido_at desc);
create index if not exists recibos_salida_idx on recibos (updated_at)
  where estado = 'emitido' and (correo_estado in ('pendiente', 'enviando', 'fallo') or wa_estado in ('pendiente', 'enviando'));

create table if not exists recibo_pagos (
  id bigint generated by default as identity primary key,
  recibo_id bigint not null references recibos(id) on delete restrict,
  -- La lista de medios vive en lib/recibos-reglas.ts (`MEDIOS`): acá sólo la forma.
  medio text not null check (medio ~ '^[a-z0-9_-]{2,30}$'),
  -- Normalizada en el código (`referenciaNormal`): sin espacios a los costados, y la de Binance, sus 18 dígitos.
  referencia text not null check (char_length(referencia) between 1 and 200 and referencia = btrim(referencia)),
  fecha timestamptz not null,
  monto numeric(14, 2) not null check (monto > 0),
  moneda text not null check (moneda ~ '^[A-Z0-9]{3,5}$'),
  -- DECLARADO, nunca calculado con una tasa: el del cobro, o el que escribió quien lo cargó.
  monto_usd numeric(14, 2) check (monto_usd is null or monto_usd > 0),
  impuesto numeric(14, 2) check (impuesto is null or impuesto >= 0),
  de text check (de is null or char_length(de) <= 120),
  comprobante_path text check (comprobante_path is null or (comprobante_path like 'plataforma/recibos/%' and comprobante_path not like '%..%')),
  comprobante_nombre text check (comprobante_nombre is null or char_length(comprobante_nombre) <= 200),
  anulado boolean not null default false,
  created_at timestamptz not null default now()
);
-- La llave del PAGO (nunca la del aviso): sirve igual para un aviso repetido, un reenvío a mano con id nuevo, la red y una
-- orden de Binance cargada dos veces.
create unique index if not exists recibo_pagos_uk on recibo_pagos (medio, referencia) where not anulado;
create index if not exists recibo_pagos_recibo_idx on recibo_pagos (recibo_id);

alter table recibos enable row level security;
alter table recibo_pagos enable row level security;
alter table recibos_numeracion enable row level security;
revoke all on recibos, recibo_pagos, recibos_numeracion from anon, authenticated;
grant select, insert, update on recibos, recibo_pagos to service_role;
grant select, update on recibos_numeracion to service_role;

-- ─────────────────────────────────────────────────────────────────────────────
-- emitir_recibo: el número, la llave y el insert, en una transacción.
-- Devuelve (recibo_id, numero, ya_estaba). Tira (P0001) con un texto que empieza con una MARCA que lee lib/recibos.ts:
--   RECIBO_OCUPADO <numero> <referencia> · la orden ya está en otro recibo (o la clave es de un recibo sin esa orden)
--   RECIBO_INVALIDO <motivo>            · lo que mandaron no sirve para un recibo
-- ─────────────────────────────────────────────────────────────────────────────
create or replace function public.emitir_recibo(p jsonb)
returns table (recibo_id bigint, numero integer, ya_estaba boolean)
language plpgsql security invoker set search_path = public as $f$
declare
  v_ultimo integer;
  v_num integer;
  v_id bigint;
  v_falta text;
  v_pagos jsonb := coalesce(p->'pagos', '[]'::jsonb);
  v_lineas jsonb := coalesce(p->'lineas', '[]'::jsonb);
  v_mon_det text;
  v_tot_det numeric;
  v_totales jsonb;
  v_estado text := coalesce(p->>'estado', 'emitido');
begin
  if jsonb_typeof(v_pagos) <> 'array' or jsonb_array_length(v_pagos) = 0 then
    raise exception 'RECIBO_INVALIDO un recibo necesita al menos un pago';
  end if;
  if jsonb_typeof(v_lineas) <> 'array' or jsonb_array_length(v_lineas) = 0 then
    raise exception 'RECIBO_INVALIDO un recibo necesita al menos un renglón';
  end if;
  if v_estado not in ('emitido', 'devuelto') then
    raise exception 'RECIBO_INVALIDO estado de nacimiento no válido: %', v_estado;
  end if;
  -- El mismo pago dos veces en el mismo pedido.
  if (select count(*) from jsonb_to_recordset(v_pagos) x(medio text, referencia text))
     <> (select count(distinct (x.medio, x.referencia)) from jsonb_to_recordset(v_pagos) x(medio text, referencia text)) then
    raise exception 'RECIBO_INVALIDO el mismo pago está dos veces';
  end if;

  -- El candado: de dos emisiones a la vez, la segunda espera acá y después ve lo que escribió la primera.
  select n.ultimo into v_ultimo from recibos_numeracion n where n.unica for update;
  if not found then raise exception 'RECIBO_INVALIDO falta la numeración de recibos'; end if;

  -- 1. ¿La clave ya tiene recibo? Sólo es «ya estaba» si TODOS los pagos pedidos están en él.
  select r.id, r.numero into v_id, v_num from recibos r where r.clave = p->>'clave' and r.estado <> 'anulado';
  if found then
    select x.referencia into v_falta from jsonb_to_recordset(v_pagos) x(medio text, referencia text)
      where not exists (select 1 from recibo_pagos rp where rp.recibo_id = v_id and not rp.anulado and rp.medio = x.medio and rp.referencia = x.referencia)
      limit 1;
    if found then raise exception 'RECIBO_OCUPADO % %', v_num, v_falta; end if;
    return query select v_id, v_num, true;
    return;
  end if;

  -- 2. ¿Algún pago ya tiene recibo? Igual: «ya estaba» sólo si todos están en ESE recibo.
  select r.id, r.numero into v_id, v_num
    from recibo_pagos rp join recibos r on r.id = rp.recibo_id
    join jsonb_to_recordset(v_pagos) x(medio text, referencia text) on x.medio = rp.medio and x.referencia = rp.referencia
    where not rp.anulado
    limit 1;
  if found then
    select x.referencia into v_falta from jsonb_to_recordset(v_pagos) x(medio text, referencia text)
      where not exists (select 1 from recibo_pagos rp where rp.recibo_id = v_id and not rp.anulado and rp.medio = x.medio and rp.referencia = x.referencia)
      limit 1;
    if found then
      -- La que SÍ está en el otro recibo es la que se nombra.
      select rp.referencia into v_falta from recibo_pagos rp join jsonb_to_recordset(v_pagos) x(medio text, referencia text)
        on x.medio = rp.medio and x.referencia = rp.referencia where rp.recibo_id = v_id and not rp.anulado limit 1;
      raise exception 'RECIBO_OCUPADO % %', v_num, v_falta;
    end if;
    return query select v_id, v_num, true;
    return;
  end if;

  -- 3. Los totales los calcula la base: el detalle en UNA moneda, lo recibido por moneda.
  select min(x.moneda), max(x.moneda), sum(x.monto) into v_mon_det, v_falta, v_tot_det
    from jsonb_to_recordset(v_lineas) x(moneda text, monto numeric);
  if v_mon_det is null or v_mon_det <> v_falta then
    raise exception 'RECIBO_INVALIDO los renglones tienen que ir en una sola moneda';
  end if;
  select coalesce(jsonb_agg(jsonb_build_object('moneda', t.moneda, 'monto', t.monto) order by t.moneda), '[]'::jsonb) into v_totales
    from (select x.moneda, sum(x.monto) as monto from jsonb_to_recordset(v_pagos) x(moneda text, monto numeric) group by x.moneda) t;

  -- 4. El número: el siguiente, o uno forzado que ya se gastó a mano y está libre (0001 y 0002).
  if p ? 'numero' then
    v_num := (p->>'numero')::integer;
    if v_num < 1 or v_num > v_ultimo or exists (select 1 from recibos r where r.numero = v_num) then
      raise exception 'RECIBO_INVALIDO el número % no está disponible', v_num;
    end if;
  else
    v_num := v_ultimo + 1;
    update recibos_numeracion set ultimo = v_num where unica;
  end if;

  insert into recibos (
    numero, clave, origen, estado, paga, solo_correo, cobro_id, destino_ws, agencia_ws, cliente_ws, a_nombre, email_cobro, mes, lineas,
    total_detalle, moneda_detalle, totales_recibido, total_recibido, moneda_recibido, impuesto, emisor, zona, nota_pdf, nota_interna,
    pdf_path, pdf_sha256, fecha_pago, emitido_por, emitido_at, correo_estado, correo_a, correo_ids, correo_at, wa_estado, wa_ws, wa_id, wa_at,
    devuelto_at, historial
  ) values (
    v_num, p->>'clave', p->>'origen', v_estado, p->>'paga', coalesce((p->>'solo_correo')::boolean, false),
    (p->>'cobro_id')::bigint, (p->>'destino_ws')::bigint, (p->>'agencia_ws')::bigint, (p->>'cliente_ws')::bigint,
    p->>'a_nombre', p->>'email_cobro', p->>'mes', v_lineas,
    v_tot_det, v_mon_det, v_totales,
    case when jsonb_array_length(v_totales) = 1 then (v_totales->0->>'monto')::numeric end,
    case when jsonb_array_length(v_totales) = 1 then v_totales->0->>'moneda' end,
    (p->>'impuesto')::numeric, coalesce(p->'emisor', '{}'::jsonb), coalesce(p->>'zona', 'UTC'), p->>'nota_pdf', p->>'nota_interna',
    p->>'pdf_path', p->>'pdf_sha256', (p->>'fecha_pago')::timestamptz, p->>'emitido_por', coalesce((p->>'emitido_at')::timestamptz, now()),
    coalesce(p->>'correo_estado', case when v_estado = 'emitido' then 'pendiente' else 'no_va' end),
    case when p ? 'correo_a' then array(select jsonb_array_elements_text(p->'correo_a')) end,
    case when p ? 'correo_ids' then array(select jsonb_array_elements_text(p->'correo_ids')) end,
    (p->>'correo_at')::timestamptz,
    coalesce(p->>'wa_estado', case when v_estado = 'emitido' then 'pendiente' else 'no_va' end),
    (p->>'wa_ws')::bigint, p->>'wa_id', (p->>'wa_at')::timestamptz,
    case when v_estado = 'devuelto' then now() end,
    coalesce(p->'historial', '[]'::jsonb)
  )
  returning id into v_id;

  insert into recibo_pagos (recibo_id, medio, referencia, fecha, monto, moneda, monto_usd, impuesto, de, comprobante_path, comprobante_nombre)
  select v_id, x.medio, x.referencia, x.fecha, x.monto, x.moneda, x.monto_usd, x.impuesto, x.de, x.comprobante_path, x.comprobante_nombre
  from jsonb_to_recordset(v_pagos) x(medio text, referencia text, fecha timestamptz, monto numeric, moneda text, monto_usd numeric, impuesto numeric, de text, comprobante_path text, comprobante_nombre text);

  return query select v_id, v_num, false;
end $f$;

revoke execute on function public.emitir_recibo(jsonb) from public, anon, authenticated;
grant execute on function public.emitir_recibo(jsonb) to service_role;

-- ─────────────────────────────────────────────────────────────────────────────
-- recibos_que_faltan: los pagos de la pasarela de la PLATAFORMA (modo real) que no tienen recibo, desde `p_desde`.
-- Dos fuentes: el cobro pagado o devuelto (su primer pago) y las cuotas del CRM atadas a un cobro (cubren una renovación cuyo
-- recibo se cortó). Mira cualquier recibo, también uno anulado: lo que una persona anuló no lo vuelve a emitir la red.
-- ─────────────────────────────────────────────────────────────────────────────
create or replace function public.recibos_que_faltan(p_ws bigint, p_desde timestamptz, p_tope integer)
returns table (cobro_id bigint, cuota_id bigint, proveedor text, proveedor_pago_id text, devuelto boolean, fecha timestamptz)
language sql stable security invoker set search_path = public as $f$
  select * from (
    select c.id, null::bigint, c.proveedor, c.proveedor_pago_id, c.estado = 'reembolsado', coalesce(c.pagado_at, c.updated_at)
      from cobros c
     where c.workspace_id = p_ws and c.modo = 'real' and c.estado in ('pagado', 'reembolsado') and c.proveedor_pago_id is not null
       and coalesce(c.pagado_at, c.updated_at) >= p_desde
       and not exists (select 1 from recibo_pagos rp where rp.medio = c.proveedor and rp.referencia = c.proveedor_pago_id)
    union all
    select c.id, q.id, q.proveedor, q.proveedor_pago_id, not coalesce(q.pagado, false), q.created_at
      from pagos q join cobros c on c.id = q.cobro_id and c.workspace_id = p_ws and c.modo = 'real'
     where q.workspace_id = p_ws and q.proveedor is not null and q.proveedor_pago_id is not null and q.created_at >= p_desde
       and q.proveedor_pago_id is distinct from c.proveedor_pago_id
       and not exists (select 1 from recibo_pagos rp where rp.medio = q.proveedor and rp.referencia = q.proveedor_pago_id)
  ) t
  order by 6 asc
  limit greatest(1, least(p_tope, 200));
$f$;

revoke execute on function public.recibos_que_faltan(bigint, timestamptz, integer) from public, anon, authenticated;
grant execute on function public.recibos_que_faltan(bigint, timestamptz, integer) to service_role;

commit;

