-- =============================================================================
-- 0372 — Los grupos de MaKo DENTRO DE LA APP (3/11/2026): el hilo, los invitados y lo que leyó cada persona
-- =============================================================================
-- ⚠️ ORDEN DE DESPLIEGUE: ANTES del deploy que trae lib/grupo-app.ts. Sin estas tablas la copia de los avisos loguea
-- y sigue: WhatsApp queda como está, y las pantallas del grupo no tienen qué mostrar. Agrega y no saca nada: la versión
-- desplegada no las nombra, así que aplicarla antes no le molesta a nadie.
--
-- Pedido de Martín (3/11/2026), tras el ban de la línea de MaKo: un grupo por negocio dentro del Ops Center, con aspecto de
-- WhatsApp, fijado arriba, donde caen TODOS los avisos aunque WhatsApp no los entregue, donde se puede invitar a usuarios de
-- MaKo de otro negocio, y donde MaKo participa igual que en el grupo de WhatsApp.
--
-- ⚠️ NO HAY TABLA `grupos`. El grupo ES el negocio: `workspace_id` lo identifica. Un grupo por negocio por construcción, sin
-- alta ni relleno, y un negocio nuevo ya lo tiene. El título se calcula (`tituloDelGrupo`, lib/grupo-reglas.ts).
--
--   · `grupo_mensajes`: el hilo visible. NO es `mako_doer_conv`, que es lo que vuelve al modelo: no tiene autor y excluye a
--     propósito los carteles, la agenda, los acuses y lo del equipo.
--   · `grupo_invitados`: quién entró por invitación. `desde_id` NO tiene default a propósito: con `default 0`, una lectura que
--     falla al invitar le abriría el historial entero sin ningún error. `salio_at`: la fila queda al sacarlo porque de ella
--     sale el tope de avisos (un mail y un push cada 24 h por email, también si lo sacan y lo vuelven a invitar).
--   · `grupo_leidos`: hasta dónde leyó cada persona, en su fila (no en `usuarios.perfil`, que se reescribe entero).
--
-- ⚠️ `id` ES GLOBAL Y CORRELATIVO: toda lectura por id lleva `workspace_id`. Por eso `responde_a` es una clave compuesta: una
-- cita no puede apuntar a un mensaje de OTRO negocio ni siquiera con un bug en el código. No lleva `on delete`: los mensajes no
-- se borran de a uno, y vaciar un negocio es UN statement (NO ACTION se chequea al final de él).
--
-- ⚠️ Las tres van en TABLAS_DE_INQUILINO y en FUERA_DEL_PROXY (tests/tenant-tables-contract.test.ts), NUNCA en TENANT_TABLES:
-- `getTenantDb()` le daría a un invitado el grupo de SU negocio y estamparía su ws en el mensaje. Se leen con el cliente de
-- servicio y `.eq('workspace_id', ws)`, con el ws de la URL ya autorizada (lib/grupo-puerta.ts).
--
-- Los archivos van al bucket privado `archivero`, rutas `grupos/<ws>/<uuid>.<ext>`: sin bucket nuevo.
-- SIN `default 1` en `workspace_id`, a propósito: el 1 es un cliente (Mauricio).
-- RLS prendida sin políticas y `revoke` explícito: el servidor lee y escribe con service_role.

begin;

create table if not exists grupo_mensajes (
  id             bigint generated by default as identity primary key,
  workspace_id   bigint not null references workspaces(id) on delete cascade,
  autor_tipo     text not null check (autor_tipo in ('persona', 'mako', 'equipo', 'sistema')),
  usuario_id     bigint references usuarios(id) on delete set null,
  autor_nombre   text not null default '' check (char_length(autor_nombre) <= 120),
  canal          text not null check (canal in ('app', 'whatsapp')),
  texto          text not null default '' check (char_length(texto) <= 20000),
  adjunto        jsonb,
  responde_a     bigint,
  reaccion       text check (reaccion is null or char_length(reaccion) <= 16),
  aviso_tipo     text check (aviso_tipo is null or char_length(aviso_tipo) <= 120),
  wa_message_id  text check (wa_message_id is null or char_length(wa_message_id) <= 200),
  wa_at          timestamptz,
  cliente_id     text check (cliente_id is null or char_length(cliente_id) <= 64),
  created_at     timestamptz not null default now(),
  constraint grupo_mensajes_ws_id_uk unique (workspace_id, id),
  constraint grupo_mensajes_responde_fk foreign key (workspace_id, responde_a) references grupo_mensajes (workspace_id, id)
);
comment on table grupo_mensajes is 'El hilo visible del grupo de cada negocio en la app (mig 0372). No es la memoria del modelo (mako_doer_conv). El índice único (workspace_id, id) sirve también para leer el hilo en los dos sentidos.';

-- Una re-entrega de Evolution, o dos líneas con el mismo mensaje, son UNA fila.
create unique index if not exists ux_grupo_mensajes_wa on grupo_mensajes (workspace_id, wa_message_id) where wa_message_id is not null;
-- El navegador reintenta con el mismo `idLocal` y no duplica.
create unique index if not exists ux_grupo_mensajes_cliente on grupo_mensajes (workspace_id, usuario_id, cliente_id) where cliente_id is not null;

create table if not exists grupo_invitados (
  workspace_id       bigint not null references workspaces(id) on delete cascade,
  email              text not null check (email = lower(email) and char_length(email) <= 254),
  usuario_id         bigint references usuarios(id) on delete cascade,
  invito_usuario_id  bigint references usuarios(id) on delete set null,
  desde_id           bigint not null,
  invitado_at        timestamptz not null default now(),
  abrio_at           timestamptz,
  avisado_at         timestamptz,
  salio_at           timestamptz,
  created_at         timestamptz not null default now(),
  primary key (workspace_id, email)
);
comment on table grupo_invitados is 'Quién entró al grupo de un negocio por invitación (mig 0372). Lee sólo id > desde_id. salio_at: ya no está; la fila queda por el tope de avisos.';
create index if not exists ix_grupo_invitados_usuario on grupo_invitados (usuario_id) where usuario_id is not null;
create index if not exists ix_grupo_invitados_quien on grupo_invitados (invito_usuario_id, invitado_at);

create table if not exists grupo_leidos (
  workspace_id  bigint not null references workspaces(id) on delete cascade,
  usuario_id    bigint not null references usuarios(id) on delete cascade,
  hasta_id      bigint not null default 0,
  updated_at    timestamptz not null default now(),
  primary key (workspace_id, usuario_id)
);
comment on table grupo_leidos is 'Hasta qué mensaje leyó cada persona el grupo de un negocio (mig 0372). Sube y nunca baja.';
create index if not exists ix_grupo_leidos_usuario on grupo_leidos (usuario_id);

alter table grupo_mensajes enable row level security;
alter table grupo_invitados enable row level security;
alter table grupo_leidos enable row level security;
revoke all on grupo_mensajes from anon, authenticated;
revoke all on grupo_invitados from anon, authenticated;
revoke all on grupo_leidos from anon, authenticated;

commit;
