-- =============================================================================
-- 0422_inspiracion — Inspiración: los links de Instagram que el dueño le manda a MaKo por WhatsApp, guardados y ordenados
-- en las carpetas del negocio (sus series de contenido). Lo dudoso espera en la bandeja de Copywriting (docs/inspiracion/diseno.md).
-- Sólo agrega: dos tablas nuevas, nada existente cambia.
-- =============================================================================
begin;

create table if not exists inspiracion_carpetas (
  id           bigint generated by default as identity primary key,
  workspace_id bigint not null references workspaces(id) on delete cascade,
  nombre       text not null,
  -- Una línea de qué va ahí: es lo que lee el clasificador.
  descripcion  text not null default '',
  orden        int not null default 0,
  creada_por   text not null default 'persona' check (creada_por in ('persona', 'mako')),
  creada_en    timestamptz not null default now()
);
create index if not exists idx_inspiracion_carpetas_ws on inspiracion_carpetas (workspace_id);
create unique index if not exists uq_inspiracion_carpetas_nombre on inspiracion_carpetas (workspace_id, lower(nombre));
comment on table inspiracion_carpetas is 'Inspiración (0422): las carpetas del negocio donde se ordenan las piezas guardadas (sus series de contenido).';

create table if not exists inspiracion_piezas (
  id            bigint generated by default as identity primary key,
  workspace_id  bigint not null references workspaces(id) on delete cascade,
  -- El shortcode de la publicación, o «@usuario» si es una cuenta entera. Único por negocio: el mismo link no se guarda dos veces.
  ref           text not null,
  url           text not null,
  tipo_link     text not null check (tipo_link in ('reel', 'post', 'cuenta')),
  -- Lo que devuelve la lectura (Apify).
  cuenta        text,
  pie           text,
  miniatura_url text,
  metricas      jsonb not null default '{}'::jsonb,
  -- Lo que dijo la IA: formato, de qué trata, gancho, estructura, CTA.
  lectura       jsonb not null default '{}'::jsonb,
  carpeta_id    bigint references inspiracion_carpetas(id) on delete set null,
  sugerida_id   bigint references inspiracion_carpetas(id) on delete set null,
  carpeta_nueva text,
  confianza     int,
  por_que       text,
  estado        text not null default 'leyendo' check (estado in ('leyendo', 'ordenada', 'por_revisar', 'sin_leer')),
  -- Lo que escribió la persona junto al link («para la serie de ventas»).
  nota          text,
  origen        text not null default 'whatsapp' check (origen in ('whatsapp', 'app')),
  mensaje_id    text,
  creada_en     timestamptz not null default now(),
  -- La persona la confirmó (Sí en la bandeja, o la movió a mano). Como `revisada_en` de carruseles_biblioteca_piezas (0411).
  revisada_en   timestamptz,
  -- Cuándo se leyó el post en Instagram (Apify). null = todavía no: la pieza se guardó igual y se relee cuando la lectura vuelve
  -- a andar (19/11/2026: la clave de Apify daba 401 y ningún link podía quedar en «no pude guardar»).
  leida_en      timestamptz
);
create index if not exists idx_inspiracion_piezas_ws on inspiracion_piezas (workspace_id);
create unique index if not exists uq_inspiracion_piezas_ref on inspiracion_piezas (workspace_id, ref);
create index if not exists idx_inspiracion_piezas_estado on inspiracion_piezas (workspace_id, estado);
comment on table inspiracion_piezas is 'Inspiración (0422): cada link de Instagram guardado (reel, post o cuenta) con su lectura y su carpeta.';

-- RLS on sin políticas = sólo del lado del servidor (service_role), como el resto (0359).
alter table inspiracion_carpetas enable row level security;
alter table inspiracion_piezas enable row level security;
revoke all on inspiracion_carpetas from anon, authenticated;
revoke all on inspiracion_piezas from anon, authenticated;

commit;
