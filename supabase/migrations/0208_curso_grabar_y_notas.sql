-- =============================================================================
-- 0208 — El curso: qué clases hay que GRABAR, y las notas (con adjunto) de cada clase y etapa
-- =============================================================================
-- ⚠️ ORDEN DE DESPLIEGUE: se aplica ANTES del deploy: el código nuevo la lee. La tab
-- /customer-success/curso lee `curso_clases.grabar` y `curso_clase_notas` al dibujarse, y las
-- notas suben al bucket `curso-notas`. Agrega y no saca nada: la versión desplegada no mira
-- ninguna de las tres cosas, así que aplicarla antes no le molesta.
--
-- ⚠️ Y LO QUE NO DEPENDE DE ESTA MIGRACIÓN, a propósito: el portal del alumno, la ficha y el cron
-- leen las clases con `COLUMNAS_CLASE` (lib/curso-datos.ts), que NO trae `grabar`. Si esta
-- migración se atrasa, lo único que se rompe es la tab Curso del equipo, nunca lo que ve un
-- cliente de Mauricio.
--
-- Pedidos (tablero, 06/10/2026):
--   · #693 «Agregar botón de "grabar / no grabar" en el programa del curso».
--   · #692 «Habilitar sección de notas y subida de archivos en las clases del curso»: una caja
--     de notas debajo de cada clase (y de cada etapa), con PDF, documentos y planillas.

begin;

-- ── 1. Grabar / no grabar ────────────────────────────────────────────────────
-- ⚠️ SIN DEFAULT, y NULL ES UN VALOR: «sin decidir». Las 107 clases cargadas el 06/10 quedan así
-- y las marca Mauricio; un default (o un backfill) inventaría una decisión que nadie tomó, y el
-- contador «por grabar» de la cabecera contaría lo que nadie eligió grabar.
-- ⚠️ Lo escribe UNA sola función (`marcarGrabar`, lib/curso-admin.ts) y sólo esa columna:
-- guardar la clase entera no la toca, porque `validarClase` no la trae.
alter table curso_clases add column if not exists grabar boolean;

comment on column curso_clases.grabar is 'true = hay que grabarla · false = no se graba · NULL = sin decidir. Sólo la escribe marcarGrabar (lib/curso-admin.ts); el portal del alumno no la lee.';

-- ── 2. Las notas del equipo sobre el curso ───────────────────────────────────
-- Una nota cuelga de UNA clase o de UNA etapa (la clave de `producto_entrega`, como
-- `curso_clases.etapa`), nunca de las dos: una nota de clase sigue a la clase si la mueven de
-- etapa. Puede traer UN adjunto, que vive en el bucket `curso-notas`.
--
-- ⚠️ ESTO ES DEL EQUIPO Y NUNCA VIAJA AL ALUMNO: lib/curso-portal.ts no la lee, y un test lo fija
-- (tests/curso-portal.test.ts). Las notas pueden nombrar a otros clientes de Mauricio.
create table if not exists curso_clase_notas (
  id              bigint generated by default as identity primary key,
  workspace_id    bigint not null default 1 references workspaces(id) on delete cascade,
  producto_id     bigint not null references productos(id) on delete cascade,
  -- Borrar la clase se lleva sus notas. El adjunto queda huérfano en el bucket y lo barre el
  -- cron de huérfanos (/api/cron/curso-purga) pasadas 24 h.
  clase_id        bigint references curso_clases(id) on delete cascade,
  etapa           text,
  -- Quién la escribió: el email decide quién la puede borrar (la autora o un admin); el nombre
  -- es lo que se dibuja. Texto y no FK: una sesión de super admin no tiene fila en `usuarios`
  -- del workspace.
  autor_email     text,
  autor_nombre    text,
  texto           text not null default '',
  -- El adjunto: `<ws>/<producto>/<uuid>.<ext>` en `curso-notas`. El nombre original va APARTE y
  -- nunca en la ruta (acentos, espacios, el nombre de un cliente).
  archivo_path    text,
  archivo_nombre  text,
  archivo_mime    text,
  archivo_bytes   bigint,
  created_at      timestamptz not null default now(),
  constraint curso_clase_notas_destino check ((clase_id is null) <> (etapa is null)),
  constraint curso_clase_notas_contenido check (length(btrim(texto)) > 0 or archivo_path is not null),
  constraint curso_clase_notas_archivo check ((archivo_path is null) = (archivo_nombre is null))
);
create index if not exists idx_curso_clase_notas_clase on curso_clase_notas (workspace_id, clase_id, created_at) where clase_id is not null;
create index if not exists idx_curso_clase_notas_etapa on curso_clase_notas (workspace_id, producto_id, etapa, created_at) where etapa is not null;

comment on table curso_clase_notas is 'Notas del EQUIPO sobre una clase o una etapa del curso, con un adjunto opcional en el bucket curso-notas. Nunca viajan al portal del alumno.';

alter table curso_clase_notas enable row level security;
revoke all on curso_clase_notas from anon, authenticated;

-- ── 3. El bucket de los adjuntos ─────────────────────────────────────────────
-- PRIVADO: se lee con una URL firmada de vida corta que se pide al hacer clic. La subida va
-- directo del navegador con una URL firmada (una server action topa en 1 MB), como los videos.
-- 25 MiB por archivo: documentos, planillas e imágenes, no videos (para eso está curso-videos).
-- ⚠️ LA LISTA DE TIPOS ES LA MISMA QUE `MIME_NOTA` (app/customer-success/curso/reglas.ts), y el
-- tope es `TOPE_NOTA_BYTES`: un test compara las dos. Si se cambia una, se cambia la otra — el
-- bucket rechaza recién al terminar de subir, y la pantalla tiene que poder decir «no» antes.
insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values ('curso-notas', 'curso-notas', false, 26214400, array[
  'application/pdf',
  'application/msword',
  'application/vnd.openxmlformats-officedocument.wordprocessingml.document',
  'application/vnd.ms-excel',
  'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet',
  'application/vnd.ms-powerpoint',
  'application/vnd.openxmlformats-officedocument.presentationml.presentation',
  'application/vnd.oasis.opendocument.text',
  'application/vnd.oasis.opendocument.spreadsheet',
  'text/csv',
  'text/plain',
  'image/png',
  'image/jpeg',
  'image/webp',
  'image/gif'
])
on conflict (id) do update set public = false, file_size_limit = excluded.file_size_limit, allowed_mime_types = excluded.allowed_mime_types;

commit;
