-- =============================================================================
-- 0074_wa_borradores — Cola de BORRADORES del WhatsApp no oficial (F2.3)
-- =============================================================================
-- Regla dura del PDF: a leads calientes la app NUNCA dispara automático directo
-- por el número no oficial (riesgo alto de ban si reportan spam). En su lugar
-- deposita el mensaje personalizado como BORRADOR y un humano (setter) lo envía
-- con 1 clic. El envío automático directo queda SOLO para clientes que ya pagaron
-- (riesgo bajo) y para alertas al propio dueño (F4).
--
-- origen: quién generó el borrador — 'nutricion' (motor), 'mako' (IA), 'manual'.

begin;

create table if not exists wa_borradores (
  id             bigint generated by default as identity primary key,
  workspace_id   bigint not null default 1 references workspaces(id) on delete cascade,
  lead_id        bigint references leads(id) on delete set null,
  telefono       text not null,                     -- destino (normalizado)
  chat_jid       text,                              -- remoteJid si lo conocemos
  texto          text not null,
  origen         text not null default 'nutricion', -- nutricion | mako | manual
  secuencia_id   bigint,                            -- si viene del motor de nutrición
  paso           int,
  inscripcion_id bigint,
  estado         text not null default 'pendiente', -- pendiente | enviado | descartado
  enviado_at     timestamptz,
  enviado_por    text,                              -- email del que lo mandó
  created_at     timestamptz not null default now()
);

create index if not exists idx_wa_borradores_pend
  on wa_borradores (workspace_id, estado, created_at);
-- Anti-duplicado del toque de nutrición: un mismo (inscripcion, paso) se deposita
-- UNA sola vez aunque el cron reintente. NO parcial (para que sirva de target del
-- ON CONFLICT del upsert). Los borradores manuales/MaKo tienen inscripcion_id NULL
-- → Postgres trata los NULL como distintos, así que no colisionan entre sí.
create unique index if not exists uq_wa_borradores_toque
  on wa_borradores (workspace_id, inscripcion_id, paso);

comment on table wa_borradores is
  'Cola de borradores del WhatsApp no oficial: mensajes que el setter envía con 1 clic (leads calientes nunca reciben automático directo).';

alter table wa_borradores enable row level security;

commit;
