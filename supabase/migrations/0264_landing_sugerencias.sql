-- y el panel del diagnóstico (app/landing-generator/diagnostico/). El código nuevo LEE y ESCRIBE esta
-- tabla desde el primer análisis: sin ella, el panel contesta «relation does not exist» al abrir el
-- diagnóstico. Agrega y no saca nada: la versión desplegada no la nombra, así que aplicarla antes no le
-- molesta a nadie.
--
-- (Se escribió como 0259; se renumeró a 0264 antes de aplicarse el 12/10/2026: la 0258 la tomó la
-- sesión del CRM y las 0260-0262 la de Graphics.)
--
-- Pedido de Martín (11/10/2026), punto 7 de la tanda 2, textual: «También quiero que al analizar una
-- landing sea como un "tutorial" de los que tenemos en MaKo, que se ponga opaco y señale el lugar donde
-- se esta haciendo el comentario, y luego que queden guardados todos los comentarios y sugerencias y
-- claro, la opción de solucionarlo allí mismo con IA.» Decisión T5 de docs/diseno-editor-landing.md.
--
-- Una fila por COMENTARIO (un hallazgo del Landing Analyst con su cita textual), de una landing NUESTRA
-- (`doc_id`) o de una de AFUERA (`url`, normalizada como en landing_analyses): exactamente uno de los dos.
--   · `hallazgo`: el hallazgo entero, con la forma de `LandingHallazgo` (lib/landing-analyst.ts):
--     titulo, severidad, seccion, cita, por_que, arreglo.
--   · `cita`: la cita textual, aparte (con ella el panel ubica el bloque que señala).
--   · `seccion_id`: la sección (tarjeta) de una landing nuestra donde está la cita, si se encontró.
--   · `estado`: 'pendiente' | 'resuelta' | 'descartada'. La lista es `ESTADOS_SUGERENCIA`
--     (lib/editor-landing/diagnostico.ts): si cambia una, cambia la otra (el test las compara).
--   · `clave`: de qué landing es y qué dice (título y cita normalizados, `claveSugerencia`). Con el
--     índice único, volver a analizar no repite lo que ya está guardado — tampoco lo que se descartó.
-- Descartar no es borrar (AGENTS.md, «cerrar no es borrar»): la fila queda con su estado.
--
-- `workspace_id` SIN default (nunca es del dueño por omisión), RLS prendida sin políticas y `revoke`
-- explícito: el que mantiene afuera a la clave pública es el revoke. El servidor lee con service_role.
-- ⚠️ Y VA A DOS REGISTROS DEL CÓDIGO (el compilador no ve ninguno): `TENANT_TABLES` (lib/workspace.ts,
-- para que getTenantDb la acote) y `TABLAS_DE_INQUILINO` (lib/tablas-de-inquilino.ts, para que el reset
-- y el borrado del workspace la vacíen).

begin;

create table if not exists landing_sugerencias (
  id            bigint generated by default as identity primary key,
  workspace_id  bigint not null references workspaces(id) on delete cascade,
  doc_id        bigint references landing_docs(id) on delete cascade,
  url           text check (url is null or char_length(url) between 8 and 2000),
  hallazgo      jsonb not null,
  cita          text not null default '' check (char_length(cita) <= 1200),
  seccion_id    text check (seccion_id is null or seccion_id ~ '^[A-Za-z0-9_-]{1,64}$'),
  estado        text not null default 'pendiente' check (estado in ('pendiente', 'resuelta', 'descartada')),
  clave         text not null check (char_length(clave) between 3 and 200),
  created_at    timestamptz not null default now(),
  updated_at    timestamptz not null default now(),
  -- De una landing nuestra o de una de afuera: exactamente uno de los dos.
  constraint landing_sugerencias_un_objetivo check ((doc_id is null) <> (url is null))
);

create unique index if not exists uq_landing_sugerencias_clave on landing_sugerencias (workspace_id, clave);
create index if not exists idx_landing_sugerencias_ws on landing_sugerencias (workspace_id);
create index if not exists idx_landing_sugerencias_doc on landing_sugerencias (doc_id) where doc_id is not null;
create index if not exists idx_landing_sugerencias_url on landing_sugerencias (workspace_id, url) where url is not null;

comment on table landing_sugerencias is 'Los comentarios del diagnóstico de una landing (nuestra o de afuera): el hallazgo con su cita y su estado (pendiente / resuelta / descartada).';

alter table landing_sugerencias enable row level security;
revoke all on landing_sugerencias from anon, authenticated;

commit;
