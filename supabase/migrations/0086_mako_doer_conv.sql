-- =============================================================================
-- 0086_mako_doer_conv — memoria de conversación del doer "Hola MaKo" por grupo
-- =============================================================================
-- MaKo tiene que recordar lo que se habló en el grupo (como cualquier chat de IA):
-- guardamos cada turno (del dueño y de MaKo) por grupo y lo re-inyectamos como
-- historial en cada respuesta. Así cada mensaje tiene más sentido que el anterior.
-- Scopeado por workspace.

begin;

create table if not exists mako_doer_conv (
  id           bigint generated by default as identity primary key,
  workspace_id bigint not null default 1 references workspaces(id) on delete cascade,
  grupo_jid    text not null,                       -- grupo de WhatsApp
  role         text not null,                       -- 'user' (dueño/cliente) | 'assistant' (MaKo)
  content      text not null,                       -- texto (o transcripción de la nota de voz)
  wa_message_id text,                               -- id del mensaje de WhatsApp (dedup/trazabilidad)
  created_at   timestamptz not null default now()
);

-- Leer el historial reciente de un grupo, en orden.
create index if not exists ix_mako_conv_grupo
  on mako_doer_conv (workspace_id, grupo_jid, created_at);

comment on table mako_doer_conv is
  'Historial de la conversación del doer "Hola MaKo" por grupo (memoria de contexto). Se re-inyecta como historial en cada respuesta.';

alter table mako_doer_conv enable row level security;

commit;

notify pgrst, 'reload schema';
