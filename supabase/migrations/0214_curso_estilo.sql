-- =============================================================================
-- 0214_curso_estilo — cómo se VE el curso de un producto: el color, el título, la
-- descripción y las portadas (del curso, de cada etapa y de cada clase).
-- =============================================================================
-- Pedido de Martín (07/10/2026), mirando la tab Curso con el diseño de Conocimientos:
-- «Permite personalizar cosas, como colores (el verde), las portadas, los títulos solo
-- con darle click». Lo ve también el alumno en su portal.
--
-- UNA FILA POR AJUSTE (clave/valor), y no una fila por producto con N columnas:
--   · cada cambio es un upsert de UNA clave, así que dos personas cambiando dos portadas
--     a la vez no se pisan (con una fila entera, el guardado de la segunda devolvía la
--     portada vieja de la primera: AGENTS.md, «un campo nuevo en un objeto que se guarda
--     ENTERO»);
--   · volver al default es BORRAR la fila: «nadie lo eligió» y «eligió lo de siempre» no
--     quedan mezclados en un valor.
-- Las claves y lo que vale cada una las decide el código (lib/curso-estilo.ts,
-- `sanearAjuste`): 'acento', 'titulo', 'resumen', 'portada', 'portada:etapa:<key>' y
-- 'portada:clase:<id>'. La base sólo pone techos de largo.
--
-- ⚠️ ORDEN DE DESPLIEGUE: va ANTES (o junto con) el deploy. El código nuevo la LEE para
--    dibujar; sin la tabla la lectura falla y el curso se dibuja con el estilo de siempre
--    (es cosmético: cae al default sin tumbar nada), pero guardar daría error.
begin;

create table if not exists curso_estilo (
  id           bigint generated by default as identity primary key,
  workspace_id bigint not null default 1 references workspaces(id) on delete cascade,
  producto_id  bigint not null references productos(id) on delete cascade,
  clave        text not null check (char_length(clave) between 1 and 80),
  valor        text not null check (char_length(valor) between 1 and 2000),
  updated_at   timestamptz not null default now(),
  updated_by   text
);
create unique index if not exists curso_estilo_uk on curso_estilo (workspace_id, producto_id, clave);
create index if not exists idx_curso_estilo_producto on curso_estilo (workspace_id, producto_id);

comment on table curso_estilo is
  'Cómo se ve el curso de un producto (color, título, descripción, portadas). Una fila por ajuste; sin fila = el default. Lo valida lib/curso-estilo.ts.';

-- RLS on sin políticas = sólo server-side (service_role), igual que el resto.
alter table curso_estilo enable row level security;
revoke all on curso_estilo from anon, authenticated;

commit;
