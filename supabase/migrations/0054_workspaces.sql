-- =============================================================================
-- 0054 — workspaces: aislamiento multi-inquilino de los datos del dashboard
-- =============================================================================
-- Hasta acá todo el dato de negocio (leads, métricas, funnel, onboarding, etc.)
-- vivía global en una sola base y cualquier usuario logueado lo veía. Este
-- cambio introduce `workspaces` (un cliente = un workspace) y le agrega
-- `workspace_id` a cada tabla de datos por-cliente. El scoping real lo hace la
-- app (lib/workspace.ts) porque el service_role bypassa RLS.
--
-- Regla de oro de seguridad de esta migración: es ADITIVA. Todas las columnas
-- entran con DEFAULT 1, así:
--   · todo lo existente queda en el workspace 1 = Mauricio (dueño) → su
--     dashboard no cambia;
--   · los 12 crons siguen escribiendo sin tocarlos (sus inserts no ponen
--     workspace_id → cae el default 1).
-- Los PK/unique se hacen compuestos SOLO donde un usuario nuevo escribiría y
-- colisionaría con el dueño (app_settings.key, funnel singleton, clave de
-- secuencias, name+language de plantillas). Las tablas que hoy solo escriben
-- los crons (métricas, transcripts, closing/script analyses, adset budgets)
-- mantienen su PK/unique de una sola columna; el PK compuesto por workspace se
-- hará en la Fase 2 (ingesta por-cliente).
--
-- Seguro de re-ejecutar (idempotente) y transaccional.
-- =============================================================================

begin;

-- 1) Tabla de workspaces + workspace dueño (id 1 = Mauricio).
create table if not exists workspaces (
  id         bigint generated by default as identity primary key,
  nombre     text not null,
  slug       text unique,
  estado     text not null default 'activo',   -- activo | pausado
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

comment on table workspaces is
  'Un cliente = un workspace. El workspace 1 es el dueño (Mauricio) y contiene todos los datos previos a la migración multi-inquilino.';

insert into workspaces (id, nombre, slug, estado)
  values (1, 'Mauricio Bustos', 'mauricio', 'activo')
  on conflict (id) do nothing;

-- Reencaminar la secuencia de identity para que el próximo workspace sea >= 2.
select setval(pg_get_serial_sequence('workspaces', 'id'),
              greatest((select max(id) from workspaces), 1));

alter table workspaces enable row level security;

-- 2) workspace_id NOT NULL DEFAULT 1 + índice en cada tabla de datos por-cliente.
do $$
declare
  t text;
  tenant text[] := array[
    'ad_transcripts','adset_budget_daily','anthropic_usage','app_settings','chart_chats',
    'chart_sessions','closing_analyses','credenciales','email_broadcast_envios','email_broadcasts',
    'experimento_tareas','experimentos','funnel_config','landing_visits','lead_audit','leads',
    'marketing_metrics_daily','nutricion_envios','nutricion_inscripciones','nutricion_secuencias',
    'pagos','pipeline_stages','retros','review_queue','script_analyses','script_drafts',
    'tarea_categorias','vsl_events','whatsapp_template_drafts'
  ];
begin
  foreach t in array tenant loop
    execute format(
      'alter table %I add column if not exists workspace_id bigint not null default 1 references workspaces(id)', t);
    execute format(
      'create index if not exists %I on %I (workspace_id)', 'idx_'||t||'_ws', t);
  end loop;
end $$;

-- 3) usuarios: a qué workspace pertenece cada cuenta (nullable: los admin cruzan
--    workspaces vía impersonación, no tienen uno propio).
alter table usuarios add column if not exists workspace_id bigint references workspaces(id);

-- 4) Claves compuestas por workspace SOLO donde un usuario nuevo colisionaría
--    con el dueño.

-- 4a) app_settings: la PK pasa de (key) a (workspace_id, key) — cada cliente
--     tiene sus propios objetivos/onboarding/perfil/prompts.
do $$
begin
  if exists (
    select 1 from pg_constraint
    where conname = 'app_settings_pkey' and conrelid = 'app_settings'::regclass
      and array_length(conkey, 1) = 1
  ) then
    alter table app_settings drop constraint app_settings_pkey;
    alter table app_settings add constraint app_settings_pkey primary key (workspace_id, key);
  end if;
end $$;

-- 4b) funnel_config: romper el singleton (id=1) → una fila por workspace.
alter table funnel_config drop constraint if exists funnel_config_singleton;
create unique index if not exists funnel_config_ws_uk on funnel_config (workspace_id);

-- 4c) nutricion_secuencias.clave: única por workspace.
alter table nutricion_secuencias drop constraint if exists nutricion_secuencias_clave_key;
drop index if exists nutricion_secuencias_clave_key;
create unique index if not exists nutricion_secuencias_ws_clave on nutricion_secuencias (workspace_id, clave);

-- 4d) whatsapp_template_drafts (name, language): única por workspace.
alter table whatsapp_template_drafts drop constraint if exists whatsapp_template_drafts_name_language_key;
drop index if exists whatsapp_template_drafts_name_language_key;
create unique index if not exists wa_tpl_ws_name_lang on whatsapp_template_drafts (workspace_id, name, language);

commit;
