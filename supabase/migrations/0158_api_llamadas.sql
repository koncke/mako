-- =============================================================================
-- 0158_api_llamadas — bitácora de la API de MaKo: una fila por llamada HTTP
-- =============================================================================
-- Con cientos de operaciones detrás de un bearer que vive en la máquina de un
-- tercero, la única forma de contestar «¿me filtraron el token?» es saber qué
-- pidió, cuándo y desde dónde. La escribe lib/api-mako/bitacora.ts, best-effort,
-- con workspace_id EXPLÍCITO (no hay sesión: lo resolvió el token). Sin `default 1`
-- a propósito: una fila sin workspace no puede caer en el de Mauricio.
-- Scopeada por workspace → TENANT_TABLES (lib/workspace.ts).
begin;

create table if not exists api_llamadas (
  id           bigint generated by default as identity primary key,
  workspace_id bigint not null references workspaces(id) on delete cascade,
  operacion    text not null,
  canal        text not null,                 -- 'http' hoy; 'whatsapp' | 'app' si se quiere medir
  ok           boolean not null,
  status       integer not null,
  ms           integer not null,
  ip           text,                          -- recortada: dos últimos octetos en cero
  created_at   timestamptz not null default now()
);

create index if not exists ix_api_llamadas_ws on api_llamadas (workspace_id, created_at desc);

comment on table api_llamadas is 'Bitácora de la API de MaKo (/api/v1): qué operación pidió cada token, cuándo, desde dónde y cómo salió.';

alter table api_llamadas enable row level security;

commit;

notify pgrst, 'reload schema';
