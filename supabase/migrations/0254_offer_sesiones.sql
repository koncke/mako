-- 0254 — offer_sesiones: las conversaciones de la tab «Offer» (Analyst + Generator en una)
-- =============================================================================
-- Pedido de Martín (11/10/2026): «Implementa completamente la funcionalidad de "Offer Analyst" y
-- "Offer Generator" pero todo en una misma tab que se llame "Offer"… algo simple como un chat con una
-- IA… y que el resultado final sea que te dé un PDF con la conclusión».
--
-- ⚠️ ORDEN DE DESPLIEGUE: **ANTES o JUNTO** con el deploy que trae app/api/offer y app/offer. AGREGA
-- una tabla que el código nuevo YA LEE (AGENTS.md «Toda migración decide su ORDEN»): sin ella, la tab
-- abre con el error de lectura y el primer mensaje contesta un 500. No saca nada: la versión desplegada
-- no la mira, así que aplicarla antes no le molesta a nadie.
--
-- ⚠️ El número: 0249-0251 están SIN TRACKEAR en el clon (otras sesiones, 11/10/2026) y 0252-0253 se
-- dejaron libres por si alguna de ellas ya los tiene en su worktree. Si al integrar alguien se adelantó
-- con 0254, se RENUMERA antes de pushear y se borra este archivo.
--
-- UNA FILA POR CONVERSACIÓN. Todo lo de la conversación vive en la misma fila (mensajes, piezas,
-- documentos, borrador y conclusiones) porque se lee y se escribe junto, y porque el reparto entre
-- tablas no le compra nada a una lista que no pasa de unas decenas por negocio. Las escrituras son
-- compare-and-set sobre `updated_at` (lib/offer-sesiones.ts): dos archivos que se suben a la vez
-- agregan a `documentos` sin pisarse.
--
-- `documentos` guarda el TEXTO de cada archivo (recortado a 40.000 caracteres), no el binario: el
-- binario se sube al bucket `archivero` en `<ws>/offer/<uuid>`, se lee una vez y se BORRA (lo hace la
-- ruta, también si la lectura falla). La vista que baja al navegador NUNCA lleva ese texto.
--
-- `borrador` es el diagnóstico entre «diagnosticar» y «generar» (los dos pasos son dos pedidos porque
-- juntos no entran en los 300 s de una ruta). Un mensaje nuevo del dueño lo vacía: un diagnóstico de
-- una conversación que siguió ya no la describe.
--
-- `conclusiones` es un array de versiones (la última es la vigente): afinar y volver a concluir no
-- pisa la anterior. `oferta_id` + `oferta_version` dicen qué versión se guardó como fila de `ofertas`
-- (un doble clic en «Guardar como oferta» devuelve la misma fila en vez de crear dos).
--
-- ⚠️ Y VA A `TENANT_TABLES` (lib/workspace.ts) y a `TABLAS_DE_INQUILINO` (lib/tablas-de-inquilino.ts):
-- sin lo primero `getTenantDb()` es PASSTHROUGH (la lista mostraría las conversaciones de todos los
-- negocios); sin lo segundo, el reset y el borrado de un negocio la dejan atrás.
-- =============================================================================

begin;

create table if not exists offer_sesiones (
  id             bigint generated by default as identity primary key,
  workspace_id   bigint not null default 1 references workspaces(id) on delete cascade,
  titulo         text not null default 'Mi oferta' check (char_length(titulo) between 1 and 120),
  estado         text not null default 'conversando' check (estado in ('conversando', 'concluida')),
  -- [{id, de: 'mako'|'yo', texto, at, opciones?, adjuntos?}] — lib/offer-marco.ts → OfferMensaje.
  mensajes       jsonb not null default '[]'::jsonb,
  -- {<pieza>: {valor, fuente: 'negocio'|'chat'|'doc', at}} — lib/offer-marco.ts → PiezasSabidas.
  piezas         jsonb not null default '{}'::jsonb,
  -- [{id, nombre, via, texto, chars, aviso?, at}] — el texto recortado a 40.000 caracteres. Tope: 12.
  documentos     jsonb not null default '[]'::jsonb,
  -- {diagnostico, calculo, modelo, at} entre «diagnosticar» y «generar»; null fuera de esa ventana.
  borrador       jsonb,
  -- [ConclusionOferta] — la última es la vigente.
  conclusiones   jsonb not null default '[]'::jsonb,
  -- La fila de `ofertas` que se creó con «Guardar como oferta», y de qué versión de la conclusión.
  -- Sin FK a propósito: borrar la oferta desde su editor no tiene por qué borrar la conversación.
  oferta_id      bigint,
  oferta_version integer,
  -- Email (o `sub`) de quien abrió la conversación. Sólo para auditar.
  creado_por     text,
  created_at     timestamptz not null default now(),
  updated_at     timestamptz not null default now()
);

create index if not exists idx_offer_sesiones_ws_updated on offer_sesiones (workspace_id, updated_at desc);

comment on table offer_sesiones is
  'Conversaciones de la tab Offer: lo que el dueño contó, lo que MaKo sabe de cada pieza de la oferta, los documentos leídos (texto, no binario), el diagnóstico en curso y las versiones de la conclusión. Ver lib/offer-sesiones.ts y docs/offer-marco.md.';

-- RLS prendido y SIN políticas: sólo el servidor (service_role) la lee. El revoke explícito porque que
-- el grant llegue o no depende de quién aplique el DDL (AGENTS.md, «una VISTA no tiene RLS…»).
alter table offer_sesiones enable row level security;
revoke all on offer_sesiones from anon, authenticated;

commit;
