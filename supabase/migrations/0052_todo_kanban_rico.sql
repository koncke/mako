-- =============================================================================
-- 0052_todo_kanban_rico — el To-do pasa a un tablero kanban completo
-- =============================================================================
-- El tablero /todo (sacado de /experimentos a su propia ruta) suma, sobre las
-- columnas de estado (por_hacer|en_curso|hecho) y la prioridad ya existentes:
--   • progreso  (0-100)  — slider de avance por tarjeta
--   • deadline  (date)   — con coloreo de urgencia en la UI
--   • categorias (jsonb) — array de ids de categoría (multi, con color)
-- y una tabla de categorías reutilizable. Modelado sobre el kanban de Martín
-- (/martinkoncke).
-- =============================================================================

begin;

alter table experimento_tareas
  add column if not exists progreso  integer not null default 0,
  add column if not exists deadline  date,
  add column if not exists categorias jsonb not null default '[]'::jsonb;

create table if not exists tarea_categorias (
  id         bigint generated by default as identity primary key,
  nombre     text not null default '',
  color      text not null default '#9b9ba2',
  created_at timestamptz not null default now()
);

comment on table tarea_categorias is
  'Categorías (etiquetas con color) del tablero To-do (/todo). Referenciadas por experimento_tareas.categorias (array de ids).';

alter table tarea_categorias enable row level security;

commit;
