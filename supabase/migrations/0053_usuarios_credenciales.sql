-- =============================================================================
-- 0053 — usuarios + credenciales: cuentas con rol y tokens de integraciones
-- =============================================================================
-- Hasta acá el acceso era una contraseña compartida (cookie mako_auth) y TODOS
-- los tokens de servicios vivían en env vars de Vercel: agregar a alguien o
-- rotar un token pedía tocar el deploy. Este par de tablas invierte eso:
--
--   · usuarios      — quién puede entrar y con qué rol. El login con Google
--                     resuelve el email contra esta tabla; 'admin' ve /admin y
--                     gestiona cuentas, 'usuario' usa el dashboard normal.
--                     Bootstrap: los emails de AUTH_ALLOWED_EMAILS se auto-crean
--                     como admin en su primer login (los dueños actuales).
--   · credenciales  — tokens de integraciones cargados desde la UI (/metodo),
--                     cifrados con AES-256-GCM en el server (nunca llegan en
--                     claro a la base). Al arrancar cada instancia,
--                     instrumentation.ts los hidrata a process.env SOLO si la
--                     env no está seteada en Vercel (la env del server gana).
--
-- RLS on sin políticas = solo server-side (service_role), igual que el resto.
-- Seguro de re-ejecutar.
-- =============================================================================

begin;

create table if not exists usuarios (
  id            bigint generated by default as identity primary key,
  email         text not null unique,              -- siempre lowercase
  nombre        text not null default '',
  rol           text not null default 'usuario',   -- admin | usuario
  estado        text not null default 'invitado',  -- invitado | activo | suspendido
  foto_url      text,                              -- avatar de Google (si vino)
  invitado_por  text,                              -- email del admin que lo agregó
  ultimo_login  timestamptz,
  created_at    timestamptz not null default now(),
  updated_at    timestamptz not null default now()
);

comment on table usuarios is
  'Cuentas del dashboard: quién entra (login con Google) y con qué rol. invitado = agregado desde /admin pero nunca entró; activo = ya hizo login; suspendido = bloqueado.';

create index if not exists idx_usuarios_email on usuarios (email);

create table if not exists credenciales (
  clave       text primary key,                    -- nombre de la env var (ej. META_ACCESS_TOKEN)
  valor_enc   text not null,                       -- AES-256-GCM: gcm1.<iv>.<tag>.<cipher> en base64url
  servicio    text not null,                       -- key del catálogo (meta, chatwoot, resend…)
  updated_by  text,                                -- email de quien la guardó
  updated_at  timestamptz not null default now()
);

comment on table credenciales is
  'Tokens de integraciones cargados desde /metodo, cifrados app-side. Se hidratan a process.env al arrancar el server si la env correspondiente no existe en Vercel.';

alter table usuarios enable row level security;
alter table credenciales enable row level security;

commit;
