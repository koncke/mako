-- =============================================================================
-- 0277_admin_decisiones — el tablero de decisiones del super admin (/admin/runway)
-- =============================================================================
-- Pedido de Martín (14/10/2026): /admin/runway pasa a ser «el tablero donde él contesta
-- las decisiones de todos los chats». Cada chat junta preguntas, el chat «Estrategia 3
-- cuentas» las publica acá (scripts/decisiones.ts) y Martín las contesta desde la pantalla,
-- muchas veces desde el teléfono. Una fila = una decisión.
--
-- ⚠️ SIN workspace_id, a propósito: no es un dato de ningún cliente sino de la plataforma,
-- y sólo la lee y la escribe el super admin (getSesionAdmin + service role). No va a
-- TENANT_TABLES.
-- ⚠️ ORDEN DE DESPLIEGUE: AGREGA una tabla que el código nuevo YA LEE → se aplica ANTES o
-- junto con el deploy. Sin la tabla, la pantalla dice que falta y no se cae.
-- ⚠️ Dos escritores con dos ritmos (el script que publica, la pantalla que contesta): por eso
-- es una tabla y no un JSON en app_settings. Republicar una decisión (mismo `ref`) actualiza
-- la pregunta y NO toca la respuesta.

begin;

create table if not exists admin_decisiones (
  id               bigint generated by default as identity primary key,
  -- La clave estable con la que el chat la publica: republicar con el mismo ref no duplica.
  ref              text not null unique,
  -- De qué chat / área viene («Image Editor», «Customer Success»…).
  chat             text not null,
  -- La pregunta en una línea, en palabras de producto.
  pregunta         text not null,
  -- [{ "clave": "A", "texto": "Sí, ya está hecho" }, …]. Vacío = se contesta con texto libre.
  opciones         jsonb not null default '[]'::jsonb,
  -- Qué se destraba si la contesta: lo que la hace priorizar.
  destraba         text,
  -- Un renglón de contexto arriba de la pregunta.
  contexto         text,
  -- La opción que recomienda el chat que pregunta (una clave de opciones), si recomienda una.
  recomendada      text,
  -- 'bloquea' (un chat parado) · 'cuesta' (dinero o clientes ahora) · 'criterio' (sin apuro)
  -- · 'aviso' (no es una decisión: algo que hay que saber; se marca leído).
  urgencia         text not null default 'criterio' check (urgencia in ('bloquea', 'cuesta', 'criterio', 'aviso')),
  -- Un link para mirar antes de contestar (un borrador, una pantalla).
  href             text,
  -- Desempate dentro de la misma urgencia: más bajo, más arriba.
  orden            integer not null default 100,
  -- La respuesta: la clave elegida, u 'otra' con su texto.
  respuesta        text,
  respuesta_texto  text,
  respondida_at    timestamptz,
  -- El chat ya leyó la respuesta y la tiene: deja de ser «nueva» para quien publica.
  recogida_at      timestamptz,
  -- Retirada por quien la publicó (ya no hace falta): no se dibuja.
  archivada_at     timestamptz,
  creada_at        timestamptz not null default now()
);

create index if not exists idx_admin_decisiones_abiertas on admin_decisiones (urgencia, orden) where archivada_at is null;

comment on table admin_decisiones is 'Decisiones que los chats le piden a Martín; se contestan en /admin/runway. Sólo super admin.';

-- RLS prendido y sin políticas = sólo el server con service_role. Y el revoke explícito,
-- porque que el grant llegue o no depende de quién aplique el DDL (AGENTS.md).
alter table admin_decisiones enable row level security;
revoke all on admin_decisiones from anon, authenticated;

commit;
