-- =============================================================================
-- 0072_evolution_instancias — WhatsApp NO oficial (Evolution API) por workspace
-- =============================================================================
-- Cuenta única de MaKo en Evolution (env EVOLUTION_*), UNA instancia por
-- workspace (instance_name = 'mako_ws<id>'). Esta tabla mapea instancia ↔
-- workspace (para que el webhook, que llega sin sesión, sepa de quién es cada
-- evento) y cachea el estado de conexión. El QR NO se persiste: es efímero y se
-- pide en vivo a Evolution al conectar/refrescar.
--
-- Reglas del PDF de Martín: el número de empresa va por acá (no oficial, QR);
-- a leads calientes la app NUNCA dispara automático (eso lo maneja F2.3 con una
-- cola de borradores). RLS on sin políticas = solo server-side, igual que todo.

begin;

create table if not exists evolution_instancias (
  id                 bigint generated by default as identity primary key,
  workspace_id       bigint not null default 1 references workspaces(id) on delete cascade,
  instance_name      text not null unique,               -- 'mako_ws<id>' (único en Evolution)
  instance_id        text,                                -- UUID que devuelve Evolution
  estado             text not null default 'desconectado', -- desconectado|conectando|conectado|error
  numero             text,                                -- JID/número conectado (una vez logueado)
  perfil_nombre      text,                                -- nombre del perfil de WhatsApp conectado
  ultima_conexion_at timestamptz,
  ultimo_evento_at   timestamptz,                          -- último webhook recibido
  created_at         timestamptz not null default now(),
  updated_at         timestamptz not null default now(),
  unique (workspace_id)                                    -- una instancia no-oficial por workspace
);

create index if not exists idx_evolution_instancias_ws on evolution_instancias (workspace_id);

comment on table evolution_instancias is
  'WhatsApp no oficial (Evolution API): una instancia por workspace. Mapea instancia↔workspace para el webhook y cachea el estado de conexión.';

alter table evolution_instancias enable row level security;

commit;
