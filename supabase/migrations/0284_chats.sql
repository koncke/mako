-- =============================================================================
-- 0284 — La tab Chats (14/10/2026): el estado de cada conversación, lo que leyó cada persona y sus eventos
-- =============================================================================
-- ⚠️ ORDEN DE DESPLIEGUE: ANTES o JUNTO con el deploy que trae /chats. El código nuevo la LEE: sin ella la
-- lista se dibuja igual (todas abiertas, todo «sin leer» lo que el contacto escribió último) y avisa la falla
-- de la fuente (`fallas: ['estado', 'leidos']`) en vez de afirmar que no hay nada cerrado; cerrar, posponer y
-- marcar leído contestan el error. Agrega y no saca nada: la versión desplegada no la nombra, así que
-- aplicarla antes no le molesta a nadie.
--
-- Pedido de Martín (14/10/2026), literal: «Implementar la tab "Chats" algo como "https://respond.io" para tener
-- en UNA sola tab centralizado absolutamente todos los chats, WhatsApp, Instagram, Messenger, etc...». El plano
-- es docs/diseno-chats.md (§2.5).
--
-- La conversación de la lista es un CONTACTO, no un canal (el modelo de respond.io): su `clave` es `lead:<id>`
-- si tiene lead, y si no `wa:<linea>:<tel10 o jid>`, `ig:<id>` o `fb:<id>` (lib/chats-reglas.ts arma y valida
-- las claves). Las conversaciones NO se copian acá: los mensajes siguen viviendo en `wa_mensajes` e
-- `ig_mensajes`. Acá vive sólo lo que respond.io agrega encima y que ninguna tabla tenía:
--
--   · `chat_estado`: abierta / cerrada (con quién, cuándo y la nota de cierre) y pospuesta hasta cuándo. Una
--     POSPUESTA se guarda como 'abierta' + `pospuesta_hasta`: el estado que se VE lo calcula `estadoEfectivo`
--     al leer (una cerrada se reabre sola si el contacto escribe después de `cerrada_at`; una pospuesta vuelve
--     al vencer o si el contacto escribe después de `pospuesta_at`). Nada escribe en el webhook.
--   · `chat_leidos`: hasta cuándo leyó CADA PERSONA cada conversación. En el servidor y por usuario (la bandeja
--     vieja lo guardaba en el navegador: no se compartía entre dispositivos y mezclaba workspaces).
--   · `chat_eventos`: «Cerrada por Martín», «Pospuesta hasta…». El actor es el NOMBRE de quien lo hizo.
--
-- ⚠️ La asignación NO vive acá: el asignado es `leads.setter` (decisión 2 del plano: una cosa, un lugar; el CRM
-- ya lo tiene y lo ve igual). Las notas tampoco: un comentario es una nota del lead (`lead_audit`, campo 'Nota').
--
-- ⚠️ La clave de un contacto sin lead CAMBIA cuando se agrega al CRM (pasa a `lead:<id>`): su estado y su marca
-- de leído quedan en la clave vieja. Aceptado y documentado en el plano.
--
--   · `usuario_id` es `usuarios.id` (bigint, mig 0053), el `sub` numérico de la sesión. Una sesión sin fila
--     (legacy / dev / contraseña maestra) no marca leído: el código no escribe (no hay a quién atarlo).
--   · SIN `default 1` en `workspace_id`, a propósito (como la 0271): el 1 es un cliente (Mauricio).
--     `getTenantDb` estampa el workspace al insertar; una fila sin él es un error, no del ws 1.
--   · Las tres van en TENANT_TABLES (lib/workspace.ts) y en TABLAS_DE_INQUILINO (lib/tablas-de-inquilino.ts).
--
-- RLS prendida sin políticas y `revoke` explícito: el servidor lee y escribe con service_role (getTenantDb).

begin;

create table if not exists chat_estado (
  workspace_id     bigint not null references workspaces(id) on delete cascade,
  clave            text not null check (char_length(clave) between 1 and 200),
  estado           text not null default 'abierta',
  cerrada_at       timestamptz,
  cerrada_por      text,
  nota_cierre      text check (nota_cierre is null or char_length(nota_cierre) <= 2000),
  pospuesta_hasta  timestamptz,
  pospuesta_at     timestamptz,
  updated_at       timestamptz not null default now(),
  primary key (workspace_id, clave),
  constraint chat_estado_estado_ok check (estado in ('abierta', 'cerrada'))
);

comment on table chat_estado is 'Tab Chats: abierta/cerrada/pospuesta de cada conversación (clave = lead:<id> | wa:<linea>:<id> | ig:<id> | fb:<id>). El estado que se ve lo calcula estadoEfectivo (lib/chats-reglas.ts) al leer.';

create table if not exists chat_leidos (
  workspace_id  bigint not null references workspaces(id) on delete cascade,
  usuario_id    bigint not null references usuarios(id) on delete cascade,
  clave         text not null check (char_length(clave) between 1 and 200),
  leido_at      timestamptz not null default now(),
  primary key (workspace_id, usuario_id, clave)
);

-- El borrado de un usuario cascadea por acá: sin índice por usuario, recorre la tabla entera.
create index if not exists idx_chat_leidos_usuario on chat_leidos (usuario_id);

comment on table chat_leidos is 'Tab Chats: hasta cuándo leyó cada persona cada conversación (no leído por persona, en el servidor).';

create table if not exists chat_eventos (
  id            bigint generated by default as identity primary key,
  workspace_id  bigint not null references workspaces(id) on delete cascade,
  clave         text not null check (char_length(clave) between 1 and 200),
  tipo          text not null,
  actor         text check (actor is null or char_length(actor) <= 200),
  detalle       jsonb not null default '{}'::jsonb,
  created_at    timestamptz not null default now(),
  constraint chat_eventos_tipo_ok check (tipo in ('cerrada', 'reabierta', 'pospuesta', 'reanudada'))
);

create index if not exists idx_chat_eventos_clave on chat_eventos (workspace_id, clave, created_at);

comment on table chat_eventos is 'Tab Chats: los eventos del hilo (cerrada, reabierta, pospuesta, reanudada) con el nombre de quien lo hizo.';

alter table chat_estado enable row level security;
alter table chat_leidos enable row level security;
alter table chat_eventos enable row level security;
revoke all on chat_estado from anon, authenticated;
revoke all on chat_leidos from anon, authenticated;
revoke all on chat_eventos from anon, authenticated;

commit;
