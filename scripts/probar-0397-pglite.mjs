// =============================================================================
// probar-0397-pglite — el libro de recibos (mig 0397) contra un Postgres DE VERDAD, sin tocar la base de nadie
// =============================================================================
// `emitir_recibo` decide el número, la llave y los totales en SQL: un test que lee el .sql con regex no prueba que ande. Esto
// levanta un Postgres en memoria (PGlite) con un esquema chico con las formas del real (workspaces, cobros, pagos) y le aplica
// la 0397 entera. Molde: scripts/probar-0340-pglite.mjs.
//
// PGlite NO es dependencia del repo. Una vez, en una carpeta vacía:
//   npm i @electric-sql/pglite@0.2.17
// y después, desde la raíz del repo:
//   PGLITE=<esa carpeta> node scripts/probar-0397-pglite.mjs supabase/migrations/0397_recibos.sql
// Sale con 1 si algún caso falla.
//
// ⚠️ LO QUE NO PRUEBA: dos emisiones A LA VEZ. PGlite es una sola conexión, así que el candado (`for update` sobre la numeración)
// no se puede ejercitar acá. Eso se prueba en producción con dos conexiones y rollback, justo después de aplicar
// (docs/relevo/nube-recibos.md, «Qué mirar al aplicar»).
//
// Medido el 5/11/2026 en la nube: los casos de abajo en verde; y cada una de estas roturas de la 0397 da rojo (al menos un
// caso): sin comparar los pagos de una clave ya usada (el agujero del segundo pago del mes), sin comparar en la búsqueda por
// pago, sin el candado de número forzado ≤ ultimo, sin calcular los totales por moneda, sin el `no_va` de un devuelto, y la
// red mirando sólo los recibos no anulados.
// =============================================================================

import fs from 'node:fs';
import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
import { join } from 'node:path';
import { pathToFileURL } from 'node:url';

if (!process.env.PGLITE) { console.error('Falta PGLITE=<carpeta donde instalaste @electric-sql/pglite> (ver la cabecera).'); process.exit(2); }
const { PGlite } = await import(pathToFileURL(createRequire(join(process.env.PGLITE, 'x.js')).resolve('@electric-sql/pglite')).href);

const migracion = fs.readFileSync(process.argv[2] ?? 'supabase/migrations/0397_recibos.sql', 'utf8')
  // `notify` no existe en PGlite; el resto, tal cual.
  .replace(/^notify pgrst.*$/m, '');

const ESQUEMA = `
create role anon; create role authenticated; create role service_role;
create table workspaces (id bigserial primary key, nombre text);
create table cobros (
  id bigint generated by default as identity primary key, workspace_id bigint not null references workspaces(id),
  proveedor text not null, modo text not null default 'real', estado text not null, proveedor_pago_id text,
  pagado_at timestamptz, updated_at timestamptz not null default now()
);
create table pagos (
  id bigint generated by default as identity primary key, workspace_id bigint, lead_id bigint, cobro_id bigint references cobros(id),
  proveedor text, proveedor_pago_id text, pagado boolean not null default false, created_at timestamptz not null default now()
);
insert into workspaces (id, nombre) values (9, 'MaKo'), (13, 'Codigo Inmobiliario'), (1, 'Un cliente');
`;

const pago = (referencia, o = {}) => ({ medio: 'binance', referencia, fecha: '2026-11-04T22:42:23-03:00', monto: 94, moneda: 'USDT', ...o });
const base = (clave, pagos, o = {}) => ({
  clave, origen: 'manual', paga: 'manual', destino_ws: 13, a_nombre: 'Código Inmobiliario', emitido_por: 'prueba', zona: 'America/Argentina/Buenos_Aires',
  fecha_pago: '2026-11-05T12:20:19-03:00', emisor: { nombre: 'MaKo' },
  lineas: [{ concepto: 'Plan Pro', mes: 'noviembre', monto: 97, moneda: 'USD' }], pagos, ...o,
});

const fallos = [];
async function caso(nombre, fn) {
  try { await fn(); console.log(`✓ ${nombre}`); } catch (e) { fallos.push(nombre); console.log(`✗ ${nombre}\n   ${e instanceof Error ? e.message : String(e)}`); }
}

const db = new PGlite();
await db.exec(ESQUEMA);
await db.exec(migracion);

const emitir = async (p) => (await db.query('select * from emitir_recibo($1::jsonb)', [JSON.stringify(p)])).rows[0];
const tira = async (p, marca) => {
  let msg = null;
  try { await emitir(p); } catch (e) { msg = e instanceof Error ? e.message : String(e); }
  assert.ok(msg, 'tenía que tirar y no tiró');
  assert.match(msg, marca);
  return msg;
};
const ultimo = async () => Number((await db.query('select ultimo from recibos_numeracion')).rows[0].ultimo);

await caso('nace en 2 y el primero que emite es el 0003', async () => {
  assert.equal(await ultimo(), 2);
  const r = await emitir(base('form:a', [pago('463869660353134592')]));
  assert.equal(Number(r.numero), 3);
  assert.equal(r.ya_estaba, false);
  assert.equal(await ultimo(), 3);
});

await caso('la misma clave con el mismo pago es «ya estaba» y no gasta número', async () => {
  const r = await emitir(base('form:a', [pago('463869660353134592')]));
  assert.equal(Number(r.numero), 3);
  assert.equal(r.ya_estaba, true);
  assert.equal(await ultimo(), 3);
});

await caso('la misma clave con un pago NUEVO tira nombrando el número y la orden (no se traga el segundo pago)', async () => {
  const m = await tira(base('form:a', [pago('463869660353134592'), pago('463975050149208064', { monto: 144 })]), /RECIBO_OCUPADO 3 463975050149208064/);
  assert.ok(m);
  assert.equal(await ultimo(), 3);
});

await caso('otra clave con un pago que ya está es «ya estaba» de ESE recibo', async () => {
  const r = await emitir(base('pago:binance:463869660353134592', [pago('463869660353134592')]));
  assert.equal(Number(r.numero), 3);
  assert.equal(r.ya_estaba, true);
});

await caso('otra clave con un pago usado y otro nuevo tira nombrando la orden usada', async () => {
  await tira(base('form:b', [pago('999'), pago('463869660353134592')]), /RECIBO_OCUPADO 3 463869660353134592/);
  assert.equal(await ultimo(), 3);
});

await caso('el mismo pago dos veces en un pedido no entra', async () => {
  await tira(base('form:c', [pago('1'), pago('1')]), /RECIBO_INVALIDO/);
});

await caso('un número forzado sólo si ya se gastó y está libre (0001 sí; 0001 otra vez y 0009 no)', async () => {
  const r = await emitir({ ...base('mensualidad:13:2026-10', [pago('461213098188603392', { monto: 146 })]), numero: 1 });
  assert.equal(Number(r.numero), 1);
  assert.equal(await ultimo(), 3);
  await tira({ ...base('mensualidad:13:2026-09', [pago('77')]), numero: 1 }, /RECIBO_INVALIDO el número 1/);
  await tira({ ...base('mensualidad:13:2026-08', [pago('78')]), numero: 9 }, /RECIBO_INVALIDO el número 9/);
});

await caso('los totales los calcula la base: dos pagos en USDT suman 238', async () => {
  const r = await emitir(base('form:d', [pago('11'), pago('12', { monto: 144 })]));
  const f = (await db.query('select total_recibido, moneda_recibido, totales_recibido, total_detalle, moneda_detalle from recibos where id = $1', [r.recibo_id])).rows[0];
  assert.equal(Number(f.total_recibido), 238);
  assert.equal(f.moneda_recibido, 'USDT');
  assert.equal(Number(f.total_detalle), 97);
  assert.equal(f.moneda_detalle, 'USD');
});

await caso('pagos en dos monedas: un total por moneda y ningún total suelto', async () => {
  const r = await emitir(base('form:e', [pago('21', { monto: 100 }), pago('22', { medio: 'transferencia', monto: 50, moneda: 'USD' })]));
  const f = (await db.query('select total_recibido, moneda_recibido, totales_recibido from recibos where id = $1', [r.recibo_id])).rows[0];
  assert.equal(f.total_recibido, null);
  assert.equal(f.moneda_recibido, null);
  assert.deepEqual(f.totales_recibido.map((t) => [t.moneda, Number(t.monto)]), [['USD', 50], ['USDT', 100]]);
});

await caso('renglones en dos monedas no entran', async () => {
  await tira(base('form:f', [pago('31')], { lineas: [{ concepto: 'a', monto: 1, moneda: 'USD' }, { concepto: 'b', monto: 1, moneda: 'ARS' }] }), /RECIBO_INVALIDO los renglones/);
});

await caso('un recibo que nace devuelto no manda nada (correo y WhatsApp en no_va)', async () => {
  const r = await emitir({ ...base('pago:mercadopago:555', [pago('555', { medio: 'mercadopago', moneda: 'ARS', monto: 73555 })], { origen: 'pasarela', paga: 'solo' }), estado: 'devuelto' });
  const f = (await db.query('select estado, correo_estado, wa_estado, devuelto_at from recibos where id = $1', [r.recibo_id])).rows[0];
  assert.equal(f.estado, 'devuelto');
  assert.equal(f.correo_estado, 'no_va');
  assert.equal(f.wa_estado, 'no_va');
  assert.ok(f.devuelto_at);
});

await caso('un comprobante fuera de plataforma/recibos/ no entra', async () => {
  let msg = null;
  try { await emitir(base('form:g', [pago('41', { comprobante_path: '13/contratos/x.png' })])); } catch (e) { msg = String(e); }
  assert.match(msg ?? '', /comprobante_path|check/i);
});

await caso('anular libera la clave y la orden: se corrige emitiendo otro, con número nuevo', async () => {
  const antes = await ultimo();
  const r = await emitir(base('form:h', [pago('51')]));
  await db.query(`update recibos set estado = 'anulado' where id = $1`, [r.recibo_id]);
  await db.query('update recibo_pagos set anulado = true where recibo_id = $1', [r.recibo_id]);
  const otro = await emitir(base('form:h', [pago('51')]));
  assert.equal(otro.ya_estaba, false);
  assert.equal(Number(otro.numero), antes + 2);
});

await caso('la red ve el cobro pagado y la renovación sin recibo, y deja de verlos al emitir', async () => {
  await db.query(`insert into cobros (id, workspace_id, proveedor, modo, estado, proveedor_pago_id, pagado_at) values
    (100, 9, 'creem', 'real', 'pagado', 'tran_1', now()),
    (101, 9, 'creem', 'prueba', 'pagado', 'tran_p', now()),
    (102, 1, 'stripe', 'real', 'pagado', 'pi_ajeno', now()),
    (103, 9, 'mercadopago', 'real', 'reembolsado', '777', now())`);
  await db.query(`insert into pagos (workspace_id, cobro_id, proveedor, proveedor_pago_id, pagado) values
    (9, 100, 'creem', 'tran_1', true), (9, 100, 'creem', 'tran_2', true), (9, 103, 'mercadopago', '778', false)`);
  const ver = async () => (await db.query(`select * from recibos_que_faltan(9, now() - interval '1 day', 50)`)).rows
    .map((x) => `${x.proveedor}:${x.proveedor_pago_id}:${x.devuelto}`).sort();
  assert.deepEqual(await ver(), ['creem:tran_1:false', 'creem:tran_2:false', 'mercadopago:777:true', 'mercadopago:778:true']);
  await emitir(base('pago:creem:tran_1', [pago('tran_1', { medio: 'creem', moneda: 'USD', monto: 47 })], { origen: 'pasarela', paga: 'solo' }));
  assert.deepEqual(await ver(), ['creem:tran_2:false', 'mercadopago:777:true', 'mercadopago:778:true']);
});

await caso('la red no vuelve a emitir lo que una persona anuló', async () => {
  const r = await emitir(base('pago:creem:tran_2', [pago('tran_2', { medio: 'creem', moneda: 'USD', monto: 47 })], { origen: 'pasarela', paga: 'solo' }));
  await db.query(`update recibos set estado = 'anulado' where id = $1`, [r.recibo_id]);
  await db.query('update recibo_pagos set anulado = true where recibo_id = $1', [r.recibo_id]);
  const filas = (await db.query(`select proveedor_pago_id from recibos_que_faltan(9, now() - interval '1 day', 50)`)).rows.map((x) => x.proveedor_pago_id);
  assert.ok(!filas.includes('tran_2'), `volvió a aparecer: ${filas.join(', ')}`);
});

await caso('la función queda cerrada a la clave pública', async () => {
  const f = (await db.query(`select has_function_privilege('anon', 'public.emitir_recibo(jsonb)', 'execute') as anon,
    has_function_privilege('service_role', 'public.emitir_recibo(jsonb)', 'execute') as sr`)).rows[0];
  assert.equal(f.anon, false);
  assert.equal(f.sr, true);
});

console.log(fallos.length ? `\n${fallos.length} caso(s) en rojo.` : '\nTodo en verde.');
process.exit(fallos.length ? 1 : 0);
