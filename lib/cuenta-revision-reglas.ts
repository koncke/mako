/**
 * El negocio de la cuenta de revisión. PROPIO y fuera de `WS_PRUEBAS` (4/11/2026): el negocio de prueba (ws 3) no es un lugar fijo.
 * «Datos de Mau» (app/api/datos-mau) copia ahí datos de un cliente real, «simular» y el Reset escriben ahí, y cualquiera con la
 * contraseña los habría visto. Éste no lo toca ninguna herramienta de prueba.
 *
 * ⚠️ EL ID ES EXPLÍCITO Y ALTO a propósito: lo crea `scripts/tiendas-cuenta-revision.mts` con este número (`workspaces.id` es
 * «generated by default as identity», acepta un id explícito). La secuencia va por las decenas y nunca llega acá.
 * ⚠️ Y NO HAY VARIABLE DE ENTORNO QUE LO CAMBIE: mover la cuenta es un cambio de código que pasa por una revisión.
 */
export const WS_REVISION = 900_001;

/**
 * La ÚNICA cuenta que entra sin segundo factor.
 *
 * ⚠️ EN POSITIVO Y ATADA A LO QUE DICE LA FILA: ESE correo (exacto), SU negocio, un usuario común y CLOSER adentro del negocio. Cambiar
 * cualquiera de esas cosas apaga la excepción en el pedido siguiente (lib/auth.ts). El correo no es de una persona: nadie recibe nada.
 * ⚠️ CLOSER Y NO ADMIN: con admin invitaba gente, creaba tokens, renombraba el negocio y mandaba mails de MaKo (revisión del 3/11).
 * `rol_ws` nulo vale como admin (lib/workspace.ts), así que tampoco entra.
 */
export const CUENTA_DE_REVISION = { email: 'revision-tiendas@hola-mako.com', ws: WS_REVISION, rolWs: 'closer' } as const;

/**
 * ¿Es ESTE correo? Comparación EXACTA (`===`, 4/11/2026): con `toLowerCase()`, una fila con `revision-tiendas@hola-maKo.com` pasaba,
 * y la fila la escribe cualquiera con acceso a /admin. El script la crea con este texto y nadie más la toca.
 */
export function esCorreoDeRevision(email: unknown): boolean {
  return email === CUENTA_DE_REVISION.email;
}

export function esCuentaDeRevision(u: { email?: string | null; workspace_id?: number | null; rol?: string | null; rol_ws?: string | null } | null | undefined): boolean {
  if (!u) return false;
  return esCorreoDeRevision(u.email)
    && u.workspace_id === CUENTA_DE_REVISION.ws
    && u.rol === 'usuario'
    && u.rol_ws === CUENTA_DE_REVISION.rolWs;
}

/** El nombre de su negocio. Lo pone scripts/tiendas-cuenta-revision.mts al crearlo, y el de revertir no borra un 900001 que se llame distinto. */
export const NOMBRE_NEGOCIO_REVISION = 'Negocio de demostración';

/** Una semana: el revisor vuelve a entrar con la misma contraseña, y una cookie copiada se muere sola. */
export const DIAS_SESION_REVISION = 7;

/**
 * La sesión vale si es posterior al último cambio de contraseña: rotarla tiene que cerrar lo que estaba abierto. Sin fecha que comparar,
 * no vale: es la única sesión sin segundo factor, y un «no sé» acá no puede ser un sí.
 */
export function sesionDeRevisionVigente(iatSegundos: number | null | undefined, cambiadaAt: string | null | undefined): boolean {
  const cambio = Date.parse(String(cambiadaAt ?? ''));
  return typeof iatSegundos === 'number' && Number.isFinite(cambio) && iatSegundos * 1000 >= cambio - 1000;
}

