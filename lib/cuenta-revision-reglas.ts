//
// Lo usan: proxy.ts (qué escribe), lib/auth.ts (la sesión), app/api/auth/contrasena (la entrada), lib/revision-guarda.ts (los envíos),
// lib/tickets-db.ts (sin despacho), scripts/tiendas-cuenta-revision.mts y los tests. Vive aparte y sin `server-only` para que un test
