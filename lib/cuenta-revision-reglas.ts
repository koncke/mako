// ── Su negocio, limpio: lo que se mide antes de dar la sesión (4/11/2026) ──────────────────────────────────────────────

/** Lo que tiene que estar en CERO para que un tercero entre. `null` = no se pudo contar, y eso no es cero. */
export type ConteosNegocioDeRevision = { lineas: number | null; credenciales: number | null; cartera: number | null };

/**
 * ¿Se le da la sesión? Sin líneas de WhatsApp (le escribiría a gente real), sin credenciales (una key de un cliente, su Meta, su Resend)
 * y sin cartera de agencia (entraría a otro negocio). Fail-closed: lo que no se pudo contar, no entra.
 */
export function negocioDeRevisionLimpio(c: ConteosNegocioDeRevision): { limpio: true } | { limpio: false; falta: string[] } {
  const falta: string[] = [];
  if (c.lineas !== 0) falta.push(c.lineas == null ? 'no pude contar las líneas de WhatsApp' : `${c.lineas} línea(s) de WhatsApp`);
  if (c.credenciales !== 0) falta.push(c.credenciales == null ? 'no pude contar las credenciales' : `${c.credenciales} credencial(es)`);
  if (c.cartera !== 0) falta.push(c.cartera == null ? 'no pude contar la cartera de agencia' : `${c.cartera} cliente(s) de agencia`);
  return falta.length ? { limpio: false, falta } : { limpio: true };
}

/** El dominio de los correos de los leads de ejemplo (RFC 2606: reservado, nunca es de nadie). */
export const DOMINIO_DE_EJEMPLO = 'example.com';

/** ¿Es un lead que cargó el script? Sólo con correo @example.com: uno sin correo, o con otro, puede ser una persona de verdad. */
export function esCorreoDeEjemplo(email: unknown): boolean {
  return typeof email === 'string' && /^[^@\s]+@example\.com$/i.test(email.trim());
}
