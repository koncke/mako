const SOLO_LEE = new Set(['GET', 'HEAD', 'OPTIONS']);

/**
 * ¿Esta sesión de revisión puede hacer este pedido? Leer siempre; escribir, sólo lo de la lista. Un pedido con `next-action` nunca, con el
 * método que sea: Next sólo corre una acción por POST, pero el corte no depende de que eso no cambie (como el del alumno, lib/rutas-publicas.ts).
 */
export function revisionPuedeEscribir(pathname: string, metodo: string, conAccion = false): boolean {
  if (conAccion) return false;
  if (SOLO_LEE.has(metodo.toUpperCase())) return true;
  const ruta = pathname.length > 1 ? pathname.replace(/\/+$/, '') : pathname;
  return Object.prototype.hasOwnProperty.call(PERMITIDO_EN_REVISION, ruta);
}

// ── Lo que le llega a un TERCERO: la guarda en el punto de envío (4/11/2026) ───────────────────────────────────────────

/**
 * ¿Sale este envío? En revisión, sólo un correo a la casilla del equipo (`emailEquipo`): todo lo demás (un mail a otra persona, un
 * WhatsApp a quien sea) no sale. La lista del proxy corta por dónde ENTRA el pedido; esto corta por dónde SALE, y cubre lo que la
 * lista no ve (una acción de MaKo, un flujo, un camino que todavía no existe).
 */
export function envioPermitidoEnRevision(canal: 'email' | 'whatsapp', destinos: string | readonly string[], emailEquipo: string): boolean {
  if (canal !== 'email') return false;
  const lista = (Array.isArray(destinos) ? destinos : [destinos]) as readonly string[];
  const equipo = emailEquipo.trim().toLowerCase();
  return lista.length > 0 && !!equipo && lista.every((d) => typeof d === 'string' && d.trim().toLowerCase() === equipo);
}

